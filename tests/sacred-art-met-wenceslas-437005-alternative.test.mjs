import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const root='../data/artwork/research/';
const read=p=>JSON.parse(readFileSync(new URL(root+p,import.meta.url),'utf8'));
const m=read('m2m-met-437005-wenceslas-alternative-20261110.v1.json');
const q=read('m2m-consolidated-image-selection-queue-20261110.v1.json');
const c=m.candidate;
assert.equal(m.schema,'AO_SACRED_ART_MET_WENCESLAS_ALTERNATIVE_V1');
assert.equal(c.key,'Met:437005');
assert.equal(c.museumObjectId,437005);
assert.equal(c.museumAccession,'44.147.2');
assert.equal(c.originalBlockedWorkKey,'Olomouc:Skreta-WenceslasCycle');
assert.equal(c.officialMetadataApi,'https://collectionapi.metmuseum.org/public/collection/v1/objects/437005');
assert.equal(c.medium,'Oil and gold on spruce');
assert.equal(c.fidelity,'SAINT_PERSON_EXACT_DIFFERENT_NARRATIVE');
assert.match(c.visualStyle,/NON_BAROQUE_LOWER_AESTHETIC_PRIORITY/);
assert.equal(c.isExistingOwnerSelected,false);
assert.equal(c.globalRejectionMasterCrosscheckComplete,false);
assert.equal(c.notAlreadyIn151WorkResearchPool,true);
assert.equal(c.productionEligible,false);
assert.equal(c.ownerCalendarApproval,false);
assert.equal(c.sourceImageUrl,'https://images.metmuseum.org/CRDImages/ep/original/DP164825.jpg');
assert.equal(c.sourceImageBytesAcquired,true);
assert.equal(c.sourceImageSha256,'468b1255c8114607a665e38f81da679409166da76aa0f42cf82bc3c41c1c4608');
assert.equal(q.photographs.length,10);
assert.ok(q.works.some(x=>x.artworkKey==='Met:437005'&&x.releaseReady===false));
assert.equal(q.photographs.find(x=>x.artworkKey==='Met:437005').exactBytesSha256,c.sourceImageSha256);
assert.equal(q.counts.totalSelectionQueueWorkKeys,156);
assert.equal(q.counts.verifiedColourJpegExternalAlternate,2);
assert.equal(q.counts.newOwnerApprovedPlacements,0);
assert.ok(q.works.some(x=>x.artworkKey==='Olomouc:Skreta-WenceslasCycle'));
assert.equal(q.counts.newPublicArtworkReleases,0);
assert.equal(m.count.originalFocalWorksReplaced,0);
assert.equal(m.count.ownerApprovedCalendarPlacements,0);
console.log('PASS: museum accession 44.147.2 is a distinct research-only Wenceslas burial alternative and not a Škréta replacement.');
