import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const root = new URL("../data/pray/", import.meta.url);
const base = JSON.parse(readFileSync(new URL("prayer-corpus-ownership-foundation.v1.json",root),"utf8"));
const first = JSON.parse(readFileSync(new URL("prayer-corpus-external-discovery-wave02-icksp-firstpass.v1.json",root),"utf8"));
const second = JSON.parse(readFileSync(new URL("prayer-corpus-external-discovery-wave02-icksp-uk-fr-secondpass.v1.json",root),"utf8"));
assert.equal(base.records.length,94);
assert.equal(first.records.length,40);
assert.equal(second.records.length,76);
assert.equal(second.summary.combined_units_with_first_pass,116);
const ids=new Set(second.records.map(x=>x.lead_id));
assert.equal(ids.size,76);
const owned=new Set(base.records.map(x=>x.key));
const prior=new Set(first.records.map(x=>x.lead_id));
const valid=new Set([...ids,...prior,...owned]);
assert.ok(second.records.every(x=>!x.match_candidate||valid.has(x.match_candidate)));
assert.ok(second.records.every(x=>!x.part_of_source_program||ids.has(x.part_of_source_program)));
assert.ok(second.records.every(x=>x.source_url.startsWith("https://")));
assert.ok(second.records.every(x=>x.original_print_edition_verified===false&&x.source_rights_checked===false&&x.canonical_imported===false));
const evidence={SOURCE_TEXT_VISIBLE:0,PDF_PAGE_IMAGES_INSPECTED:0,SOURCE_FRAGMENT_ONLY:0,DOCUMENT_COVER_ONLY:0};
for(const x of second.records){assert.ok(Object.hasOwn(evidence,x.evidence_status)); evidence[x.evidence_status]++;}
assert.deepEqual(second.summary.by_evidence,evidence);
assert.equal(evidence.SOURCE_TEXT_VISIBLE,69);
assert.equal(evidence.PDF_PAGE_IMAGES_INSPECTED,3);
assert.equal(evidence.SOURCE_FRAGMENT_ONLY,2);
assert.equal(evidence.DOCUMENT_COVER_ONLY,2);
assert.equal(second.records.filter(x=>x.unit_kind==="STATION_COMPONENT").length,14);
assert.equal(second.records.filter(x=>x.unit_kind==="COLLECT_IN_RITUAL_PROGRAM").length,10);
assert.equal(second.summary.canonical_imports,0);
assert.equal(second.summary.original_print_certificates,0);
assert.equal(second.summary.unique_prayers_confirmed,0);
assert.equal(first.records.filter(x=>x.evidence==="INDEX_ONLY").length,2);
const matching=second.records.filter(x=>x.match_candidate&&owned.has(x.match_candidate)).length;
assert.equal(second.summary.direct_existing_owner_witnesses,matching);
console.log("Prayer corpus Wave 02b: 76 additional source units; combined 116; all anchors and evidence gates PASS");
