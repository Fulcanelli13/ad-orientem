import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {auditShrineSource,assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=load("data/geography/research/sacred-places-p36-nine-exact-churches.v1.json");
const g=load("data/geography/seed-registry.v1.json"),s=load("data/shrines/source-registry.v1.json");
const h=load("data/explore/heritage-place-reconciliation.review.v1.json");
const sh=load("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P36_NINE_EXACT_CHURCHES_V1");
assert.deepEqual(Object.values(m.baseline),[440,738,440,181,145,9]);
assert.deepEqual(Object.values(m.proposed),[449,747,449,190,145,9]);
assert.deepEqual([g.places.length,s.sources.length,h.place_crosswalk.length,h.exception_queues.places_without_direct_claim.length,g.geoAreas.length,g.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
assert.equal(h.counts.places,LIVE.places);
assert.equal(h.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(m.new_physical_locations,9);
assert.equal(m.published_new.length,9);
assert.equal(m.photo_assets_approved,0);
assert.equal(m.tlm_schedule_links_added,0);
assert.equal(new Set(m.published_new.map(r=>r.place_id)).size,9);
assert.equal(new Set(m.published_new.map(r=>r.geo_source_ref)).size,9);
const releaseIndex=RELEASES.findIndex(r=>r.id==="P36");
assert.ok(releaseIndex>0&&RELEASES[releaseIndex-1].id==="P35");
const previousReleaseIds=new Set(RELEASES.slice(0,releaseIndex).flatMap(r=>(r.data.published_new||[]).map(x=>x.place_id)));
const sourceMap=new Map(s.sources.map(x=>[x.id,x])),placeMap=new Map(g.places.map(x=>[x.place_id,x]));
assert.equal(placeMap.size,g.places.length);
assert.equal(sourceMap.size,s.sources.length);
const p36Ids=new Set(m.published_new.map(r=>r.place_id));
const p36Refs=new Set(m.published_new.map(r=>r.geo_source_ref));
const laterIds=new Set(RELEASES.slice(releaseIndex+1).flatMap(r=>(r.data.published_new||[]).map(x=>x.place_id)));
const existing=g.places.filter(x=>!p36Ids.has(x.place_id)&&!laterIds.has(x.place_id));
assert.equal(existing.length,440,"P36 approved historical 440-place predecessor is preserved");
assert.ok(existing.every(x=>!p36Refs.has(x.geo?.source_ref)));
for(const row of m.published_new){
 assert.ok(!previousReleaseIds.has(row.place_id));
 assert.match(row.geo_source_ref,/^osm:way:\d+$/);
 assert.equal(row.geo_source_url,"https://www.openstreetmap.org/way/"+row.geo_source_ref.split(":")[2]);
 const place=placeMap.get(row.place_id);assert.ok(place);
 assert.equal(place.name.official,row.name);
 assert.equal(place.address.country_code,row.country);
 assert.equal(place.place_type,row.place_type);
 assert.deepEqual(place.geo_area_ids,["geo:country:"+row.country]);
 assert.deepEqual([place.geo.lat,place.geo.lng],[row.lat,row.lng]);
 assert.equal(place.geo.source_ref,row.geo_source_ref);
 assert.equal(place.geo.source_url,row.geo_source_url);
 assert.equal(place.geo.matched_country_code,row.country);
 assert.equal(place.geo.geocoding_source,"OSM");
 assert.ok(isMapPublishablePlaceGeo(place.geo,row.country));
 assert.deepEqual(place.source_ids,row.source_ids);
 assert.equal(place.source_ids.length,1);
 const src=sourceMap.get(row.source_ids[0]);assert.ok(src);
 assert.equal(src.url,row.identity_source_url);
 assert.deepEqual(auditShrineSource(src),[]);
 assert.ok(h.place_crosswalk.some(x=>x.place_id===row.place_id&&Object.keys(x.record_ids).length===0));
 assert.ok(h.exception_queues.places_without_direct_claim.includes(row.place_id));
 assert.ok(!g.directoryPlaceLinks.some(x=>x.place_id===row.place_id));
 assert.ok(!sh.shrines.some(x=>x.place_id===row.place_id));
 for(const f of ["mass_times","hero_image","opening_hours","pilgrimage_schedule"])assert.equal(place[f],undefined);
}
assert.equal(m.held_scope.length,1);
const hold=m.held_scope[0];
assert.equal(hold.candidate_id,"SG-INV-0017");
assert.ok(g.places.some(p=>p.place_id==="place:FR:sanctuaire-sacre-coeur-paray"));
assert.ok(!g.places.some(p=>p.geo?.source_ref==="osm:way:121381927"),"Paray building not independently published while parent scope remains unsettled");
assert.equal(assertExploreGeographyRegistry(g).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...sh,sources:s.sources,places:g.places}).pass,true);
console.log("PASS P36: nine exact Catholic worship building features; parent sanctuary collision held; "+LIVE.places+" Places and "+LIVE.sources+" sources");
