import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const F=JSON.parse(readFileSync(new URL("../data/geography/research/mass-scripture-fortescue-order-extract-20261011.v1.json",import.meta.url),"utf8"));
const earlier=JSON.parse(readFileSync(new URL("../data/geography/research/mass-scripture-source-extractions-20261011.v1.json",import.meta.url),"utf8"));
const mainFormation=JSON.parse(readFileSync(new URL("../data/learn/mass-formation-campion.v1.json",import.meta.url),"utf8"));
assert.equal(F.schema,"MASS_SCRIPTURE_FORTESCUE_ORDER_EXTRACT_V1");
assert.equal(F.records.length,30);
assert.equal(new Set(F.records.map(r=>r.id)).size,30);
assert.ok(F.source.edition.includes("1914 NEW EDITION"),"supplied second edition is 1914, not 1912");
assert.equal(F.editionCorrection.firstEdition,"1912");
assert.equal(F.existingProductionOwners.formationRoute,"learn.mass");
assert.equal(mainFormation.route,"learn.mass");
assert.equal(mainFormation.stages.length,8);
assert.equal(F.existingProductionOwners.scriptureReadingBridge,"src/mass/scripture-reading-context.js");
const stageIds=new Set(mainFormation.stages.map(s=>s.id)),existingIds=new Set(earlier.records.map(r=>r.id));
assert.ok(F.records.every(r=>r.existingStudyIds.every(id=>existingIds.has(id)),"existing prior claim IDs must be reused"));
assert.ok(F.records.every(r=>r.suggestedOwnerStage===null||stageIds.has(r.suggestedOwnerStage)));
assert.ok(F.records.every(r=>r.formationMappingStatus==="PROPOSED_ONLY_NOT_APPLIED_TO_MAIN"));
assert.ok(F.records.every(r=>r.sourceUrl===F.source.originalOcrUrl && r.fortescueSection && r.printedPageStart>0 && r.ocrLines));
assert.ok(F.records.every(r=>r.editorial.publishable===false && r.editorial.exact1962PrayerMatched===false && r.editorial.doctrinalHistoricalCert===false));
assert.equal(F.records.flatMap(r=>r.scripture).length,52);
assert.ok(F.records.flatMap(r=>r.scripture).every(x=>x.sourceBookChapterUrl?.startsWith("https://www.newadvent.org/bible/") && !x.reference.includes("numbering edition-specific")));
assert.ok(F.records.some(r=>r.id==="FT019"&&r.scripture[0].reference==="Romans 12:1"));
assert.ok(F.records.some(r=>r.id==="FT013"&&r.scripture[0].reference.startsWith("Daniel 3:39")));
assert.ok(F.records.some(r=>r.id==="FT027"&&r.authorialExplanation.includes("anima")));
const ctx=F.records.filter(r=>r.fortescueCitationStatus!=="FORTESCUE_PASSAGE_LOCATED");
assert.deepEqual(ctx.map(r=>r.id),["FT010","FT012","FT016","FT024"]);
assert.equal(F.records.find(r=>r.id==="FT010").editorial.originalTextLocusLocated,false,"index-only section must never be promoted to direct inspected evidence");
assert.ok(F.records.find(r=>r.id==="FT012").scripture.every(s=>s.linkRole==="CONTEXTUAL_REFERENCE_NOT_DIRECTLY_CITED_HERE_BY_FORTESCUE"));
assert.ok(F.records.find(r=>r.id==="FT024").scripture.every(s=>s.linkRole==="CONTEXTUAL_REFERENCE_NOT_DIRECTLY_CITED_HERE_BY_FORTESCUE"));
assert.ok(F.records.find(r=>r.id==="FT020").scripture.every(s=>s.linkRole==="FORTESCUE_TENTATIVE_ALLUSION"));
assert.ok(F.records.filter(r=>r.evidenceType==="EARLY_PRACTICE_PARALLEL").length>=4);
console.log("PASS Fortescue revised-1914 Mass ↔ Bible evidence register:",F.records.length,"records and",F.records.flatMap(r=>r.scripture).length,"Scripture links; no production approvals");
