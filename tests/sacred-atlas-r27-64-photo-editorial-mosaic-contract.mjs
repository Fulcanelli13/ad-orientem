import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const htmlPath="data/geography/research/sacred-atlas-r27-one-bulk-61-cover-editorial-mosaic-20261104.html";
const html=readFileSync(htmlPath,"utf8");
const source=read("data/geography/research/sacred-atlas-round25-23place-64-original-review-20261104.json");
const rec=read("data/geography/research/sacred-atlas-round26-existing21-cover-triage-20261104.v1.json");
const cross=read("data/geography/research/sacred-atlas-existing-first-151-photo-reconciliation-20261104.v1.json");
const match=html.match(/<script type="application\/json" id="review-data">([\s\S]*?)<\/script>/);
assert.ok(match,"R27 must embed all source files offline");
const embedded=JSON.parse(match[1]);
assert.equal(embedded.schema,"AO_SACRED_ATLAS_R27_ONE_BULK_PHOTO_EDITORIAL_MOSAIC_V1");
assert.equal(embedded.places.length,23);
assert.equal(embedded.production.published,379);
assert.equal(embedded.production.total,530);
assert.equal(embedded.editorial_source.selections_approved,0);
const old=new Map(source.places.map(p=>[p.place_id,p]));
const r26=new Map(rec.rows.map(p=>[p.place_id,p]));
const existing=new Map(cross.rows.map(p=>[p.place_id,p]));
assert.equal(new Set(embedded.places.map(p=>p.place_id)).size,23);
let eligible=0,context=0,firstLooks=0,single=0,multi=0,excluded=0;
for(const place of embedded.places){
 const prior=old.get(place.place_id),editor=r26.get(place.place_id);
 assert.ok(prior&&editor&&existing.has(place.place_id));
 assert.equal(place.approval_from_source_metadata,false);
 assert.equal(place.user_cover_choice_made,false);
 assert.equal(place.review_group,editor.eligibility);
 assert.equal(place.review_recommendation,editor.first_look_source_title);
 assert.equal(place.images.length,prior.images.length);
 if(editor.candidate_count===1)single++;
 else if(editor.candidate_count>1)multi++;
 else excluded++;
 let count=0,first=0;
 for(let i=0;i<place.images.length;i++){
  const a=place.images[i],b=prior.images[i];
  assert.equal(a.file,b.file);
  assert.equal(a.url,b.url);
  assert.equal(a.sha1,b.sha1);
  assert.equal(a.bytes,b.bytes);
  assert.equal(a.author,b.author);
  assert.equal(a.license,b.license);
  assert.equal(a.role,b.role);
  assert.equal(a.byte_verified,true);
  assert.equal(a.first_look,a.file===editor.first_look_source_title);
  if(a.role==="COVER_CANDIDATE"){count++;eligible++;}else context++;
  if(a.first_look){first++;firstLooks++;}
 }
 assert.equal(count,editor.candidate_count);
 assert.ok(first<=1);
}
assert.equal(eligible,61);
assert.equal(context,3);
assert.equal(firstLooks,19);
assert.equal(single,13);
assert.equal(multi,8);
assert.equal(excluded,2);
for(const id of ["place:NZ:pukekaraka-otaki","place:CL:sanctuary-of-our-lady-of-la-tirana-chile"]){
 const p=embedded.places.find(x=>x.place_id===id);
 assert.ok(p);
 assert.ok(p.images.every(x=>x.role!=="COVER_CANDIDATE"));
 assert.ok(!p.images.some(x=>x.first_look));
}
const client=html.match(/<script>([\s\S]*?)<\/script><\/body><\/html>/)?.[1];
assert.ok(client,"Self-contained client JavaScript must exist");
new vm.Script(client,{filename:"R27-auto-thumb-one-tap.js"});
assert.ok(html.includes('id="gallery"'),"All 23 Places should be in one visible gallery");
assert.ok(html.includes('See every photo. Approve or reject in one click.'));
assert.ok(html.includes('id="singles"')&&html.includes('id="compare"')&&html.includes('id="context"')&&html.includes('id="pending"'));
assert.ok(html.includes('id="import"')&&html.includes('id="export"')&&html.includes('id="next"'));
assert.ok(html.includes('data-act="approve"')===false,"Action controls must be generated from source manifest, not hardcoded");
assert.ok(client.includes('data-act="approve"')&&client.includes('data-act="reject"'));
assert.ok(client.includes('data-act="hold"')&&client.includes('data-act="none"'));
assert.ok(client.includes('data-act="reset"')&&client.includes('data-act="crop"'));
assert.ok(client.includes('function placeHtml(p,i)'),"Every source photo should have a card");
assert.ok(client.includes('document.getElementById("gallery").innerHTML=places.map(placeHtml).join("")'),"All 64 cards must render up-front");
assert.ok(client.includes('IntersectionObserver'),"Automatically load visible thumbnails");
assert.ok(client.includes('queueFrame(e.target)'),"Load thumbnails as they enter viewport");
assert.ok(client.includes('MIN_GAP_MS=2500,MAX_ACTIVE=2'),"Respect rate limiting, no immediate 64-file burst");
assert.ok(client.includes('failedInARow>=3'),"Stop requests when thumbnails are repeatedly unavailable");
assert.ok(client.includes('img.src="https://commons.wikimedia.org/wiki/Special:FilePath/"'),"Original-only preview source, no third-party proxy");
assert.ok(!client.includes('loadAll')&&!client.includes('document.querySelectorAll("details.place").forEach'),"Do not flood Commons");
assert.ok(!client.includes('XMLHttpRequest')&&!client.includes("fetch("),"No background API scrapes");
assert.ok(client.includes('const eligible=im=>im.role==="COVER_CANDIDATE"'),"Context-only photos cannot be promoted");
assert.ok(client.includes('if(b.dataset.act==="approve"&&im&&eligible(im))'),"One-tap approve restricted to genuine cover candidate");
assert.ok(client.includes('if(approvedSource(p)===im.sha1)'),"One chosen original per Place");
assert.ok(client.includes('rejected[p.place_id]'),"Per-image rejection must be tracked");
assert.ok(client.includes('editorial_approved:true,publication_authorized:false'),"Curatorial choice is not rights clearance");
assert.ok(client.includes('photo_rights_approved:false,original_current_revision_verified_for_publication:false,visual_mobile_crop_approved:false'));
assert.ok(client.includes('AO_SACRED_ATLAS_UNDECIDED66_USER_EDITORIAL_REVIEW_EXPORT_V1'),"Preserve canonical export envelope");
assert.ok(client.includes('AO_Sacred_Atlas_23_Place_Photo_Approvals.json'),"One download after all decisions");
assert.ok(client.includes('function validChoice(p,d)'),"Imported decisions must match a frozen original file, URL and SHA1");
assert.ok(client.includes('saved&&typeof saved==="object"'),"Recover previous decisions when local storage is available");
assert.ok(!html.includes('"publication_authorized":true')&&!html.includes('"selections_approved":1'));
console.log("R27 THUMBNAIL EDITOR PASS: 23 Places, 64 auto-preview source cards, 61 cover choices, explicit one-click decisions, 3 context-only exclusions, paced Commons requests, editorial-only export.");
