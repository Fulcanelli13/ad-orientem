import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_HOLY_FACE_1887_B25,HOLY_FACE_SOURCE_GATES_B25} from "../src/pray/holy-face-janvier-1887-b25.js";
const research=name=>JSON.parse(readFileSync(new URL("../data/pray/research/"+name,import.meta.url),"utf8"));
const d=research("pray-holy-face-1895-fr-day04-transcribed-first-pass.v1.json");
const day1=research("pray-holy-face-1895-fr-day01-transcribed-proofread.v1.json");
const map=research("pray-holy-face-original-french-1895-printed-9day-page-map.v1.json");
assert.equal(d.schema,"ao.pray.holy-face.french-1895-day-transcription.v1");
assert.equal(d.canonicalId,NOVENA_HOLY_FACE_1887_B25.id);
assert.equal(d.day,4);
assert.deepEqual(d.printedPages,[124,125,126,127]);
assert.deepEqual(d.pdfZeroBasedPages,[130,131,132,133]);
assert.equal(map.dayMap[3].printedPages.from,124);
assert.equal(map.dayMap[3].printedPages.to,127);
assert.equal(d.dayHeading,"La sainte Face au jardin des Oliviers");
assert.deepEqual(d.dayComponents.map(x=>x.key),["opening_reference","narrative","point1","point2","point3","act","virtue","bouquet","conclusion_reference"]);
const sections=d.dayComponents.filter(x=>typeof x.text==="string");
const refs=d.dayComponents.filter(x=>x.text===null);
assert.equal(sections.length,7);
assert.equal(refs.length,2);
assert.ok(sections.every(x=>x.text.length>100&&x.pages.every(p=>p>=124&&p<=127)));
assert.ok(sections.reduce((n,x)=>n+x.text.length,0)>3400);
assert.deepEqual(refs.map(x=>x.refDay),[1,1]);
assert.equal(refs[0].refSection,"opening");
assert.deepEqual(refs[1].refSections,["prayers","collect"]);
for(const key of ["opening","prayers","collect"]) assert.ok(day1.dayComponents.some(x=>x.key===key&&x.text?.length>100));
assert.match(d.dayComponents[1].text,/Suivez Jésus se rendant après la Cène au jardin des Olives/);
assert.match(d.dayComponents[2].text,/Elle reflète toutes les impressions de son âme/);
assert.match(d.dayComponents[3].text,/cette Victime endolorie et languissante/);
assert.match(d.dayComponents[4].text,/Ô Jésus ! vous n’avez point refusé le secours d’autrui/);
assert.match(d.dayComponents[5].text,/Offrez-vous tout entier vous-même à Dieu/);
assert.match(d.dayComponents[6].text,/les amertumes qu’il plaira à Dieu/);
assert.match(d.dayComponents[7].text,/Ma nourriture, c’est-à-dire ma joie et mes délices/);
assert.deepEqual(d.comparison.englishParagraphIndicesByFrenchSection.conclusion_reference,[8,9]);
assert.equal(d.comparison.variants.length,5);
assert.ok(d.comparison.variants.every(x=>x.action&&x.printedPage>=124&&x.printedPage<=127));
assert.equal(d.independentSecondProofComplete,false);
assert.equal(d.release,"RESEARCH_ONLY_NOT_BOUND_TO_PUBLIC_READER");
assert.equal(d.frenchBodyInCanonicalReader,"EMPTY");
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every((x,i)=>x.originalSourceDay===i+1&&x.text.fr===""));
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every(x=>x.text.en.length>3000));
assert.equal(HOLY_FACE_SOURCE_GATES_B25.verifiedFrenchPrayerBody,false);
assert.equal(HOLY_FACE_SOURCE_GATES_B25.originalPrintPhotoCollated,false);
console.log("PASS Day IV 1895 French 7 sections, two shared prayer refs, 5 variants; nine original English bodies preserved and no French published");
