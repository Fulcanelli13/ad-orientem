import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const root=new URL("../data/pray/",import.meta.url);
const d=JSON.parse(readFileSync(new URL("prayer-corpus-raccolta1857-numbered-index-wave03.v1.json",root),"utf8"));
const owned=JSON.parse(readFileSync(new URL("prayer-corpus-ownership-foundation.v1.json",root),"utf8"));
assert.equal(d.schema,"ao.raccolta.index-discovery.v1");
assert.equal(d.records.length,161);
assert.deepEqual(d.records.map(x=>x.historical_index_number),Array.from({length:161},(_,i)=>i+1));
assert.equal(new Set(d.records.map(x=>x.lead_id)).size,161);
assert.equal(d.records.filter(x=>x.index_title!==null).length,79);
assert.equal(d.records.filter(x=>x.index_title===null).length,82);
assert.equal(d.summary.title_transcribed,79);
assert.equal(d.summary.title_pending,82);
const owner=new Set(owned.records.map(x=>x.key));
assert.equal(owner.size,94);
assert.ok(d.records.every(x=>x.matched_ownership_candidates.every(k=>owner.has(k))));
assert.ok(d.records.every(x=>x.source_index_url===d.source_index_url));
assert.ok(d.records.every(x=>x.edition==="1857"&&!x.original_scan_page_checked&&!x.original_text_verified&&!x.canonical_imported&&!x.duplicate_work_confirmed));
assert.ok(d.records.every(x=>x.index_title!==null||x.evidence_status==="INDEX_NUMBER_ONLY_TITLE_PENDING"));
assert.equal(d.summary.distinct_prayers_established,0);
assert.equal(d.summary.canon_imports,0);
console.log("Raccolta 1857 Wave 03: 161 numbered historical slots, 79 headings, 82 explicit title gaps; no false certification PASS");
