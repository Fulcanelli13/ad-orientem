import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {auditPlaceGeo,assertExploreGeographyRegistry} from "../src/find/geography-contracts.js";
import {projectExploreDataset} from "../src/find/explore-projection.js";
import {exploreMapFeatures} from "../src/find/map-runtime.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const manifest=read("data/explore/relic-principal-sites-publication.2026-10-09.json");
const selection=read("data/explore/relic-atlas-site-selection.review.v1.json");
const geo=read("data/geography/seed-registry.v1.json");
const sh=read("data/shrines/shrines-pilgrimages-seed.v1.json");
const sources=read("data/shrines/source-registry.v1.json");
const sacred=read("data/explore/sacred-phenomena-seed.v1.json");
assert.equal(manifest.schema,"SACRED_ATLAS_RELIC_BULK_PUBLICATION_V1");
assert.equal(manifest.mode,"SITE_LEVEL_NOT_EVERY_FRAGMENT");
assert.equal(manifest.sites.length,39);
assert.equal(manifest.one_relic_aggregate_per_site,true);
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({shrines:sh.shrines,pilgrimages:sh.pilgrimages,routes:sh.routes,temporalLinks:sh.temporalLinks,sources:sources.sources,places:geo.places}).pass,true);
assert.equal(geo.places.length,174);
assert.equal(sh.shrines.length,170);
assert.equal(sh.pilgrimages.length,198);
assert.equal(sources.sources.length,253);
assert.equal(sacred.relics.length,114);
const idset=new Set(),pmap=new Map(geo.places.map(p=>[p.place_id,p]));
const sid=new Set(),selectionIds=new Set(selection.site_decisions.map(x=>x.selection_id));
for(const group of manifest.sites){
 assert.ok(!idset.has(group.place_id));idset.add(group.place_id);
 assert.ok(group.selection_ids.length>0&&group.selection_ids.every(x=>selectionIds.has(x)));
 assert.ok(group.subject_ids.length>=1);
 assert.ok(group.geo_source.startsWith("https://"));
 assert.ok(group.original_custodian_sources.length>=1);
 const p=pmap.get(group.place_id);
 assert.ok(p,p?.place_id+" place missing");
 assert.equal(auditPlaceGeo(p.geo,{countryCode:p.address.country_code}).length,0);
 assert.equal(p.mappable,true);
 assert.ok(["site","complex_anchor","locality"].includes(p.geo.precision));
 assert.ok(group.original_custodian_sources.every(x=>x.startsWith("https://")));
 const relics=sacred.relics.filter(r=>r.place_id===group.place_id);
 assert.equal(relics.length,1,"Only one grouped relic object at a new site");
 assert.equal(relics[0].id,group.relic_id);
 assert.equal(relics[0].authentication,"NOT_INDEPENDENTLY_CERTIFIED_BY_APP");
 assert.equal(relics[0].calendar_semantic_key,null);
 assert.equal(sh.shrines.filter(s=>s.place_id===group.place_id).length,1);
 assert.equal(sh.shrines.find(s=>s.place_id===group.place_id).shrine_id,group.shrine_id);
 assert.equal(sh.pilgrimages.filter(x=>x.destination_shrine_id===group.shrine_id).length,1);
 assert.equal(sources.sources.filter(x=>x.id===p.source_ids[0]).length,1);
 for(const x of group.subject_ids)sid.add(x);
}
assert.ok(sid.size>=40);
const projected=projectExploreDataset({geography:geo,shrines:sh,sacredPhenomena:sacred});
const allRelics=projected.byLens.relics;
const points=exploreMapFeatures(allRelics);
const uniqueEligiblePlaces=new Set(allRelics.filter(x=>x.map_publishable).map(x=>x.place_id));
assert.equal(points.length,uniqueEligiblePlaces.size,"Relic map must publish exactly one marker per physical Place");
assert.ok(points.every(p=>p.properties.lens==="relics"));
for(const site of manifest.sites){
 assert.ok(allRelics.some(x=>x.place_id===site.place_id&&x.source_id===site.relic_id));
 assert.equal(points.filter(p=>p.properties.item_id==="relics:"+site.relic_id).length,1);
}
const rome=projected.byLens.relics.filter(x=>x.place_id==="place:FR:notre-dame-paris");
assert.equal(rome.length,3,"Original Holy Crown/Cross/Nail remain independent records in place profile");
assert.equal(points.filter(p=>rome.some(x=>x.item_id===p.properties.item_id)).length,1,"Original multi-object relic sites must not flood the pin map");
const remaining=selection.site_decisions.filter(x=>!x.existing_place_id&&!manifest.sites.some(g=>g.selection_ids.includes(x.selection_id)));
assert.ok(remaining.length===0,"All 39 originally shortlisted new Places are now mapped");
console.log("PASS 39 principal relic destinations, 43 saint associations, one marker per Place, 114 relic records, 170 shrines, 198 pilgrimages");
