import assert from "node:assert/strict";
import {createLivingChurchConversationTrail} from "../previews/visible-mass-3d/living-church-conversation-trail.mjs";
const trail=createLivingChurchConversationTrail({limit:3});
assert.equal(trail.count(),0);
assert.equal(trail.record({kind:"guide",guide:"sacristan"}).ok,true);
assert.equal(trail.record({kind:"guide",guide:"sacristan"}).duplicate,true);
assert.equal(trail.count(),1);
assert.equal(trail.record({kind:"objective",guide:"sacristan",objective:"protestant"}).ok,true);
assert.equal(trail.record({kind:"source",guide:"pius-x",objective:"protestant",sourceId:"apostolate:AQ08"}).ok,true);
assert.equal(trail.record({kind:"source",guide:"pius-x",objective:"protestant",sourceId:"apostolate:AQ03"}).ok,true);
assert.equal(trail.count(),3,"oldest event evicted from the memory-only trail");
assert.equal(trail.entries()[0].kind,"objective");
assert.equal(trail.record({kind:"source",guide:"pius-x",sourceId:"javascript:alert(1)"}).ok,false);
assert.equal(trail.record({kind:"objective",guide:"pius-x",objective:"mass",message:"a private confession"}).ok,true);
const serialized=JSON.stringify(trail.entries());
assert.equal(serialized.includes("a private confession"),false,"never persist typed or private message fields");
const snapshot=trail.entries();assert.ok(Object.isFrozen(snapshot));
assert.ok(snapshot.every(x=>Object.isFrozen(x)));
assert.equal(trail.clear(),true);
assert.equal(trail.count(),0);
console.log("PASS bounded source-ID-only ephemeral Living Church conversation trail");
