import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const load=p=>JSON.parse(readFileSync(p,'utf8'));
const root='data/customs/master/';
const base=load(root+'pitre-1900-129-original-witness-facsimile-and-1881-dependency-gates.v1.json');
const old=load(root+'pitre-1900-feste-patronali-original-edition-ocr-actions-wave01.v1.json');
const p0=load(root+'pitre-1900-uploaded-facsimile-25p0-16-wave03-page-gates.v1.json');
const p1=load(root+'pitre-1900-uploaded-facsimile-17-p1-date-region-page-gates.v1.json');
const p2=load(root+'pitre-1900-uploaded-facsimile-87-p2-original-page-verifications.v1.json');
const snapshot277=load(root+'pitre-1900-277-new-observations-current-original-page-queue.v1.json');
const snapshot156=load(root+'pitre-1900-156-wave03-remaining-original-folio-page-queue.v1.json');
const current=load(root+'pitre-1900-current-zero-outstanding-original-edition-page-queue.v1.json');
const catalogue=load(root+'comprehensive-customs-working-catalogue.v1.json');
const orig=new Map(old.records.map(r=>[r.id,r]));
const indexed=new Map(catalogue.external_source_observations_pitre_original_1900_ocr.map(r=>[r.id,r]));
const expectedP2=new Set(base.records.filter(r=>r.priority==='P2_STANDARD_FACSIMILE').map(r=>r.original_source_id));
const checkedP0=new Set(p0.original_129_p0_page_checks.map(r=>r.source_id));
const checkedP1=new Set(p1.records.map(r=>r.source_id));
const p2Ids=new Set();
assert.equal(expectedP2.size,87);
assert.equal(checkedP0.size,25);
assert.equal(checkedP1.size,17);
assert.equal(p2.records.length,87);
assert.equal(p2.summary.new_original_folio_checks,87);
assert.equal(p2.summary.distinct_original_printed_pages,37);
assert.equal(p2.source.compressed_pdf_sha256,'100e2b3164bd7a342c5c0c5d01df2a60b4635d5695dea456e9b93769866ee5ee');
assert.equal(p2.summary.old_original_129_total_after_this_pass,129);
assert.equal(p2.summary.original_page_verified_after_this_pass,145);
assert.equal(p2.summary.remaining_new_293_page_checks,277);
const printed=new Set();
for(const r of p2.records){
 assert.ok(expectedP2.has(r.source_id),'Every P2 record must be drawn from older P2 priority gate');
 assert.ok(!checkedP0.has(r.source_id)&&!checkedP1.has(r.source_id),'P0/P1 overlap');
 assert.ok(!p2Ids.has(r.source_id),'Duplicated P2 ID');
 p2Ids.add(r.source_id);
 const before=orig.get(r.source_id),after=indexed.get(r.source_id);
 assert.ok(before&&after,'Corresponding original ID missing');
 assert.equal(r.original_1900_ocr_line,before.html_ocr_line);
 assert.equal(r.original_record_action,before.reported_action_or_component);
 assert.equal(r.pdf_page_1_based,r.printed_page+58);
 assert.ok(Number.isInteger(r.printed_page)&&r.printed_page>=200&&r.printed_page<=520);
 assert.ok(r.italian_text_anchor.length>=12);
 assert.equal(r.original_scan_page_rendered_and_reviewed,true);
 assert.equal(r.printed_folio_located,true);
 assert.equal(r.original_italian_text_layer_normalized_anchor_matched,true);
 assert.equal(after.original_1900_printed_page,r.printed_page);
 assert.equal(after.original_1900_scan_pdf_page_1_based,r.pdf_page_1_based);
 assert.equal(after.original_page_evidence_anchor,r.italian_text_anchor);
 assert.equal(after.printed_scan_page_verified,true);
 assert.equal(after.facsimile_provenance_file,root+'pitre-1900-uploaded-facsimile-87-p2-original-page-verifications.v1.json');
 for(const flag of ['underlying_historical_testimony_independently_verified','modern_calendar_date_verified','roman_ritual_approval_verified','unique_custom_identity_certified','app_published'])assert.equal(r[flag],false,flag);
 assert.equal(after.independent_witness_certified,false);
 assert.equal(after.practice_identity_certified,false);
 assert.equal(after.app_publication,'NONE');
 printed.add(r.printed_page);
}
assert.deepEqual(p2Ids,expectedP2);
assert.equal(printed.size,37);
assert.equal(new Set([...checkedP0,...checkedP1,...p2Ids]).size,129);
assert.equal(indexed.size,129);
assert.equal([...indexed.values()].filter(r=>r.printed_scan_page_verified).length,129);
assert.equal(catalogue.external_source_observations_pitre_original_1900_new_ocr.length,293);
assert.equal(catalogue.external_source_observations_pitre_original_1900_new_ocr.filter(r=>r.original_printed_folio_verified).length,293);
assert.equal(snapshot277.records.length,277);
assert.equal(snapshot156.records.length,156);
assert.equal(current.records.length,0);
assert.equal(snapshot156.summary.still_unverified_new_wave03,156);
assert.equal(current.summary.current_unverified_original_pages,0);
const outstanding=new Set(catalogue.external_source_observations_pitre_original_1900_new_ocr.filter(r=>!r.original_printed_folio_verified).map(r=>r.id));
assert.equal(outstanding.size,0);
assert.deepEqual(outstanding,new Set(current.records.map(r=>r.id)));
assert.equal(catalogue.summary.source_review.pitre_1900_original_folio_images_visually_checked,129);
assert.equal(catalogue.summary.source_review.pitre_1900_original_remaining_p2_page_checks,0);
assert.equal(catalogue.summary.source_review.pitre_1900_original_p2_verified,87);
assert.equal(catalogue.summary.source_review.pitre_1900_original_129_verified,129);
assert.equal(catalogue.summary.source_review.pitre_1900_all_original_folio_record_checks,422);
assert.equal(catalogue.summary.source_review.pitre_1900_unchecked_record_pages_remaining,0);
assert.equal(catalogue.summary.source_review.pitre_1900_full_422_unique_pdf_pages_checked,144);
assert.equal(catalogue.summary.source_observations.total_source_detail_rows_including_external,3512);
assert.equal(catalogue.summary.identity_working_rows.provisional_after_53_no_owner_action_review,408);
assert.equal(catalogue.summary.identity_working_rows.final_uniquely_verified_customs_added,0);
assert.equal(catalogue.summary.no_new_app_publications,true);
console.log('Pitrè full original 1900 scan: 25 P0 + 17 P1 + 87 P2 = 129/129 author-source page checks; 145/422 overall; 277 new outstanding; no rite, identity or app promotion — PASS');
