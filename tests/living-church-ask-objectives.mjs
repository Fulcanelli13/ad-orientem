import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {loadLivingChurchObjectives} from "../previews/visible-mass-3d/living-church-objective-director.mjs";
const file=JSON.parse(await readFile(new URL("../data/learn/ask-church-app-route-survey.v1.json",import.meta.url),"utf8"));
const fetchImpl=async()=>({ok:true,json:async()=>file});
const router=await loadLivingChurchObjectives({fetchImpl});
assert.equal(router.objectives().length,7,"reuse all seven existing objective families");
assert.ok(router.objectives().some(x=>x.id==="defend"));
assert.equal(router.choice("defend").ok,true);
assert.equal(router.branch("protestant").ok,true);
assert.equal(router.snapshot().selection.guide,"pius-x");
assert.ok(router.snapshot().selection.sourceRoutes.length>0);
const source=await router.digest("apostolate:AQ08");
assert.equal(source.ok,true);
assert.equal(source.owner,"Apostolate");
assert.equal(source.sourceStatus,"READY_IN_RUNTIME_SOT");
assert.match(source.text,/Scripture|Tradition/);
assert.ok(source.detail.length>50);
assert.ok(source.sources.length>0);
assert.ok(source.sources.every(x=>new URL(x.url).protocol==="https:"));
assert.equal((await router.digest("learn.church_crisis")).ok,false);
assert.equal((await router.digest("learn.apologetics")).ok,false);
assert.equal((await router.digest("apostolate:HS02")).ok,false,"other objective source cannot leak through");

assert.ok(router.snapshot().selection.sourceRoutes.every(x=>x!=="learn.apologetics"&&x!=="learn.church_crisis"));
router.reset();
assert.equal(router.choice("understand").ok,true);
assert.equal(router.branch("mass").ok,true);
assert.equal(router.snapshot().selection.guide,"canon");
const mass=await router.digest("learn.mass_explorer");
assert.equal(mass.ok,true);
assert.equal(mass.owner,"Formation");
assert.equal(mass.sourceStatus,"MODULE_DESCRIPTION");
assert.equal(mass.sources.length,0,"No fake theological citation for module description");

router.reset();
assert.equal(router.choice("explore").ok,true);
assert.equal(router.branch("places").ok,true);
assert.equal(router.snapshot().selection.guide,"sacristan");
router.reset();
const inferred=router.interpret("I'd like to understand the traditional Latin Mass");
assert.equal(inferred.kind,"path");
assert.equal(inferred.selection.guide,"canon");
assert.equal(inferred.selection.objective,"understand");
assert.ok(router.snapshot().selection.sourceRoutes.every(x=>x!=="learn.apologetics"));
router.language("fr");
router.reset();
assert.ok(router.objectives().some(x=>x.title==="Défendre la foi"));
assert.equal(router.choice("defend").ok,true);
assert.ok(router.branches().some(x=>x.title.includes("protestantes")));
assert.equal(router.branch("protestant").ok,true);
assert.equal(router.snapshot().selection.guide,"pius-x");
assert.equal(router.snapshot().selection.sourceRoutes.includes("learn.apologetics"),false);
console.log("PASS shared PR1391 objective engine and registry; 7 families, guided routing, publication hold, French and three guides");
