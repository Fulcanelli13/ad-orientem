assert.equal(m.global_unresolved_after_release,p48.global_unresolved_after_release-2);
assert.equal(m.global_canonical_links_after_release,p48.global_canonical_links_after_release+2);
const ids=new Set(m.published_new.map(x=>x.candidate_id));
assert.deepEqual([...ids].sort(),["SG-INV-0330","SG-INV-0341"]);
for(const x of m.published_new){
 assert.ok(p43.global_acquisition_500.some(z=>z.candidate_id===x.candidate_id&&!z.known_canonical_link));
 const place=g.places.find(z=>z.place_id===x.place_id);assert.ok(place);
 assert.equal(place.geo.source_ref,x.geo_source_ref);
 assert.equal(place.geo.source_url,x.geo_source_url);
 assert.equal(place.geo.precision,"site");
 assert.equal(place.address.country_code,x.country);
 assert.deepEqual([place.geo.lat,place.geo.lng],[x.lat,x.lng]);
 assert.ok(isMapPublishablePlaceGeo(place.geo,x.country));
 const source=s.sources.find(z=>z.id===x.source_ids[0]);assert.ok(source);
 assert.deepEqual(auditShrineSource(source),[]);
 assert.equal(source.url,x.identity_source_url);
 assert.ok(h.exception_queues.places_without_direct_claim.includes(x.place_id));
 assert.equal(h.place_crosswalk.filter(z=>z.place_id===x.place_id).length,1);
 assert.equal(g.directoryPlaceLinks.filter(z=>z.place_id===x.place_id).length,0);
}
