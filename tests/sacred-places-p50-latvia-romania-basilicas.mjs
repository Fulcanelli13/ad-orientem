import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {auditShrineSource} from "../src/find/shrines-contracts.js";
import {isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=read("data/geography/research/sacred-places-p50-latvia-romania-basilicas.v1.json");
const p48=read("data/geography/research/sacred-places-p48-eight-global-buildings.v1.json");
const p43=read("data/geography/research/sacred-places-p43-open35-global500-reconciliation.v1.json");
const g=read("data/geography/seed-registry.v1.json");
const s=read("data/shrines/source-registry.v1.json");
const h=read("data/explore/heritage-place-reconciliation.review.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P50_TWO_BASILICA_BUILDINGS_V1");
assert.deepEqual(Object.values(m.baseline),[512,810,512,253,146,9]);
assert.deepEqual(Object.values(m.proposed),[514,812,514,255,146,9]);
assert.deepEqual([g.places.length,s.sources.length,h.place_crosswalk.length,h.exception_queues.places_without_direct_claim.length,g.geoAreas.length,g.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
