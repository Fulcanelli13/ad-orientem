import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_HOLY_FACE_1887_B25,HOLY_FACE_SOURCE_GATES_B25} from "../src/pray/holy-face-janvier-1887-b25.js";
const research=name=>JSON.parse(readFileSync(new URL("../data/pray/research/"+name,import.meta.url),"utf8"));
const d=research("pray-holy-face-1895-fr-day05-transcribed-first-pass.v1.json");
const day1=research("pray-holy-face-1895-fr-day01-transcribed-proofread.v1.json");
const map=research("pray-holy-face-original-french-1895-printed-9day-page-map.v1.json");
assert.equal(d.schema,"ao.pray.holy-face.french-1895-day-transcription.v1");
assert.equal(d.canonicalId,NOVENA_HOLY_FACE_1887_B25.id);
assert.equal(d.day,5);
assert.deepEqual(d.printedPages,[127,128,129,130]);
assert.deepEqual(d.pdfZeroBasedPages,[133,134,135,136]);
assert.equal(d.dayHeading,"La sainte Face dans la cour de Caïphe");
assert.equal(map.dayMap[4].printedPages.from,127);
assert.equal(map.dayMap[4].printedPages.to,130);
assert.deepEqual(d.dayComponents.map(x=>x.key),["opening_reference","narrative","point1","point2","point3","act","virtue","bouquet","conclusion_reference"]);
const original=d.dayComponents.filter(x=>typeof x.text==="string");
const references=d.dayComponents.filter(x=>x.text===null);
assert.equal(original.length,7);
assert.equal(references.length,2);
assert.ok(original.every(x=>x.text.length>65&&x.pages.every(p=>p>=127&&p<=130)));
assert.ok(original.reduce((n,x)=>n+x.text.length,0)>3100);
assert.deepEqual(references.map(x=>x.refDay),[1,1]);
assert.equal(references[0].refSection,"opening");
assert.deepEqual(references[1].refSections,["prayers","collect"]);
for(const key of ["opening","prayers","collect"])assert.ok(day1.dayComponents.some(x=>x.key===key&&x.text?.length>100));
assert.match(d.dayComponents[1].text,/jugement dérisoire/);
assert.match(d.dayComponents[1].text,/dans la cour du grand prêtre/);
assert.match(d.dayComponents[2].text,/Le Fils de l’homme sera conspué/);
assert.match(d.dayComponents[3].text,/Conversion de saint Pierre/);
assert.match(d.dayComponents[4].text,/Ô Jésus, dont la Face divine relève et transforme/);
assert.match(d.dayComponents[5].text,/Acte de contrition/);
assert.match(d.dayComponents[6].text,/Ayez le courage de la foi/);
assert.match(d.dayComponents[7].text,/Jésus regarda Pierre, et Pierre pleura amèrement/);
assert.deepEqual(d.comparison.englishParagraphIndicesByFrenchSection.conclusion_reference,[8,9]);
assert.equal(d.comparison.variants.length,5);
assert.ok(d.comparison.variants.some(x=>x.frReading.includes("jugement dérisoire")&&x.en1887DigitalReading.includes("decisive judgment")));
assert.ok(d.comparison.variants.some(x=>x.frReading.includes("cour du grand prêtre")&&x.en1887DigitalReading.includes("house of Caiphas")));
assert.equal(d.independentSecondProofComplete,false);
assert.equal(d.release,"RESEARCH_ONLY_NOT_BOUND_TO_PUBLIC_READER");
assert.equal(d.frenchBodyInCanonicalReader,"EMPTY");
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every((x,i)=>x.originalSourceDay===i+1&&x.text.fr===""));
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every(x=>x.text.en.length>3000));
assert.equal(HOLY_FACE_SOURCE_GATES_B25.verifiedFrenchPrayerBody,false);
assert.equal(HOLY_FACE_SOURCE_GATES_B25.originalPrintPhotoCollated,false);
console.log("PASS: Day V 1895 French 7 sections, 2 genuine printed prayer references, 5 variant holds; no premature French reader activation");
