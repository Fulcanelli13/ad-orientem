import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createOriginalCatechismReferralIndex,catechismNumber,catechismRef}
 from "../src/learn/living-church-catechism-source.js";
const s=JSON.parse(readFileSync("data/learn/ltfaith-pius-x-en-witness-index.v1.json","utf8"));
const index=createOriginalCatechismReferralIndex(s);
assert.equal(index.status().count,433);
assert.equal(index.status().publication,"REVIEW_ONLY");
assert.equal(index.get(105).ref,"PX1912-Q105");
assert.equal(index.get(105).stem,"What is the Church?");
assert.equal(index.search("What is the Church?").some(x=>x.number===105),true);
assert.equal(index.search("church").some(x=>x.number===105),true);
assert.equal(index.search("no-match-this-question").length,0);
assert.equal(index.search("confession").length>0,true);
assert.equal(index.search("church",{limit:3}).length<=3,true);
assert.equal(catechismRef(1),"PX1912-Q001");
assert.equal(catechismRef(433),"PX1912-Q433");
assert.equal(catechismRef(434),null);
assert.equal(catechismNumber("PX1912-Q433"),433);
assert.equal(catechismNumber("PX1912-Q000"),null);
assert.equal(catechismNumber("PX1912-Q999"),null);
assert.equal(catechismNumber("PX1912-Q105-other"),null);
assert.equal(index.hasRef("PX1912-Q105"),true);
assert.equal(index.hasRef("PX1912-Q000"),false);
assert.throws(()=>createOriginalCatechismReferralIndex({...s,entries:s.entries.slice(0,432)}),/433-question/);
assert.throws(()=>createOriginalCatechismReferralIndex({...s,entries:s.entries.map((x,i)=>i===0?{...x,q:105}:x)}),/Unverified/);
assert.throws(()=>createOriginalCatechismReferralIndex({...s,entries:s.entries.map((x,i)=>i===0?{...x,source_file_url:"javascript:alert(1)"}:x)}),/Unverified/);
assert.equal("answer" in index.get(105),false);
assert.equal("translation" in index.get(105),false);
const code=readFileSync("src/learn/living-church-character-folio.js","utf8");
assert.match(code,/loadOriginalCatechismReferralIndex/);
assert.match(code,/integration\.nativeOpen\("learn\.catechism"/);
assert.match(code,/piusDisclosure/);
console.log("P4 original St Pius X 433-question index and source-only search: PASS");
