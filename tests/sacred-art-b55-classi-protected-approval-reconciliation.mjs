#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
const j=JSON.parse(fs.readFileSync("data/research/sacred-art-b55-class-i-2026-versus-383-protected-decisions.json","utf8"));
const summary=j.summary;
assert.equal(j.schema,"AO_B55_CLASS_I_2026_VS_383_APPROVAL_CROSSWALK_V1");
assert.equal(summary.class_i_observed_dates_2026,53);
assert.equal(summary.legacy_exact_subject_links_present_for_dates,21);
assert.equal(summary.legacy_dates_without_exact_link,32);
assert.equal(summary.documented_2026_explicit_date_choices,10);
assert.equal(summary.dated_approvals_found_same_painting_in_gallery,4);
assert.equal(summary.dated_approvals_not_in_gallery,6);
assert.deepEqual(summary.datematched_in_gallery_review_indices,[144,194,237,371]);
assert.equal(summary.gal_active_total,383);
assert.equal(summary.uploaded_shipped_and_publication_certified,0);
assert.equal(summary.production_release_ready,false);
assert.equal(summary.user_choices_to_rescore,0);
assert.equal(summary.strictly_zero_euro,true);
assert.equal(j.class_i_dates_2026.length,53);
assert.equal(new Set(j.class_i_dates_2026.map(x=>x.date)).size,53);
assert.equal(j.protected_date_approvals.length,10);
assert.equal(new Set(j.protected_date_approvals.map(x=>x.date)).size,10);
assert.equal(j.class_i_dates_2026.filter(x=>x.exact_subject_source_research_link_count>0).length,21);
assert.equal(j.class_i_dates_2026.filter(x=>x.date_specific_user_approved_painting).length,10);
assert.equal(j.protected_date_approvals.flatMap(x=>x.catalogue_matches).length,4);
assert.equal(j.protected_date_approvals.filter(x=>x.same_original_in_383).length,4);
assert.equal(j.protected_date_approvals.filter(x=>!x.same_original_in_383).length,6);
assert.ok(j.protected_date_approvals.every(x=>x.user_choice_approved&&!x.app_photo_publication_cleared));
const king=j.protected_date_approvals.find(x=>x.date==="2026-10-25");
assert.ok(king&&king.painting.artist==="Ambrosius Benson"&&king.painting.title==="Salvator Mundi"&&!king.same_original_in_383);
assert.ok(j.exceptions.find(x=>x.date==="2026-04-10"&&x.artist==="Tommaso Minardi"));
console.log("B55_CLASS_I_RECONCILIATION_PASS 53 distinct I-class dates, 10 explicit approved subjects, 4 exact original records in 383, 6 not in 383, 0 automatic reselections or releases");
