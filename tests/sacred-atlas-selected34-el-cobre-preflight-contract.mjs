import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const root="data/geography/research/";
const m=read(root+"sacred-atlas-selected34-existing-photo-recovery-20261104.v1.json");
const selected=read(root+"sacred-atlas-selected24-hold-closure-20261104.v1.json");
