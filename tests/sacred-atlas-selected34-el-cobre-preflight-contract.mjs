const decisions=read(root+"photo-finder-20261030/decisions.json").decisions;
const geo=read("data/geography/seed-registry.v1.json");
const covers=read("data/geography/approved-place-media.v1.json");
const gallery=read("data/geography/approved-place-gallery.v1.json");
assert.equal(m.schema,"AO_SACRED_ATLAS_SELECTED_34_EXISTING_IMAGE_RECOVERY_V1");
assert.equal(m.scope,"RESEARCH_ONLY_NO_PHOTO_APPROVAL");
assert.equal(m.rows.length,34);
assert.equal(new Set(m.rows.map(x=>x.place_id)).size,34);
assert.equal(m.baseline.canonical_places,530);
assert.equal(covers.items.length,m.baseline.published_covers);
assert.equal(covers.items.length,379);
assert.equal(gallery.items.length,42);
assert.equal(m.counts.new_media_approved,0);
assert.equal(m.counts.original_bytes_verified_this_batch,0);
