assert.equal(evidence.held_count,10);
const published=new Set(covers.items.map(x=>x.place_id));
const names=new Map(geo.places.map(x=>[x.place_id,x]));
const selById=new Map(selected.rows.map(x=>[x.place_id,x]));
const fById=new Map(findings.rows.map(x=>[x.place_id,x]));
const pdById=new Map(pd.rows.filter(x=>evidence.holds.some(h=>h.place_id===x.place_id)).map(x=>[x.place_id,x]));
assert.equal(pdById.size,10);
for(const item of m.rows){
 assert.ok(names.has(item.place_id),"unknown Place");
 assert.ok(!published.has(item.place_id),"no existing approved media may be replaced");
 assert.equal(names.get(item.place_id).photo_editorial.decision,"SELECTED");
 assert.equal(names.get(item.place_id).photo_editorial.cover_commons_file,item.original_selected_title);
 assert.equal(decisions[item.place_id].files[0],item.original_selected_title);
 assert.equal(item.publication_allowed,false);
 if(item.source_type==="EXISTING_SELECTED_PD_SELF"){
  const x=pdById.get(item.place_id);assert.ok(x);
  assert.equal(item.source_sha1,x.original_sha1);
  assert.equal(item.source_description_revision,x.expected_revision_id);
 }else{
  const x=selById.get(item.place_id),f=fById.get(item.place_id);
  assert.ok(x&&f);
  assert.equal(item.source_sha1,x.sha1);
  assert.equal(item.current_audit_status,f.verification_status);
  assert.ok(item.route&&item.source_page);
 }
}
assert.equal(m.rows.filter(x=>x.source_type==="EXISTING_SELECTED_PD_SELF").length,10);
assert.equal(m.rows.filter(x=>x.source_type==="EXISTING_SELECTED_CC_OR_OTHER").length,24);
assert.deepEqual(m.counts.selected24_by_latest_audit,findings.status_counts);
const pre=m.next_executable_preflight;
assert.equal(pre.place_id,"place:CU:el-cobre-caridad-basilica");
assert.equal(pre.source_title,decisions[pre.place_id].files[0]);
assert.equal(pre.source_sha1,selById.get(pre.place_id).sha1);
assert.equal(pre.source_revision_id,findings.rows.find(x=>x.place_id===pre.place_id).source_revision_id);
assert.equal(pre.expected_photo_license,"CC BY 3.0");
assert.equal(pre.publication_authorized,false);
assert.equal(m.first_two_source_rights_screen.cuba.stage,"SOURCE_BYTE_PREFLIGHT_ELIGIBLE_NO_RELEASE");
assert.equal(m.first_two_source_rights_screen.kuwait.stage,"ARCHITECTURAL_UNDERLYING_RIGHTS_HOLD_NO_RELEASE");
assert.equal(m.first_two_source_rights_screen.kuwait.place_id,"place:KW:holy-family-cocathedral-kuwait-city");
