import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {readCorpus} from '../tools/pius-x-generative-review.mjs';
import {buildPrimaryCoverageReport} from '../tools/pius-x-primary-coverage-report.mjs';

const html=readFileSync('artifacts/pius-x-study-expanded/SPX_Study_Expanded_106_P6.html','utf8');
const corpus=readCorpus(html);
const r=buildPrimaryCoverageReport(corpus);
assert.equal(r.schema,'AO_SPX_PRIMARY_SOURCE_COVERAGE_REPORT_V1');
assert.equal(r.totals.chapters,106);
assert.equal(r.totals.nodes,423);
assert.equal(r.totals.chaptersWithWitnessSpotcheck,33);
assert.equal(r.totals.nodesWithWitnessSpotcheck,82);
assert.equal(r.totals.nodesNotYetMappedToOriginalExcerpt,341);
assert.equal(r.totals.originalLanguageExcerptAnchors,102);
assert.equal(r.totals.chaptersFullyAuthenticated,0);
assert.equal(r.totals.publishedAnswers,0);
assert.equal(r.totals.uniqueDocumentGroups,r.documents.length);
assert.equal(r.documents.reduce((n,g)=>n+g.chapters.length,0),106);
assert.equal(r.documents.reduce((n,g)=>n+g.nodeCount,0),423);
assert.equal(r.documents.reduce((n,g)=>n+g.witnessMappedNodeCount,0),82);
assert(r.documents.reduce((n,g)=>n+g.witnessAnchorCount,0)>65);
assert(r.documents.reduce((n,g)=>n+g.witnessAnchorCount,0)<=102);
assert.equal(r.totals.oldAnnexMappedNodes,14);
assert.equal(r.totals.oldAnnexDocumentSubjects,4);
assert.equal(r.totals.expandedOpeningNodes,8);
assert.equal(r.totals.newBoundedFollowupNodes,14);
assert.equal(r.totals.heldResearchFollowups,8);
assert.equal(r.totals.bulkWave2NewNodes,46);
assert.equal(r.totals.bulkWave2NewExcerpts,35);
assert.equal(r.totals.bulkWave2PartialNodeHolds,5);
assert.equal(r.totals.bulkWave2Screened,51);
assert(r.suggestedNextDocuments.length>0&&r.suggestedNextDocuments.length<=12);
assert(r.suggestedNextDocuments.every(g=>g.pendingNodeCount>0&&g.chapters.length));
assert(r.documents.every(g=>g.nodeCount>=g.witnessMappedNodeCount));
assert(r.documents.every(g=>g.nodeCountWithoutWitnessSpotcheck>=0));
assert.equal(r.status,'RESEARCH_ONLY_NOT_RELEASE_APPROVED');
assert(r.warning.includes('NOT certified'));
assert.throws(()=>buildPrimaryCoverageReport(corpus,{nextBatchDocuments:0}));
assert.throws(()=>buildPrimaryCoverageReport(corpus,{nextBatchDocuments:31}));
const short=buildPrimaryCoverageReport(corpus,{nextBatchDocuments:3});
assert.equal(short.suggestedNextDocuments.length,3);
assert.deepEqual(short.suggestedNextDocuments,r.suggestedNextDocuments.slice(0,3));
console.log('PASS SPX_PRIMARY_COVERAGE: 106 subjects/423 nodes, 33 bounded subjects/82 nodes/102 research excerpt anchors; 341 not mapped; no authentication or publication');
