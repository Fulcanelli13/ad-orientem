import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const matrix=JSON.parse(readFileSync("data/pray/prayer-reviewed18-edition-variants.v1.json","utf8"));
const cert=JSON.parse(readFileSync("data/pray/prayer-source-certification-inventory.v3.json","utf8"));
const known=cert.prayers.filter(x=>x.collation?.status==="ANCHOR_REVIEWED_NOT_FULL_VERBATIM");
const seen=matrix.items;
assert.equal(matrix.schema,"AO_PRAYER_REVIEWED18_EDITION_VARIANTS_V1");
assert.equal(matrix.results.count,18);
assert.deepEqual(seen.map(x=>x.id),known.map(x=>x.id));
assert.equal(new Set(seen.map(x=>x.id)).size,18);
assert.equal(matrix.results.fully_certified,0);
assert.equal(matrix.results.all_collation_pending,18);
for(const x of seen){
 const knownRow=known.find(c=>c.id===x.id);
 assert.equal(x.historical_v3_classification,knownRow.collation.classification);
 assert.equal(x.fully_verbatim_certified,false);
 assert.equal(x.retained_text_integrity,"NO_TEXT_MUTATION");
 assert.equal(x.requires_full_line_collation,true);
 assert.ok(x.source_witnesses.length>0,"missing original anchor "+x.id);
 assert.ok(x.editorial_action.length>20,"missing item action "+x.id);
 assert.ok(x.observed_source_to_app_difference.length>35,"missing comparison "+x.id);
}
const hope=seen.find(x=>x.id==="foundations_act_of_hope");
assert.equal(hope.review_type,"PUBLISHED_FRENCH_SOURCE_ANOMALY");
assert.ok(hope.observed_source_to_app_difference.includes("Dans cette foi"));
const anima=seen.find(x=>x.id==="adoration_anima_christi");
assert.equal(anima.review_type,"ENGLISH_PROSE_VS_VERSE");
const meals=seen.find(x=>x.id==="foundations_grace_after_meals");
assert.equal(meals.review_type,"HISTORICAL_ALTERNATIVE_URL_PRIORITY");
assert.ok(meals.editorial_action.includes("duplicate"));
console.log("PASS 18 anchor-reviewed Prayer source variance classifications, zero false certification");
