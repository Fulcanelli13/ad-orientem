import assert from "node:assert/strict";
import {CPDV_FIRST_PASS,annotateCpdvReview} from "../tools/scripture/cpdv-first-pass.mjs";
import {CPDV_EDITORIAL_CHECKLIST} from "../tools/scripture/audit-cpdv-vs-drc.mjs";
const refs=CPDV_EDITORIAL_CHECKLIST.map(x=>x.book+" "+x.chapter+":"+x.verse);
assert.equal(refs.length,34);
assert.equal(Object.keys(CPDV_FIRST_PASS).length,34);
assert.equal(new Set(refs).size,34);
assert.deepEqual(refs.filter(x=>!CPDV_FIRST_PASS[x]),[]);
assert.equal(CPDV_FIRST_PASS["2Thessalonians 2:14"].priority,"high");
assert.equal(CPDV_FIRST_PASS["2Maccabees 12:46"].priority,"high");
assert.equal(CPDV_FIRST_PASS["John 1:1"].priority,"high");
const mock={items:refs.map(reference=>({reference,approvedForPublication:false}))};
const r=annotateCpdvReview(mock);
assert.equal(r.firstPassReviewed,34);
assert.equal(r.certified,0);
assert.equal(r.priorityCount.high+r.priorityCount.medium+r.priorityCount.low,34);
assert.ok(r.items.every(i=>i.certificate===undefined && i.approvedForPublication===false));
assert.ok(r.items.every(i=>i.firstPass.certificate==="NOT_CERTIFIED"));
assert.throws(()=>annotateCpdvReview({items:[]} ),/Unused editorial/);
console.log("All 34 first-pass doctrinal and readability observations have complete source ownership and fail-closed review gates");
