import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { LEDGER, RELEASES, LIVE } from "./helpers/sacred-places-live-baseline.mjs";
import { assertExploreGeographyRegistry, isMapPublishablePlaceGeo } from "../src/find/geography-contracts.js";
import { auditShrineSource, assertShrinesPilgrimagesRegistry } from "../src/find/shrines-contracts.js";
const j=(p)=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const manifest=j("data/geography/research/sacred-places-p61-four-source-verified-churches.v1.json");
const geo=j("data/geography/seed-registry.v1.json");
const src=j("data/shrines/source-registry.v1.json");
const heritage=j("data/explore/heritage-place-reconciliation.review.v1.json");
const shrines=j("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(manifest.schema,"AO_SACRED_PLACES_P61_FOUR_VERIFIED_CATHOLIC_BUILDINGS_V1");
assert.ok(RELEASES.some(r=>r.id==="P61"),"P61 historical release preserved");
assert.equal(RELEASES.at(-1).id,"P104");
assert.ok(LEDGER.releases.some(r=>r.id==="P61"));
assert.equal(LEDGER.releases.at(-1).id,"P104");
assert.deepEqual(manifest.baseline,{places:512,sources:810,crosswalk:512,unlinked:253,geo_areas:146,directory_links:9});
assert.deepEqual(manifest.proposed,{places:516,sources:818,crosswalk:516,unlinked:257,geo_areas:146,directory_links:9});
assert.equal(manifest.published_new.length,4);
assert.equal(LIVE.places,529);
assert.equal(LIVE.sources,844);
assert.equal(LIVE.heritage_crosswalk,529);
assert.equal(LIVE.unlinked,257);
assert.equal(geo.places.length,LIVE.places);
assert.equal(src.sources.length,LIVE.sources);
assert.equal(heritage.place_crosswalk.length,LIVE.heritage_crosswalk);
assert.equal(heritage.exception_queues.places_without_direct_claim.length,LIVE.unlinked);
assert.equal(heritage.counts.places,LIVE.places);
assert.equal(heritage.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(new Set(geo.places.map(x=>x.place_id)).size,geo.places.length);
assert.equal(new Set(src.sources.map(x=>x.id)).size,src.sources.length);
const placeMap=new Map(geo.places.map(x=>[x.place_id,x]));
const sourceMap=new Map(src.sources.map(x=>[x.id,x]));
const ours=new Set(manifest.published_new.map(x=>x.place_id));
const p92=new Set(RELEASES.find(r=>r.id==="P92").data.published_new.map(x=>x.place_id));
const p99=new Set(RELEASES.find(r=>r.id==="P99").data.published_new.map(x=>x.place_id));
const p104=new Set(RELEASES.find(r=>r.id==="P104").data.published_new.map(x=>x.place_id));
const prev=geo.places.filter(x=>!ours.has(x.place_id)&&!p92.has(x.place_id)&&!p99.has(x.place_id)&&!p104.has(x.place_id)).map(x=>x.geo?.source_ref);
assert.equal(prev.length,512);
const expected=new Map([["SG-INV-0200",208331549],["SG-INV-0429",95827233],["SG-INV-0410",426943457],["SG-INV-0493",36373669]]);
for(const x of manifest.published_new) {
  assert.equal(x.geo_source_ref,"osm:way:"+expected.get(x.candidate_id));
  assert.ok(!prev.includes(x.geo_source_ref),"Existing site OSM feature reused: "+x.candidate_id);
  const p=placeMap.get(x.place_id); assert.ok(p);
  assert.equal(p.name.official,x.name);
  assert.equal(p.place_type,x.place_type);
  assert.equal(p.address.country_code,x.country);
  assert.deepEqual(p.geo_area_ids,["geo:country:"+x.country]);
  assert.deepEqual([p.geo.lat,p.geo.lng],[x.lat,x.lng]);
  assert.equal(p.geo.source_ref,x.geo_source_ref);
  assert.equal(p.geo.source_url,x.geo_source_url);
  assert.equal(p.geo.geocoding_source,"OSM");
  assert.equal(p.geo.precision,"site");
  assert.equal(p.geo.matched_country_code,x.country);
  assert.equal(p.geo.attribution,"© OpenStreetMap contributors, ODbL 1.0");
  assert.ok(isMapPublishablePlaceGeo(p.geo,x.country));
  assert.deepEqual(p.source_ids,x.source_ids);
  assert.equal(x.source_ids.length,2);
  for(const sid of x.source_ids)assert.deepEqual(auditShrineSource(sourceMap.get(sid)),[]);
  assert.equal(sourceMap.get(x.source_ids[0]).url,x.identity_source_url);
  assert.equal(sourceMap.get(x.source_ids[0]).directness,x.source_directness);
  assert.equal(sourceMap.get(x.source_ids[1]).url,x.geo_source_url);
  assert.equal(sourceMap.get(x.source_ids[1]).directness,"SECONDARY");
  const h=heritage.place_crosswalk.find(z=>z.place_id===x.place_id);
  assert.deepEqual(h.record_ids,{},"Do not infer unrelated Shrine/Heritage crosslinks");
  assert.ok(heritage.exception_queues.places_without_direct_claim.includes(x.place_id));
  assert.ok(!geo.directoryPlaceLinks.some(z=>z.place_id===x.place_id),"No TLM venue link inference");
  assert.ok(!shrines.shrines.some(z=>z.place_id===x.place_id),"No shrine profile inference");
  for(const field of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(p[field],undefined);
}
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrines,places:geo.places,sources:src.sources}).pass,true);
assert.ok(manifest.held.some(x=>x.id==="SG-INV-0650"));
assert.ok(manifest.held.some(x=>x.id==="SG-INV-0049"));
assert.equal(manifest.photo_assets_approved,0);
assert.equal(manifest.tlm_schedule_links_added,0);
console.log("PASS historical P61 four buildings preserved under 518-place P92 release chain; source and crosswalk gates hold.");
