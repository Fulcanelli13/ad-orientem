import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {CSE_DEBATE_MAP,CSE_DEBATE_FIELDS} from "../src/learn/sexual-ethics-data/debates.js";
import {CSE_QUESTION_MAP,CSE_PUBLIC_QUESTION_MAP,CSE_SOURCE_MAP} from "../src/learn/sexual-ethics-data/index.js";
import {paragraphRefsFor} from "../src/learn/sexual-ethics-data/provenance.js";
const baseline=JSON.parse(readFileSync("data/learn/sexual-ethics-practical-relationships-source-batch-20261009.v1.json","utf8"));
const previous=JSON.parse(readFileSync("data/learn/sexual-ethics-practical-original-passages-15-20261009.v1.json","utf8"));
const next=JSON.parse(readFileSync("data/learn/sexual-ethics-practical-thirty-passages-20261009.v1.json","utf8"));
assert.equal(baseline.summary.debates,15);
assert.equal(baseline.summary.stages,120);
assert.equal(baseline.summary.category_counts.BOUNDED_ORIGINAL_SOURCE_SCOPE_CHECKED,24);
assert.equal(previous.records.length,15);
assert.equal(next.summary.cases,15);
assert.equal(next.summary.earlier_bounded_scopes,39);
assert.equal(next.summary.new_bounded_scopes,30);
assert.equal(next.summary.combined_bounded_scopes,69);
assert.equal(next.summary.remaining_unchanged_or_unbounded_stages,51);
assert.equal(next.summary.whole_debates_certified,0);
assert.equal(next.summary.independent_french_approved,0);
assert.equal(next.summary.independent_theology_approved,0);
assert.equal(next.records.length,30);
const used=new Set(previous.records.map(x=>x.id+"."+x.stage)),all=new Set(used);
const ids=baseline.cases.map(x=>x.id).sort();
assert.deepEqual([...new Set(next.records.map(x=>x.id))].sort(),ids);
for(const x of next.records){
 const key=x.id+"."+x.stage;
 assert.ok(!used.has(key),"repeated previous original passage "+key);
 assert.ok(!all.has(key),"duplicate new stage "+key);
 all.add(key);
 const caseRec=baseline.cases.find(y=>y.id===x.id);
 const original=caseRec.stages.find(y=>y.stage===x.stage);
 assert.ok(original,"stage not found "+key);
 assert.equal(x.prior_status,original.status,key);
 assert.notEqual(original.status,"BOUNDED_ORIGINAL_SOURCE_SCOPE_CHECKED");
 assert.ok(original.selected_sources.some(y=>y.id===x.source_id),"source not registered "+key);
 assert.ok(CSE_QUESTION_MAP[x.id]&&CSE_PUBLIC_QUESTION_MAP[x.id]);
 assert.ok(CSE_DEBATE_MAP[x.id]&&CSE_DEBATE_FIELDS.includes(x.stage));
 assert.ok(CSE_DEBATE_MAP[x.id][x.stage][0].length>32&&CSE_DEBATE_MAP[x.id][x.stage][1].length>32);
 assert.ok(paragraphRefsFor(CSE_QUESTION_MAP[x.id],"debate",x.stage).some(([id])=>id===x.source_id));
 assert.equal(x.original_source_url,CSE_SOURCE_MAP[x.source_id].canonical_url);
 assert.ok(x.passage_locator.length>3);
 assert.ok(x.what_original_establishes_en.length>75&&x.what_it_does_not_establish_en.length>75,key+" incomplete source scope");
 assert.ok(x.classification.length>10);
 assert.equal(x.english_original_scope_checked,true);
 for(const flag of ["french_text_independently_collated","whole_stage_text_certified","independent_theologian_approved","opposing_full_book_independently_collated","whole_debate_certified"])assert.equal(x[flag],false,key+" unsupported certification");
}
assert.equal(24+all.size,69);
const cse044=next.records.find(x=>x.id==="CSE044"&&x.stage==="opposition");
assert.equal(cse044.source_id,"CIC");
assert.match(cse044.what_it_does_not_establish_en,/illustrative/);
const cse038=next.records.find(x=>x.id==="CSE038"&&x.stage==="catholicCase");
assert.match(cse038.what_it_does_not_establish_en,/without consent/);
const cse054=next.records.find(x=>x.id==="CSE054"&&x.stage==="concession");
assert.match(cse054.what_it_does_not_establish_en,/forced intercourse/);
const farley=next.records.filter(x=>x.classification==="ORIGINAL_AUTHOR_EXCERPT_VIA_OFFICIAL_RESPONSE");
assert.equal(farley.length,4);
assert.ok(farley.every(x=>x.source_id==="FARLEY_QUOTED2012" && x.opposing_full_book_independently_collated===false));
const archived=["CSE055","CSE056","CSE058"];
assert.ok(archived.every(id=>!next.records.some(x=>x.id===id)));
console.log("PASS 30 new original passage scope checks across 15 practical debates; 69/120 bounded, 51 pending; no unsupported publication certification.");
