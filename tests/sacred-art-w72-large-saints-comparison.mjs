import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {Script} from "node:vm";
const root=new URL("../",import.meta.url);
const read=path=>readFileSync(new URL(path,root),"utf8");
const mf=JSON.parse(read("data/research/sacred-art-w72-saints-large-comparison-manifest-20261015.v1.json"));
const html=read("docs/research/review-galleries/ao-sacred-art-w72-large-saints-comparative-review-20261015.html");
