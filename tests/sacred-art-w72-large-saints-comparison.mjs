test(mf.cards.every(c=>c.score===null || Number.isInteger(c.score) && c.score>=3 && c.score<=5),"all presented scores valid and no 0-2");
test(mf.cards.filter(c=>c.score===5).length===69 && mf.cards.filter(c=>c.score===4).length===75 && mf.cards.filter(c=>c.score===3).length===53,"locked rating values");
test(mf.cards.filter(c=>c.score===null).every(c=>!c.lockedExistingScore),"fresh scores allowed only for previous nulls");
test(mf.cards.filter(c=>c.score!==null).every(c=>c.lockedExistingScore),"prior score lock");
test(mf.counts.knownPreviouslyRejectedExcluded===14,"excluded preview-bearing source IDs");
test(mf.counts.photoIdentityOrSourceHoldExcluded===25,"excluded known holds");
test(mf.subjectRequirements.some(x=>x.subject==="Saint Cyril of Alexandria"&&x.previewCount===0),"explicit Cyril Alexandria gap");
test(mf.subjectRequirements.some(x=>x.subject==="Saint Cyril of Jerusalem"&&x.previewCount===0),"explicit Cyril Jerusalem gap");
test(JSON.stringify(mf)===JSON.stringify(embedded),"embedded snapshot exact match");
test(html.includes("historicRatingsOverwritten:false"),"export preserves prior scores");
test(html.includes("explicitFiveApprovals:") && html.includes("previousScore:4"),"explicit final approval guard");
test(html.includes("scores:uniqueNew.filter("),"new scoring only on previously unrated art");
test(html.includes("subjectPreferences:") && html.includes("technicalReleaseApproved:false"),"subject fit preferences not release");
test(html.includes("if(n<4&&db.preferredArtwork"),"reject or research score clears preferred");
test(html.includes("if(name!==\"perfect\"&&db.preferredArtwork"),"elsewhere/unsuitable clears preferred");
test(html.includes("Invalid preference for a nonapproved candidate"),"import disallows invalid preferred records");
test(html.includes("localStorage.setItem") && html.includes("Import prior decisions"),"resume and import");
test(!/<script\s+src=/i.test(html),"no remote JavaScript");
