test(mf.schema==="AO_SACRED_ART_W72_ALL_SAINTS_COMPARATIVE_OWNER_VIEW_V1","W72 scoped schema");
test(mf.counts.sourceRecords===481,"481 source placements");
test(mf.counts.subjectRequirements===75,"75 source requirements");
