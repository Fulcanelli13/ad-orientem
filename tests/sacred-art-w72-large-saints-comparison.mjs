test(mf.counts.numericPreviouslyRatedShown===197,"197 earlier scored (locked)");
test(mf.counts.unratedForFirstReview===46,"46 unlabeled artworks");
test(mf.cards.filter(c=>c.score===null).length===46,"manifest numeric null exact");
test(mf.subjectRequirements.filter(s=>s.previewCount>=2).length===43,"43 compare-ready saints");
test(mf.subjectRequirements.filter(s=>s.previewCount===1).length===22,"22 one-image saints");
test(mf.subjectRequirements.filter(s=>s.previewCount===0).length===10,"10 no-image saints");
test(mf.subjectRequirements.filter(s=>s.category==="Apostles").length===13,"13 apostles in pilot");
test(mf.subjectRequirements.filter(s=>s.category==="Evangelists").length===2,"two Evangelists in pilot");
test(mf.subjectRequirements.filter(s=>s.category==="Doctors of the Church").length===28,"28 Doctors in pilot");
test(mf.subjectRequirements.filter(s=>s.category==="Other Saints").length===32,"32 other saint subjects in pilot");
test(mf.cards.every(c=>!c.excludedByUser && !c.photoIdentityHold && !c.permanentArtStyleExclusion),"reject/photo-identity/excluded artist not shown");
test(mf.cards.every(c=>!!c.image&&!!c.sourceURL),"every shown artwork photo has original source");
