#!/usr/bin/env node
import fs from "node:fs";
import crypto from "node:crypto";
import assert from "node:assert/strict";
const R="data/research/";
const report=JSON.parse(fs.readFileSync(R+"sacred-art-b53-383-review-image-audit.json","utf8"));
const idx=JSON.parse(fs.readFileSync(R+"sacred-art-b53-all383-placement-index.json","utf8"));
const html=fs.readFileSync("previews/sacred-art-b53-review-all383-placement-offline.html","utf8");
assert.equal(report.schema,"AO_B53_FULL_383_CANONICAL_ORDER_PLACEMENTS_OFFLINE_V1");
assert.equal(report.frozen_catalogue_total,451);
assert.equal(report.active_total,383);
assert.equal(report.batch_number,"all");
assert.equal(report.batch_size,383);
assert.equal(report.next_batch_start,null);
assert.equal(report.ordered_ids.length,383);
assert.equal(new Set(report.ordered_ids).size,383);
assert.equal(report.images.length,383);
assert.equal(report.placement_decisions_automatically_marked_yes_or_no,0);
assert.equal(report.frozen_decisions_automatically_mutated,0);
assert.equal(report.photo_reuse_approvals_automatically_granted,0);
assert.equal(report.source_research_images_newly_downloaded_from_original_providers,0);
assert.equal(report.image_fullresolution_originals_copied_to_public_git,0);
assert.equal(report.user_custom_destination_supported,true);
assert.equal(report.placement_suggestions_are_proposals_not_app_slot_certifications,true);
assert.equal(report.calendar_date_links_require_1962_source_verification,true);
assert.equal(report.export_import_user_decisions_supported,true);
assert.equal(report.HTML_review_in_unpublished_release_only,true);
assert.equal(report.cost_eur,0);
assert.equal(report.total_placement_proposals,report.images.reduce((n,x)=>n+x.placement_suggestions.length,0));
assert.equal(idx.total_placement_proposals,report.total_placement_proposals);
assert.equal(Buffer.byteLength(html,"utf8"),report.offline_HTML_bytes);
assert.ok(report.offline_HTML_bytes<130_000_000);
assert.equal(report.single_review_for_all_383,true);
assert.equal(report.batch_navigation_100_100_100_83,true);
assert.match(html,/301–383/);
assert.match(html,/data-range="0"/);
assert.match(html,/data-range="3"/);
assert.ok(report.images_actually_embedded_and_SHA_verified>=300);
assert.equal(report.images_actually_embedded_and_SHA_verified+report.cases_without_displayable_image,383);
assert.match(html,/const artworks=\[/);
assert.match(html,/image-opinion="like"/);
assert.match(html,/data-image-opinion="like"/);
assert.match(html,/data-image-opinion="dislike"/);
assert.match(html,/data-image-opinion="unsure"/);
assert.match(html,/No to all/);
assert.match(html,/Your placement suggestion/);
assert.match(html,/dataExport/);
assert.match(html,/AO_SACRED_ART_USER_REVIEW_PLACEMENTS_V3/);
assert.match(html,/Import saved review/);
assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|navigator\.sendBeacon|<script[^>]+src=/i);
assert.doesNotMatch(html,/<link[^>]+stylesheet[^>]+href=/i);
const match=html.match(/const artworks=(\[[\s\S]*?\]);\s*const key=/);
assert.ok(match);
const cards=JSON.parse(match[1]);
assert.equal(cards.length,383);
assert.deepEqual(cards.map(z=>z.id),report.ordered_ids);
const audit=new Map(report.images.map(z=>[z.artwork_id,z]));
let thumbs=0;
let count=0;
for(const art of cards){
 const a=audit.get(art.id);
 assert.ok(a);
 assert.equal(a.catalogue_row,art.catalogueRow);
 assert.equal(art.userPlacementDecision,null);
 assert.equal(art.photoCommercialRightsCleared,false);
 assert.ok(art.places.length>=1);
 assert.equal(new Set(art.places.map(z=>z.slot_id)).size,art.places.length);
 assert.ok(art.places.every(z=>z.decision_default==="unreviewed"&&z.label&&z.why));
 assert.deepEqual(art.places.map(z=>z.slot_id),a.placement_suggestions.map(z=>z.slot_id));
 if(art.image){
  count++;
  assert.ok(art.image.startsWith("data:image/webp;base64,"));
  assert.equal(art.sourceSHAReverified,true);
  const img=Buffer.from(art.image.split(",")[1],"base64");
  assert.equal(img.toString("ascii",0,4),"RIFF");
  assert.equal(img.toString("ascii",8,12),"WEBP");
  assert.equal(img.byteLength,a.preview_bytes);
  assert.equal(crypto.createHash("sha256").update(img).digest("hex"),a.preview_sha256);
  assert.equal(art.originalSHA,a.source_original_sha256);
  thumbs+=img.length;
 }else{
  assert.equal(a.image_displayed,false);
  assert.equal(art.sourceSHAReverified,false);
 }
}
assert.equal(count,report.images_actually_embedded_and_SHA_verified);
assert.equal(thumbs,report.total_offline_webp_bytes);
console.log("B53_ALL383_PASS "+count+" archived-source SHA verified artworks + "+(100-count)+" explicit no-image cards; "+report.total_placement_proposals+" independently unselected app placement proposals, separate artwork yes/no and freeform custom, JSON import/export, €0.");
