import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Script } from "node:vm";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const d=read("data/explore/biblical-story-scripture-three-edition-witness-collation.v2.json");
const html=readFileSync(new URL("../data/explore/biblical-story-scripture-review-offline.v2.html",import.meta.url),"utf8");
const catalogue=readFileSync(new URL("../src/scripture/catalogue.js",import.meta.url),"utf8");
assert.equal(d.schema,"AO_STORY_SCRIPTURE_THREE_EDITION_WITNESS_COLLATION_V2");
assert.equal(d.storyRows.length,14);
assert.equal(d.metadata.storyCount,14);
assert.equal(d.metadata.editionWitnesses,3);
assert.equal(d.metadata.distinctChapters,13);
assert.equal(d.verseSlotChecks.length,39);
assert.equal(d.verseSlotChecks.reduce((n,x)=>n+x.verseCount,0),1701);
assert.equal(d.metadata.blankSlots,0);
assert.equal(d.metadata.missingSlotNumbers,0);
assert.equal(d.metadata.approvedFinalRanges,0);
assert.equal(d.editionPolicy.productTraditionalDefault,"dr-challoner");
assert.equal(d.editionPolicy.productContemporaryEnglishAlternative,"cpdv-2009");
assert.equal(d.editionPolicy.productFrenchDefault,"crampon-1923");
assert.equal(d.editionPolicy.productLatinReference,"vulgate-clementine");
assert.equal(d.editionPolicy.reReviewerDefaultOnly,"cpdv-2009");
assert.equal(d.editionPolicy.productionDefaultsChanged,false);
assert.match(catalogue,/en:\s*"dr-challoner"/);
assert.match(catalogue,/cpdv-2009/);
const m=html.match(/<script type="application\/json" id="source">([\s\S]*?)<\/script>/);
assert.ok(m);
assert.deepEqual(JSON.parse(m[1]),d);
assert.ok(html.includes('<select id="englishEdition">'));
assert.ok(html.includes('value="cpdv-2009">CPDV · contemporary'));
assert.ok(html.includes('value="dr-challoner">Douay–Rheims · traditional'));
assert.ok(html.includes('englishEdition:"cpdv-2009"'));
assert.ok(html.includes('function updateOption(k,v)'));
assert.ok(html.includes('AO_STORY_SCRIPTURE_EDITORIAL_RATINGS_V2'));
assert.ok(html.includes('AO_STORY_SCRIPTURE_EDITORIAL_RATINGS_V1'));
assert.ok(!html.match(/<script[^>]+src=/));
const js=html.match(/<\/script><script>([\s\S]*?)<\/script><\/body>/);
assert.ok(js);
new Script(js[1],{filename:"scripture-review-v2.js"});
const joh=d.chapters.John[6];
assert.equal(joh["cpdv-2009"].length,72);
assert.equal(joh["dr-challoner"].length,72);
assert.equal(joh["crampon-1923"].length,71);
assert.ok(d.criticalWarnings.some(x=>x.code==="CPDV_CONTRAST_WITH_CHALLONER"));
assert.ok(d.criticalWarnings.some(x=>x.code==="JOHN6_SPLIT_VERSE_AND_OFFSET"));
assert.ok(d.criticalWarnings.some(x=>x.code==="GENESIS3_15_MARIAN_TEXT"));
assert.ok(d.criticalWarnings.some(x=>x.code==="HALF_VERSE_CUTS"));
for(const item of d.verseSlotChecks){
 const original=read("data/scripture/witness/"+item.edition+"/"+item.book+".json");
 assert.equal(original.sourceStatus,"UNCOLLATED_SOURCE_WITNESS");
 const expected=original.verses.filter(x=>x[0]===item.chapter).map(x=>[x[1],x[2]]);
 assert.deepEqual(d.chapters[item.book][item.chapter][item.edition],expected);
 assert.equal(expected.length,item.verseCount);
}
assert.deepEqual(d.productionChanges,[]);
assert.deepEqual(d.approvedChoices,[]);
console.log("Review v2: 14 stories, 13 chapters, 39 source extracts, 1701 exact source slots; CPDV reviewer default + optional Challoner + Crampon; original app roles unchanged; zero approved Scripture.");
