import assert from "node:assert/strict";
import fs from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(fs.readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const geo=load("data/geography/seed-registry.v1.json");
const sources=load("data/shrines/source-registry.v1.json");
const heritage=load("data/explore/heritage-place-reconciliation.review.v1.json");
const r90=load("data/geography/research/sacred-geography-r90-coverage-first-release.v1.json");
const r91=load("data/geography/research/sacred-geography-r91-coverage-first-release.v1.json");
const r92=load("data/geography/research/sacred-geography-r92-verified-site-cohort.v1.json");
const r93=load("data/geography/research/sacred-geography-r93-first-presence-release.v1.json");
const r89=load("data/geography/research/sacred-geography-r89-first-coverage-release.v1.json");
const r88=load("data/geography/research/sacred-geography-r88-country-category-coverage.v1.json");
const shrineCorpus=load("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(r90.schema,"AO_SACRED_GEOGRAPHY_R90_COVERAGE_FIRST_RELEASE_V1");
assert.equal(r89.result.places,306,"Prior R89 release is a frozen publication baseline");
assert.equal(r90.published_new.length,12);
assert.equal(r90.country_areas_added.length,12);
assert.equal(new Set(r90.published_new.map(x=>x.country)).size,12);
assert.equal(geo.places.length,306+r90.published_new.length+r91.published_new.length+r92.published_new.length+r93.published_new.length+6);
assert.equal(geo.geoAreas.length,100+r90.country_areas_added.length+r91.country_areas_added.length+r92.country_areas_added.length+r93.country_areas_added.length);
assert.equal(sources.sources.length,539+2*r90.published_new.length+2*r91.published_new.length+2*r92.published_new.length+2*r93.published_new.length+18);
assert.equal(new Set(geo.places.map(x=>x.place_id)).size,geo.places.length);
assert.equal(new Set(sources.sources.map(x=>x.id)).size,sources.sources.length);
assert.equal(geo.directoryPlaceLinks.length,9);
assert.equal(heritage.place_crosswalk.length,geo.places.length);
assert.equal(heritage.counts.places,geo.places.length);
assert.equal(heritage.counts.places_without_direct_claim,heritage.exception_queues.places_without_direct_claim.length);
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrineCorpus,sources:sources.sources,places:geo.places}).pass,true);
const byPlace=new Map(geo.places.map(x=>[x.place_id,x]));
const bySource=new Map(sources.sources.map(x=>[x.id,x]));
const r89Countries=new Set(r89.published_new.map(x=>x.country));
const r89Features=new Set(r89.published_new.map(x=>x.geo_source_ref));
const ids=new Set();
for(const r of r90.published_new){
 assert.ok(!ids.has(r.place_id),"Duplicate identity in R90: "+r.place_id);
 ids.add(r.place_id);
 const baseline=r88.countries.find(x=>x.iso_code===r.country);
 assert.ok(baseline&&baseline.published_places===0,"Original zero-coverage country: "+r.country);
 assert.ok(!r89Countries.has(r.country),"R89 already published country "+r.country);
 assert.ok(!r89Features.has(r.geo_source_ref),"Reused earlier map feature "+r.geo_source_ref);
 assert.ok(r90.country_areas_added.includes("geo:country:"+r.country));
 const p=byPlace.get(r.place_id);
 assert.ok(p,"R90 Place missing: "+r.place_id);
 assert.equal(p.name.official,r.name);
 assert.equal(p.place_type,r.place_type);
 assert.deepEqual(p.geo_area_ids,["geo:country:"+r.country]);
 assert.equal(p.address.country_code,r.country);
 assert.equal(p.geo.matched_country_code,r.country);
 assert.equal(p.geo.lat,r.lat);
 assert.equal(p.geo.lng,r.lng);
 assert.equal(p.geo.source_ref,r.geo_source_ref);
 assert.equal(p.geo.source_url,r.geo_source_url);
 assert.equal(p.geo.verified_at,r90.date);
 assert.ok(p.geo.attribution.includes("OpenStreetMap"));
 assert.ok(isMapPublishablePlaceGeo(p.geo,r.country));
 assert.deepEqual(p.source_ids,r.source_ids);
 assert.equal(r.source_ids.length,2);
 assert.equal(bySource.get(r.source_ids[0])?.url,r.identity_source_url);
 assert.equal(bySource.get(r.source_ids[1])?.url,r.geo_source_url);
 assert.equal(bySource.get(r.source_ids[0])?.directness,r.identity_source_directness);
 assert.equal(r.geo_source_url,"https://www.openstreetmap.org/"+r.geo_source_ref.replace(/^osm:/,"").replace(":","/"));
 assert.equal(geo.directoryPlaceLinks.some(x=>x.place_id===r.place_id),false,"No inferred TLM destination");
 assert.equal(r.tlm_status,"NO_1962_MISSAL_ASSERTION");
 assert.equal(r.access_status,"CURRENT_VISITOR_HOURS_NOT_ASSERTED");
 assert.ok(heritage.exception_queues.places_without_direct_claim.includes(r.place_id));
 const crosswalk=heritage.place_crosswalk.find(x=>x.place_id===r.place_id);
 assert.ok(crosswalk&&Object.keys(crosswalk.record_ids).length===0,"No inferred shrine/heritage links");
}
assert.equal(ids.size,12);
assert.equal(r90.tlm_venue_links_added,0);
assert.equal(r90.related_shrine_records_added,0);
assert.ok(r90.held.some(x=>x.country==="BD"&&x.research_id==="AO-R82-DISC-011"));
assert.equal(r90.result.places,318,"R90 frozen Place total");
assert.equal(r90.result.sources,563,"R90 frozen source total");
console.log("PASS R90: 12 published distinct Catholic places across 12 new jurisdictions; 306→318 Places, 539→563 sources; zero speculative TLM or shrine joins.");
