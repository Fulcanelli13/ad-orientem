import assert from "node:assert/strict";
import {readFileSync,existsSync} from "node:fs";
import {createHash} from "node:crypto";

const read=p=>JSON.parse(readFileSync(p,"utf8"));
const registry=read("data/geography/approved-place-media.v1.json");
const gallery=read("data/geography/approved-place-gallery.v1.json");
const known=read("data/geography/seed-registry.v1.json");
const release=read("data/geography/research/sacred-atlas-b7-nine-covers-integration-20261031.v1.json");
const finder=read("data/geography/research/photo-finder-20261030/decisions.json");
const approved=new Map(registry.items.filter(x=>x.status==="APPROVED").map(x=>[x.place_id,x]));
assert.equal(registry.items.length,151);
assert.equal(approved.size,151);
assert.equal(release.summary.imported_new_covers,9);
assert.equal(release.summary.superseded_existing_approved_cover,1);
assert.equal(release.summary.source_holds,10);
assert.equal(release.introduced.length,9);
const placeSet=new Set(known.places.map(p=>p.place_id));
const galleryRows=new Map(gallery.items.filter(x=>x.status==="APPROVED").map(x=>[x.media_id,x]));
let added=0;
for(const x of release.introduced){
  assert(placeSet.has(x.place_id),"Unknown canonical Place ID "+x.place_id);
  const row=approved.get(x.place_id);
  assert(row,"Missing approved source "+x.place_id);
  assert.equal(row.source_place_ref,"PHOTO_FINDER_2026-10-30_R1");
  assert.equal(row.asset_path,x.asset_path);
  assert.equal(row.source_sha1,x.source_sha1);
  assert.equal(row.derivative_sha256,x.derivative_sha256);
  assert.equal(row.credit,x.credit);
  assert.equal(row.license,x.license);
  assert.equal(row.license_url,x.license_url);
  assert(row.rights_verified&&row.subject_verified&&row.crop_reviewed,"Rights gates absent");
  assert.match(row.source_sha1,/^[a-f0-9]{40}$/);
  assert.match(row.derivative_sha256,/^[a-f0-9]{64}$/);
  assert.match(row.asset_path,/^assets\/approved\/place-media\/pf-[0-9a-f]{22}\.webp$/);
  assert(existsSync(row.asset_path),"Missing committed file "+row.asset_path);
  assert.equal(createHash("sha256").update(readFileSync(row.asset_path)).digest("hex"),row.derivative_sha256,"Source derivative changed");
  assert(finder.decisions[x.place_id]?.files?.length>0,"No earlier user selection");
  const title=decodeURIComponent(new URL(x.source_url).pathname.slice("/wiki/".length)).replaceAll("_"," ");
  assert.equal(title,finder.decisions[x.place_id].files[0],"Wrong original photographed Place");
  added++;
}
const overlap=release.superseded[0];
assert.equal(overlap.place_id,"place:ES:real-monasterio-santa-maria-guadalupe");
assert.equal(overlap.disposition,"DUPLICATE_EXISTING_APPROVED_GALLERY_COVER_NOT_IMPORTED");
const preserved=approved.get(overlap.place_id);
assert.equal(preserved.source_place_ref,"APPROVED_GALLERY_COVER_REUSE_20261031");
assert.equal(preserved.asset_path,overlap.kept_existing);
assert(galleryRows.has(preserved.gallery_media_id),"Previously approved gallery original lost");
assert(!existsSync(overlap.released_in_batch7),"Duplicate released WebP must not be committed to stacked release");
assert.equal(added,9);
console.log("PASS: 151 canonical Place covers, 9 Batch 7 originals hash-verified, 1 existing gallery overlap omitted, 10 holds retained");
