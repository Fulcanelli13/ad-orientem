import {LIVE} from "./helpers/sacred-places-live-baseline.mjs";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";

const load=path=>JSON.parse(readFileSync(new URL("../"+path,import.meta.url),"utf8"));
const geo=load("data/geography/seed-registry.v1.json");
const sources=load("data/shrines/source-registry.v1.json");
const heritage=load("data/explore/heritage-place-reconciliation.review.v1.json");
const shrines=load("data/shrines/shrines-pilgrimages-seed.v1.json");
const p16=load("data/geography/research/sacred-places-p16-three-qualified-site-release.v1.json");
const r=load("data/geography/research/sacred-places-p17-separated-bergamo-asuncion.v1.json");
assert.equal(r.schema,"AO_SACRED_PLACES_P17_THREE_DISTINCT_CANONICAL_PLACES_V1");
assert.equal(r.base.places,353);assert.equal(r.base.source_registry,639);
assert.equal(geo.places.length,LIVE.places);
assert.equal(sources.sources.length,LIVE.sources);
assert.equal(heritage.place_crosswalk.length,LIVE.places);
assert.equal(heritage.counts.places,LIVE.places);
assert.equal(heritage.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(heritage.exception_queues.places_without_direct_claim.length,LIVE.unlinked);
assert.equal(geo.geoAreas.length,141);
assert.equal(geo.directoryPlaceLinks.length,9);
assert.equal(r.published_new.length,3);
assert.equal(p16.held_exceptions.length,16);
assert.equal(r.source_queue.held_original_exception_slots,p16.held_exceptions.length);
assert.equal(new Set(geo.places.map(p=>p.place_id)).size,LIVE.places);
assert.equal(new Set(sources.sources.map(s=>s.id)).size,LIVE.sources);
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrines,sources:sources.sources,places:geo.places}).pass,true);
const placeById=new Map(geo.places.map(p=>[p.place_id,p]));
const sourceById=new Map(sources.sources.map(s=>[s.id,s]));
for(const release of r.published_new){
 const p=placeById.get(release.place_id);
 assert.ok(p,"P17 missing exact canonical Place "+release.place_id);
 assert.equal(p.name.official,release.name);
 assert.equal(p.address.country_code,release.country);
 assert.equal(p.geo.matched_country_code,release.country);
 assert.equal(p.mappable,true);
 assert.equal(p.geo.precision,"site","P17 site polygon cannot be represented as verified entrance");
 assert.equal(p.geo.geocoding_source,"OSM");
 assert.equal(p.geo.source_ref,"osm:way:"+release.osm_way);
 assert.equal(p.geo.source_url,"https://www.openstreetmap.org/way/"+release.osm_way);
 assert.equal(p.geo.lat,release.lat);assert.equal(p.geo.lng,release.lng);
 assert.match(p.geo.attribution,/OpenStreetMap/);
 assert.ok(isMapPublishablePlaceGeo(p.geo,p.address.country_code));
 assert.deepEqual(p.source_ids,release.source_ids);
 assert.ok(p.source_ids.length>=2);
 for(const id of release.source_ids){
  const source=sourceById.get(id);
  assert.ok(source,"P17 missing original source "+id);
  assert.match(source.url,/^https:\/\//);
  assert.ok(source.directness&&source.contribution);
 }
 assert.equal(geo.directoryPlaceLinks.some(x=>x.place_id===p.place_id),false,"No unverified 1962 venue link");
 assert.equal(shrines.shrines.some(x=>x.place_id===p.place_id),false,"No inferred Shrine owner");
 const row=heritage.place_crosswalk.filter(x=>x.place_id===p.place_id);
 assert.equal(row.length,1);
 assert.deepEqual(row[0].record_ids,{});
 assert.ok(heritage.exception_queues.places_without_direct_claim.includes(p.place_id));
}
const bergamo=placeById.get("place:IT:basilica-santa-maria-maggiore-bergamo");
assert.equal(bergamo.place_type,"basilica");
assert.ok(!bergamo.name.official.includes("Neve"),"Avoid conflated Madonna della Neve shrine name");
const cathedral=placeById.get("place:PY:catedral-metropolitana-asuncion");
const oratory=placeById.get("place:PY:oratorio-nuestra-senora-asuncion-panteon");
assert.equal(cathedral.place_type,"cathedral");
assert.equal(oratory.place_type,"chapel");
assert.notEqual(oratory.geo.source_ref,cathedral.geo.source_ref);
const d=Math.hypot((cathedral.geo.lat-oratory.geo.lat)*111195,(cathedral.geo.lng-oratory.geo.lng)*111195*Math.cos(cathedral.geo.lat*Math.PI/180));
assert.ok(d>150&&d<400,"Separate Asunción Cathedral from Oratory/National Pantheon");
assert.equal(r.proposed.new_approved_media,0);
assert.equal(r.proposed.new_directory_place_links,0);
assert.equal(r.proposed.new_shrines_owner_records,0);
console.log("PASS P17 original three Catholic buildings preserved in current 371-Place / 669-source live registry, 16 original title/identity holds unchanged");
