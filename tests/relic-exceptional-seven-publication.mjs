import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {auditPlaceGeo,assertExploreGeographyRegistry} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
import {projectExploreDataset} from "../src/find/explore-projection.js";
import {exploreMapFeatures} from "../src/find/map-runtime.js";
import {buildExploreViewModel,renderExploreToString} from "../src/find/explore-presentation.js";
const read=path=>JSON.parse(readFileSync(path,"utf8"));
const publication=read("data/explore/relic-exceptional-seven-publication.2026-10-09.json");
const research=read("data/explore/relic-exceptional-sacred-objects.review.v1.json");
const geo=read("data/geography/seed-registry.v1.json");
const sacred=read("data/explore/sacred-phenomena-seed.v1.json");
const shrine=read("data/shrines/shrines-pilgrimages-seed.v1.json");
const sources=read("data/shrines/source-registry.v1.json");
assert.equal(publication.schema,"SACRED_ATLAS_EXCEPTIONAL_SEVEN_PUBLICATION_EVIDENCE_V1");
assert.equal(publication.sites.length,7);
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({shrines:shrine.shrines,pilgrimages:shrine.pilgrimages,routes:shrine.routes,temporalLinks:shrine.temporalLinks,sources:sources.sources,places:geo.places}).pass,true);
const counts=[geo.places.length,shrine.shrines.length,shrine.pilgrimages.length,sources.sources.length,sacred.relics.length];
assert.deepEqual(counts,[181,177,205,260,121]);
const geos=new Map(geo.places.map(p=>[p.place_id,p]));
const groups=new Map(research.groups.map(g=>[g.object_group_id,g]));
const pins=new Set(),oldGroups=research.groups.filter(g=>!g.research_candidate_id);
assert.equal(oldGroups.length,8);
assert.ok(oldGroups.every(g=>g.current_map_change===false));
for(const s of publication.sites){
 const placeId="place:"+s.slug,relicId="relic:"+s.slug,shrineId="shrine:"+s.slug,sourceId="SHR-"+s.slug.replace(":","-");
 assert.ok(!pins.has(placeId),"duplicate exceptional Place");pins.add(placeId);
 const place=geos.get(placeId),relic=sacred.relics.find(r=>r.id===relicId);
 assert.ok(place&&relic,placeId+" missing canonical records");
 assert.equal(auditPlaceGeo(place.geo,{countryCode:s.country}).length,0);
 assert.equal(place.geo.source_url,s.geo);
 assert.equal(place.geo.matched_country_code,s.country);
 assert.equal(relic.place_id,placeId);
 assert.equal(relic.source_url,s.primary);
 assert.equal(relic.object_group_id,s.group);
 assert.equal(relic.material_category,s.material);
 assert.equal(relic.authentication,"NOT_INDEPENDENTLY_CERTIFIED_BY_APP");
 assert.equal(relic.attribution_class,"TRADITIONAL_IDENTITY_NOT_INDEPENDENTLY_AUTHENTICATED");
 assert.equal(relic.calendar_semantic_key,null);
 assert.ok(relic.title_fr&&relic.summary_fr&&relic.display_notice_fr);
 assert.ok(relic.title_en&&relic.summary_en&&relic.display_notice_en);
 assert.doesNotMatch(relic.summary_en,/is (certainly|scientifically|canonically) authentic|proven to be (Christ|Mary)/i);
 assert.equal(sacred.relics.filter(r=>r.place_id===placeId).length,1,"Objects must be grouped under one Place");
 const shrineRecord=shrine.shrines.find(r=>r.shrine_id===shrineId);
 assert.equal(shrineRecord?.place_id,placeId);
 assert.equal(shrineRecord?.shrine_kind,"CHRISTOLOGICAL");
 assert.equal(shrine.pilgrimages.filter(r=>r.destination_shrine_id===shrineId).length,1);
 assert.equal(sources.sources.filter(r=>r.id===sourceId&&r.url===s.primary).length,1);
 const decision=groups.get(s.group);
 assert.ok(decision&&decision.current_map_change);
 assert.equal(decision.existing_place_id,placeId);
 assert.equal(decision.research_candidate_id,s.candidate);
 assert.equal(decision.canonical_relic_class,"EXCEPTIONAL_SACRED_OBJECT_NOT_AUTOMATICALLY_FIRST_SECOND_OR_THIRD");
 assert.ok(s.geo.startsWith("https://")&&s.primary.startsWith("https://"));
}
const projected=projectExploreDataset({geography:geo,sacredPhenomena:sacred,shrines:shrine});
const items=projected.byLens.relics;
assert.equal(items.length,121);
const features=exploreMapFeatures(items);
assert.equal(features.length,new Set(items.filter(i=>i.map_publishable).map(i=>i.place_id)).size,"One relic marker per physical Place");
for(const placeId of pins)assert.equal(features.filter(f=>f.properties.item_id==="relics:relic:"+placeId.slice(6)).length,1,placeId+" lost map marker");
for(const s of publication.sites){
 const id="relic:"+s.slug,item=items.find(i=>i.source_id===id);
 assert.ok(item?.sections.some(section=>section.label==="Exposition & visitor access"),"Source-specific visitor guidance absent "+id);
 assert.ok(!item.sections.some(section=>section.title==="Temporary closure"),"Ordinary display restriction falsely labelled closure "+id);
 const rendered=renderExploreToString(buildExploreViewModel({language:"fr",lens:"relics",view:"list",items:[item],selectedId:item.item_id,counts:{relics:1}}));
 assert.ok(rendered.includes("Ostension et accès"),"French reader missing special-access explanation "+id);
}
const aachen=publication.sites.find(s=>s.group==="sacred-object-group:aachen-four-cloths");
assert.equal(aachen.groupCount,4);
assert.match(aachen.access_en,/2028/);
assert.match(publication.sites.find(s=>s.group==="sacred-object-group:trier-holy-robe").access_en,/not ordinarily visible/);
assert.match(publication.sites.find(s=>s.group==="sacred-object-group:cahors-sainte-coiffe").access_en,/viewed from outside/);
assert.match(publication.sites.find(s=>s.group==="sacred-object-group:fecamp-blood").claim_en,/two differing medieval/);
assert.match(publication.sites.find(s=>s.group==="sacred-object-group:manoppello-face").claim_en,/Roman Veronica/);
assert.ok(research.groups.filter(g=>g.current_map_change).length===7);
console.log("PASS 7 exceptional-object physical Places, 7 grouped relic records, one marker per Place, bilingual access notices, original institutional sources and distinct object identity claims");
