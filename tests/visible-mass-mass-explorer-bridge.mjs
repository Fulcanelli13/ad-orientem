import assert from "node:assert/strict";
import fs from "node:fs";
import {projectVisibleMassExplorer} from "../previews/visible-mass-3d/photographic-mass-explorer-bridge.mjs";
const guide=JSON.parse(fs.readFileSync("data/presentation/guide-registry.v1.json","utf8"));
const formation=JSON.parse(fs.readFileSync("data/learn/mass-formation-campion.v1.json","utf8"));
const p=projectVisibleMassExplorer(guide,formation);
assert.equal(p.publishedGuideCount,32);
assert.equal(p.sourceFormationCount,8);
assert.equal(p.photographicEvidenceCount,3);
assert.deepEqual(p.phases.map(x=>x.stops.length),[1,9,9,7,6]);
assert.equal(p.stops[0].id,"PRE.ASPERGES");
assert.equal(p.stops[31].id,"POST.MASS");
assert.equal(p.stops[15].id,"AO.CARD.015");
assert.equal(p.stops[16].id,"AO.CARD.016");
assert.equal(p.stops[15].title,guide.entries["AO.CARD.015"].moment);
assert.equal(p.stops[15].short,guide.entries["AO.CARD.015"].short);
assert.equal(p.stops[15].formationStageId,"MF05");
assert.equal(p.stops[15].photoContext[0].relation,"BROADER_ELEVATION_CONTEXT_REQUIRES_VISUAL_QA");
assert.equal(p.stops[24].id,"AO.CARD.024");
assert.equal(p.stops[24].photoContext[0].photoIndex,2);
assert.ok(p.stops.every(x=>x.readerPresentation48Equivalence===false));
assert.equal(p.isPublishedMassReader,false);
assert.equal(p.independentAnswersPublished,false);
assert.throws(()=>projectVisibleMassExplorer(guide,formation,{massForm:"LOW"}),/Only published Sung Guide/);
assert.throws(()=>projectVisibleMassExplorer({...guide,status:"DRAFT"},formation),/continuity-certified/);
assert.throws(()=>projectVisibleMassExplorer(guide,{...formation,stages:[]}),/eight-stage/);
console.log("PASS Visible Mass photographic Mass Explorer: 32 certified Guide stops, 5 phases, 8 Formation owners, 3 independent photograph links; no reader mutation");
