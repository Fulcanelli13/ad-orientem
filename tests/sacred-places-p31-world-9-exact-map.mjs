assert.equal(p16.held_exceptions.length,16);assert.equal(m.p16_protected_holds,16);
assert.equal(m.published_new.length,9);assert.equal(new Set(m.published_new.map(x=>x.country)).size,8);
assert.equal(new Set(m.published_new.map(x=>x.place_id)).size,9);
assert.equal(new Set(m.published_new.map(x=>x.geo_source_ref)).size,9);
assert.ok(RELEASES.some(x=>x.id==="P31"));
assert.equal(m.new_first200_source_excerpts,9);assert.equal(m.first200_source_excerpt_coverage_if_merged,136);
assert.equal(m.unreviewed_first200_after_release,64);
const ids=new Map(geo.places.map(x=>[x.place_id,x])),sources=new Map(ss.sources.map(x=>[x.id,x]));
assert.equal(ids.size,geo.places.length);assert.equal(sources.size,ss.sources.length);
const earlierRefs=new Set(geo.places.filter(x=>!m.published_new.some(y=>y.place_id===x.place_id)).map(x=>x.geo?.source_ref).filter(Boolean));
const byP29=new Map(p29.remaining_95_source_screen.map(x=>[x.candidate_id,x]));
for(const r of m.published_new){
 assert.equal(byP29.get(r.candidate_id)?.source_excerpt,null);
 assert.ok(!earlierRefs.has(r.geo_source_ref));
 assert.match(r.geo_source_ref,/^osm:way:\d+$/);assert.match(r.geo_provenance_mapcarta_url,/^https:\/\/mapcarta.com\//);
 const p=ids.get(r.place_id);assert.ok(p,"missing physical site "+r.place_id);
 assert.equal(p.name.official,r.name);assert.equal(p.place_type,r.place_type);assert.equal(p.address.country_code,r.country);
 assert.equal(p.geo.matched_country_code,r.country);assert.deepEqual([p.geo.lat,p.geo.lng],[r.lat,r.lng]);
 assert.deepEqual(p.geo_area_ids,["geo:country:"+r.country]);
 assert.equal(p.geo.source_ref,r.geo_source_ref);assert.equal(p.geo.source_url,r.geo_source_url);
 assert.equal(p.geo.precision,"site");assert.ok(isMapPublishablePlaceGeo(p.geo,r.country));
 assert.deepEqual(p.source_ids,r.source_ids);assert.equal(p.source_ids.length,1);
 const s=sources.get(p.source_ids[0]);assert.ok(s);assert.equal(auditShrineSource(s).length,0);
 assert.equal(s.url,r.identity_source_url);
 assert.ok(cross.exception_queues.places_without_direct_claim.includes(r.place_id));
 assert.deepEqual(cross.place_crosswalk.find(x=>x.place_id===r.place_id).record_ids,{});
 assert.ok(!geo.directoryPlaceLinks.some(x=>x.place_id===r.place_id));
 assert.ok(!shrines.shrines.some(x=>x.place_id===r.place_id));
 for(const field of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(p[field],undefined);
}
assert.equal(ids.get("place:CH:pfarr-wallfahrtskirche-st-theodul-sachseln").name.official,"Pfarr- und Wallfahrtskirche St. Theodul, Sachseln");
