import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {renderVerifiedStationArtwork} from "../src/pray/stations-verified-artwork-release.v1.js";
const base="data/prayer/stations/san-polo-tiepolo-oils-1747/";
const data=JSON.parse(readFileSync(base+"cc-by-sa-complete-series-release-candidate.v1.json","utf8"));
const archive=JSON.parse(readFileSync(base+"acquisition-results.v1.json","utf8"));
const attribution=readFileSync("assets/stations/san-polo/LICENSE-ATTRIBUTION.md","utf8");
assert.equal(data.assetCount,14);
assert.equal(data.entries.length,14);
assert.equal(archive.files.length,14);
assert.equal(data.licensing.photographs,"CC BY-SA 4.0");
assert.equal(data.licensing.zeroCost,true);
assert.equal(data.licensing.contactRequired,false);
assert.equal(data.licensing.compatibleWithCurrentAO_StrictPDCC0OnlyPolicy,false);
assert.equal(data.licensing.scopedExceptionAuthorized,false);
assert.equal(data.runtimeImageCount,0);
assert.match(attribution,/Didier Descouens/);
assert.match(attribution,/Attribution–ShareAlike 4.0/);
assert.match(attribution,/Richard Stracke/);
const sha=new Set();
for(const [i,row] of data.entries.entries()){
 assert.equal(row.station,i+1);
 assert.match(row.sourceFilePage,/commons.wikimedia.org\/wiki\/File:/);
 assert.equal(row.sourcePhotographLicense,"CC BY-SA 4.0");
 assert.equal(row.productionEnabled,false);
 assert.equal(row.productionPolicyExceptionAuthorized,false);
 assert.equal(row.previouslyApprovedArtworkPreserved,true);
 const local="assets/stations/san-polo/station-"+String(i+1).padStart(2,"0")+".webp";
 assert.equal(row.localPublicAsset,"/"+local);
 const source=readFileSync(row.repositoryOriginal);
 const target=readFileSync(local);
 assert.equal(Buffer.compare(source,target),0,"Git blob copy must match verified original for Station "+row.roman);
 assert.equal(createHash("sha256").update(target).digest("hex"),row.sha256);
 assert.ok(!sha.has(row.sha256));sha.add(row.sha256);
 assert.equal(renderVerifiedStationArtwork(i), "","No unapproved runtime use");
 assert.equal(row.mobileRun,"PENDING");
}
assert.equal(sha.size,14);
assert.equal(archive.productionImagesEnabled,0);
console.log("PASS 14/14 identical verified WebPs in /assets/stations/san-polo; exact source and CC BY-SA metadata; rights exception absent and all live images gated");
