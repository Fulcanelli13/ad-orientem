import assert from "node:assert/strict";
import fs from "node:fs";
import {createHash} from "node:crypto";
import {attachApprovedDirectoryMedia,eligibleDirectoryImage,DIRECTORY_CARD_STYLE,renderDirectoryVenueCard} from "../src/find/directory-card.js";
import {buildExploreViewModel,renderExploreToString} from "../src/find/explore-presentation.js";
const read=p=>JSON.parse(fs.readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const registry=read("data/geography/seed-registry.v1.json");
const covers=read("data/geography/approved-place-media.v1.json");
const source=read("data/directory/research/p102-three-photo-approved-media-source-lock.json");
const audit=read("data/directory/research/p102-three-photo-approved-bytes-audit.json");
const release=read("data/geography/research/directory-p102-three-approved-covers.v1.json");
const gallery=read("data/geography/approved-place-gallery.v1.json");
const digest=v=>createHash("sha256").update(v).digest("hex");
assert.equal(release.schema,"AO_P102_THREE_VERIFIED_DIRECTORY_COVERS_V1");
assert.equal(source.schema,"AO_P102_THREE_SOURCE_LOCKED_CHURCH_COVERS_RELEASE_INPUT_V1");
assert.equal(audit.schema,"AO_P102_PHOTO_SOURCE_BYTES_RELEASE_AUDIT_V1");
assert.deepEqual([registry.places.length,registry.directoryPlaceLinks.length],[530,23]);
assert.ok(covers.items.length>=40,"Historical P102 release remains intact as new covers are approved");
assert.equal(release.counts.existing_approved_covers,33);
assert.equal(release.counts.proposed_approved_covers,36);
assert.equal(release.counts.added_approved_covers,3);
assert.equal(release.counts.schedule_or_calendar_claims_added,0);
assert.equal(release.counts.place_registry_new_entries,0);
assert.equal(release.counts.rights_fee_eur,0);
assert.equal(audit.copied,3);
assert.equal(source.records.length,3);
assert.equal(release.photos.length,3);
const approvedPlaces=new Set(source.records.map(p=>p.place_id));
assert.equal(approvedPlaces.size,3);
for(const p of source.records){
 const matches=covers.items.filter(m=>m.place_id===p.place_id);
 assert.equal(matches.length,1,"Each exact Place gets precisely one new cover");
 const img=matches[0];
 assert.equal(img.status,"APPROVED");
 assert.ok(eligibleDirectoryImage(img,p.place_id));
 assert.equal(eligibleDirectoryImage(img,p.place_id+"-incorrect"),false,"No cross-place media reuse");
 assert.equal(img.asset_path,p.approved_path);
 assert.equal(img.derivative_sha256,p.sha256);
 assert.equal(img.source_sha1,p.source_sha1);
 assert.equal(img.source_url,p.source_url);
 assert.equal(img.license,p.license);
 assert.equal(img.license_url,p.license_url);
 assert.equal(img.credit,p.credit);
 assert.equal(img.source_place_ref,p.source_place_ref);
 assert.deepEqual([img.width,img.height],[p.width,p.height]);
 assert.equal(img.crop_reviewed,true);
 assert.equal(img.subject_verified,true);
 assert.equal(img.rights_verified,true);
 assert.ok(img.changes_en.toLowerCase().includes("no cropping"));
 assert.ok(img.changes_fr.toLowerCase().includes("sans recadrage"));
 assert.ok(img.alt_en.length>30&&img.alt_fr.length>30);
 assert.ok(img.source_url.startsWith("https://commons.wikimedia.org/wiki/File:"));
 assert.ok(img.license_url.startsWith("https://creativecommons.org/"));
 const bytes=fs.readFileSync(new URL("../"+img.asset_path,import.meta.url));
 assert.equal(bytes.length,p.bytes);
 assert.equal(digest(bytes),p.sha256);
 assert.equal(bytes.toString("ascii",0,4),"RIFF");
 assert.equal(bytes.toString("ascii",8,12),"WEBP");
 const srcRecord=audit.records.find(r=>r.place_id===p.place_id);
 assert.ok(srcRecord);
 assert.equal(srcRecord.sha256,p.sha256);
 assert.equal(srcRecord.copy_exact,true);
 assert.equal(srcRecord.reencoded,false);
 const matchesLink=registry.directoryPlaceLinks.filter(l=>l.venue_id===p.venue_id);
 assert.equal(matchesLink.length,1);
 assert.equal(matchesLink[0].place_id,p.place_id);
 assert.equal(matchesLink[0].confidence,"CONFIRMED");
 assert.equal(matchesLink[0].relationship,"LOCATED_AT");
 const items=attachApprovedDirectoryMedia([{
  kind:"TLM_VENUE",source_id:p.venue_id,title:"Exact church",item_id:"tlm:"+p.venue_id,
  subtitle:"Physical church",lens:"tlm",source_links:[{url:p.source_url}]
 }],{directoryPlaceLinks:registry.directoryPlaceLinks,approved:covers.items,gallery:gallery.items});
 assert.equal(items[0].place_id,p.place_id);
 assert.equal(items[0].cover_media?.asset_path,p.approved_path);
 const english=renderDirectoryVenueCard(items[0],"en");
 const french=renderDirectoryVenueCard(items[0],"fr");
 assert.ok(english.includes(p.approved_path)&&english.includes(p.alt_en));
 assert.ok(french.includes(p.approved_path)&&french.includes(p.alt_fr.replaceAll("&","&amp;").replaceAll("\x27","&#039;")),"French alt text must be HTML-safe and retained");
 const vm=buildExploreViewModel({language:"en",lens:"tlm",items,view:"map",selectedId:"tlm:"+p.venue_id,filters:{directoryGroup:"ALL"}});
 const html=renderExploreToString(vm);
 assert.ok(html.includes("aoTlmPreviewPhoto"));
 assert.ok(html.includes("aoTlmPreviewPhotoCredit"));
 assert.ok(html.includes(p.credit));
 assert.ok(html.includes(p.license_url));
 assert.ok(html.includes(p.source_url));
 const releasePhoto=release.photos.find(x=>x.place_id===p.place_id);
 assert.equal(releasePhoto?.derivative_sha256,p.sha256);
 assert.equal(releasePhoto.status,"APPROVED_IN_PR_NOT_LIVE");
}
// The problematic Pau image remains excluded, not silently promoted.
const held="place:FR:saint-louis-de-gonzague-pau";
assert.equal(covers.items.some(x=>x.place_id===held),false);
assert.ok(release.holds.some(x=>x.place_id===held&&x.new_cover===false));
const unknown=attachApprovedDirectoryMedia([{kind:"TLM_VENUE",source_id:"unknown-nearby-venue"}],{
 directoryPlaceLinks:registry.directoryPlaceLinks,approved:covers.items,gallery:gallery.items
});
assert.equal(unknown[0].cover_media,undefined);
assert.ok(DIRECTORY_CARD_STYLE.includes("object-fit:contain;object-position:center"));
assert.ok(DIRECTORY_CARD_STYLE.includes("aoTlmDetailPhoto img"));
assert.ok(DIRECTORY_CARD_STYLE.includes("max-height:300px;object-fit:contain"));
console.log("P102 PASS — 3 exact approved source-authored WebPs, bytes + EN/FR credit links + full-frame cards; Pau held");
