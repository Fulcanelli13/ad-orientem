import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const load=p=>JSON.parse(readFileSync(p,'utf8'));
const previous=load('data/customs/master/pitre-1900-feste-patronali-original-edition-ocr-actions-wave01.v1.json');
const old1=load('data/customs/master/pitre-1900-new-rosalia-cosmas-piazza-original-ocr-stage01.v1.json');
const old2=load('data/customs/master/pitre-1900-new-gangi-gratteri-geraci-marineo-original-ocr-stage02.v1.json');
const wave=load('data/customs/master/pitre-1900-original-ocr-unmined-messina-ragusa-scicli-comiso-mazara-calatafimi-wave03.v1.json');
const master=load('data/customs/master/comprehensive-customs-working-catalogue.v1.json');
const scan=load('data/customs/master/pitre-1900-uploaded-facsimile-25p0-16-wave03-page-gates.v1.json');
const scannedNew=new Set(scan.additional_wave03_highrisk_page_checks.map(r=>r.source_id));
assert.equal(previous.records.length,129);
assert.equal(old1.records.length+old2.records.length,121);
assert.equal(wave.records.length,172);
assert.equal(master.external_source_observations_pitre_original_1900_ocr.length,129);
assert.equal(master.external_source_observations_pitre_original_1900_new_ocr.length,293);
assert.equal(master.summary.source_observations.total_source_detail_rows_including_external,3407);
assert.equal(master.summary.identity_working_rows.provisional_after_53_no_owner_action_review,408);
const ids=new Set(previous.records.map(r=>r.id));
const raw=[...old1.records,...old2.records,...wave.records];
for(let i=0;i<raw.length;i++){
 const r=raw[i],m=master.external_source_observations_pitre_original_1900_new_ocr[i];
 assert.equal(r.id,'PIT1900-NEW-'+String(i+1).padStart(3,'0'));
 assert.ok(!ids.has(r.id)); ids.add(r.id);
 assert.equal(m.id,r.id);
 assert.equal(m.original_printed_folio_verified,scannedNew.has(m.id));
 assert.equal(m.official_1962_rite_approved,false);
 assert.equal(m.unique_practice_identity_certified,false);
 assert.equal(m.source_independence_certified,false);
 assert.equal(m.present_continuity_certified,false);
 assert.equal(m.publication_state,'RESEARCH_ONLY');
 assert.equal(m.working_master_owner,null);
}
assert.equal(ids.size,422);
assert.equal(wave.summary.new_source_action_detail_observations,172);
assert.equal(wave.summary.original_folio_images_verified,0);
assert.equal(wave.summary.certified_distinct_customs,0);
assert.equal(wave.summary.app_publications,0);
assert.deepEqual(wave.summary.section_counts,{MESSINA_ASSUNTA:47,RAGUSA_GEORGE_JOHN:40,SCICLI_MILIZIE:33,COMISO_EASTER:15,MAZARA_ST_VITUS:20,CALATAFIMI_CRUCIFIX:17});
assert.equal(master.summary.source_observations.pitre_1900_original_all_new_sections_ocr_details,293);
assert.equal(master.summary.source_review.pitre_1900_new_293_verified_unique_customs,0);
assert.equal(master.summary.source_review.pitre_1900_new_293_original_folio_images_verified,0);
assert.equal(master.summary.no_new_app_publications,true);
console.log('Pitrè 1900 source audit: 129 original + 293 new source details = 422 provenance records, 3407 corpus rows, zero promotion — PASS');
