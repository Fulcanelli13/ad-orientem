import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {auditShrineSource,assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=load("data/geography/research/sacred-places-p34-thirteen-audited-churches.v1.json");
const geo=load("data/geography/seed-registry.v1.json"),src=load("data/shrines/source-registry.v1.json");
const heritage=load("data/explore/heritage-place-reconciliation.review.v1.json");
const shrines=load("data/shrines/shrines-pilgrimages-seed.v1.json");
const p16=load("data/geography/research/sacred-places-p16-three-qualified-site-release.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P34_THIRTEEN_AUDITED_EXACT_CHURCHES_V1");
assert.deepEqual(Object.values(m.baseline),[414,712,414,155,141,9]);
assert.deepEqual(Object.values(m.proposed),[427,725,427,168,141,9]);
assert.ok(RELEASES.some(r=>r.id==="P34"));
assert.deepEqual([geo.places.length,src.sources.length,heritage.place_crosswalk.length,heritage.exception_queues.places_without_direct_claim.length,geo.geoAreas.length,geo.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
assert.equal(heritage.counts.places,LIVE.places);
assert.equal(heritage.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(m.published_new.length,13);
assert.equal(new Set(m.published_new.map(x=>x.candidate_id)).size,13);
assert.equal(new Set(m.published_new.map(x=>x.place_id)).size,13);
assert.equal(new Set(m.published_new.map(x=>x.geo_source_ref)).size,13);
assert.equal(p16.held_exceptions.length,16);
assert.equal(m.p16_protected_historical_exceptions,16);
assert.equal(m.photo_assets_approved,0);
assert.equal(m.tlm_schedule_links_added,0);
assert.equal(m.new_country_area_count,0);
const placeById=new Map(geo.places.map(x=>[x.place_id,x]));
const sourceById=new Map(src.sources.map(x=>[x.id,x]));
assert.equal(placeById.size,geo.places.length);
assert.equal(sourceById.size,src.sources.length);
const incomingIds=new Set(m.published_new.map(x=>x.place_id));
const p34Index=RELEASES.findIndex(r=>r.id==="P34");
assert.ok(p34Index>=0);
const laterReleaseIds=new Set(RELEASES.slice(p34Index+1).flatMap(r=>(r.data.published_new||[]).map(x=>x.place_id)));
const oldPlaces=geo.places.filter(p=>!incomingIds.has(p.place_id)&&!laterReleaseIds.has(p.place_id));
assert.equal(oldPlaces.length,m.baseline.places);
const oldRefs=new Set(oldPlaces.map(p=>p.geo?.source_ref).filter(Boolean));
for(const row of m.published_new){
 assert.match(row.geo_source_ref,/^osm:way:\d+$/);
 assert.equal(row.geo_source_url,"https://www.openstreetmap.org/way/"+row.geo_source_ref.split(":")[2]);
 assert.ok(!oldRefs.has(row.geo_source_ref),"Earlier physical map feature already exists: "+row.geo_source_ref);
 assert.ok(geo.geoAreas.some(x=>x.geo_area_id==="geo:country:"+row.country));
 const p=placeById.get(row.place_id);assert.ok(p,"Missing canonical Place "+row.place_id);
 assert.equal(p.name.official,row.name);
 assert.equal(p.place_type,row.place_type);
 assert.equal(p.address.country_code,row.country);
 assert.deepEqual(p.geo_area_ids,["geo:country:"+row.country]);
 assert.deepEqual([p.geo.lat,p.geo.lng],[row.lat,row.lng]);
 assert.equal(p.geo.precision,"site");
 assert.equal(p.geo.geocoding_source,"OSM");
 assert.equal(p.geo.source_ref,row.geo_source_ref);
 assert.equal(p.geo.source_url,row.geo_source_url);
 assert.equal(p.geo.matched_country_code,row.country);
 assert.equal(p.geo.verified_at,m.date);
 assert.ok(isMapPublishablePlaceGeo(p.geo,row.country));
 assert.deepEqual(p.source_ids,row.source_ids);
 assert.equal(p.source_ids.length,1);
 const s=sourceById.get(p.source_ids[0]);assert.ok(s);
 assert.deepEqual(auditShrineSource(s),[]);
 assert.equal(s.url,row.identity_source_url);
 assert.equal(s.issuer,row.identity_source_issuer);
 assert.equal(s.directness,row.source_directness);
 const cross=heritage.place_crosswalk.filter(x=>x.place_id===row.place_id);
 assert.equal(cross.length,1);
 assert.deepEqual(cross[0].record_ids,{});
 assert.ok(heritage.exception_queues.places_without_direct_claim.includes(row.place_id));
 assert.ok(!geo.directoryPlaceLinks.some(x=>x.place_id===row.place_id));
 assert.ok(!shrines.shrines.some(x=>x.place_id===row.place_id));
 for(const forbidden of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(p[forbidden],undefined);
}
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrines,sources:src.sources,places:geo.places}).pass,true);
console.log("PASS P34: 13 distinct institution-attested Catholic church sites; "+LIVE.places+" canonical Places, "+LIVE.sources+" typed sources; historical holds and Directory protected");
