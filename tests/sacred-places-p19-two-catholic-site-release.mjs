import {LIVE} from "./helpers/sacred-places-live-baseline.mjs";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=path=>JSON.parse(readFileSync(new URL("../"+path,import.meta.url),"utf8"));
const geo=load("data/geography/seed-registry.v1.json");
const src=load("data/shrines/source-registry.v1.json");
const cross=load("data/explore/heritage-place-reconciliation.review.v1.json");
const shrineCorpus=load("data/shrines/shrines-pilgrimages-seed.v1.json");
const prior=load("data/geography/research/sacred-places-p16-three-qualified-site-release.v1.json");
const r=load("data/geography/research/sacred-places-p19-two-catholic-site-release.v1.json");
assert.equal(r.schema,"AO_SACRED_PLACES_P19_TWO_CATHOLIC_SITE_RELEASE_V1");
assert.deepEqual([r.baseline.places,r.baseline.source_registry,r.baseline.heritage_crosswalk],[359,653,359]);
assert.deepEqual([geo.places.length,src.sources.length,cross.place_crosswalk.length],[LIVE.places,LIVE.sources,LIVE.places]);
assert.equal(cross.counts.places,LIVE.places);
assert.equal(cross.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(cross.exception_queues.places_without_direct_claim.length,LIVE.unlinked);
assert.equal(geo.geoAreas.length,LIVE.areas);
assert.equal(geo.directoryPlaceLinks.length,LIVE.links);
assert.equal(new Set(geo.places.map(x=>x.place_id)).size,LIVE.places);
assert.equal(new Set(src.sources.map(x=>x.id)).size,LIVE.sources);
assert.equal(r.published_new.length,2);
assert.equal(r.proposed.original_p16_exception_holds,16);
assert.equal(prior.held_exceptions.length,16);
assert.equal(r.hold_status,"NO_ORIGINAL_EXCEPTION_CLOSURE");
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrineCorpus,sources:src.sources,places:geo.places}).pass,true);
const byPlace=new Map(geo.places.map(x=>[x.place_id,x]));
const bySource=new Map(src.sources.map(x=>[x.id,x]));
for(const item of r.published_new){
 const p=byPlace.get(item.place_id);
 assert.ok(p,"P19 site not published in canonical Geo: "+item.place_id);
 assert.equal(p.name.official,item.name);
 assert.equal(p.place_type,item.place_type);
 assert.equal(p.address.country_code,item.country);
 assert.equal(p.geo.matched_country_code,item.country);
 assert.equal(p.geo.precision,"site","Not a verified entrance");
 assert.deepEqual([p.geo.lat,p.geo.lng],[item.lat,item.lng]);
 assert.equal(p.geo.geocoding_source,"OSM");
 assert.equal(p.geo.source_ref,"osm:"+item.osm_type+":"+item.osm_id);
 assert.equal(p.geo.source_url,item.location_source);
 assert.match(p.geo.attribution,/OpenStreetMap/);
 assert.ok(p.mappable&&isMapPublishablePlaceGeo(p.geo,item.country));
 assert.deepEqual(p.source_ids,item.source_ids);
 assert.equal(geo.directoryPlaceLinks.some(x=>x.place_id===p.place_id),false,"No invented 1962 Mass");
 assert.equal(shrineCorpus.shrines.some(x=>x.place_id===p.place_id),false,"No unsupported shrine owner");
 const match=cross.place_crosswalk.filter(x=>x.place_id===p.place_id);
 assert.equal(match.length,1);
 assert.deepEqual(match[0].record_ids,{});
 assert.ok(cross.exception_queues.places_without_direct_claim.includes(p.place_id));
 for(const id of item.source_ids){
  const source=bySource.get(id);
  assert.ok(source);
  assert.match(source.url,/^https:\/\//);
  assert.ok(source.directness&&source.contribution);
 }
}
const bg=byPlace.get("place:IT:madonna-neve-rocchetta-bergamo");
assert.equal(bg.geo.source_ref,"osm:way:442724372");
assert.equal(bg.address.line1,"Via Gabriele Camozzi 130");
assert.ok(byPlace.has("place:IT:basilica-santa-maria-maggiore-bergamo")||geo.places.some(x=>x.name.official.includes("Santa Maria Maggiore")&&x.address.city==="Bergamo"),"Distinct Citta Alta basilica retained");
assert.ok(byPlace.has("place:IT:santuario-beata-vergine-neve-foppolo"),"Foppolo is a separate shrine");
const mg=byPlace.get("place:MG:ilot-de-la-vierge-ampefy");
assert.equal(mg.place_type,"church");
assert.equal(mg.geo.source_ref,"osm:way:653581404");
assert.ok(geo.places.some(x=>x.place_id==="place:MG:immaculate-conception-cathedral-andohalo"),"Earlier Madagascar cathedral retained");
console.log("PASS P19: two uniquely sourced Catholic buildings, 371 Places, 669 sources, zero entrance/TLM/photo/owner inference");
