import assert from "node:assert/strict";
import fs from "node:fs";
import {expandResearchProviderSnapshot} from "../src/find/data-service.js";
import {auditDirectoryGeo,isMapPublishableGeo} from "../src/find/geo-provenance.js";
const get=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const root="data/directory/generated/v19/";
const report=get("data/directory/research/sspx-official-map-18-pin-batch-20261009.v1.json");
const byStem=new Map();
for(const stem of ["sspx-priority-europe-pacific-20261009","sspx-mexico-completion-20261009","sspx-four-district-bulk"]){
 const doc=get(root+stem+".v1.json"),geo=get(root+stem+".geo.v1.json");
 assert.equal(doc.provider,geo.provider);
 byStem.set(stem,{doc,geo,expanded:expandResearchProviderSnapshot(doc,{geoRecords:geo.records})});
}
assert.equal(report.schema,"AO_DIRECTORY_SSPX_18_NEW_GEO_PINS_REVIEW_20261009_V1");
assert.equal(report.cases.length,18);
assert.equal(report.additional_existing_sspx_pins,18);
assert.equal(report.previous_official_sspx_pins,373);
assert.equal(report.after_official_sspx_pins,391);
assert.equal(report.sspx_mass_records,614);
assert.equal(report.still_without_verified_geo,223);
assert.equal(report.new_mass_records,0);
assert.deepEqual(report.precision_counts,{address:17,locality:1});
assert.equal(byStem.get("sspx-priority-europe-pacific-20261009").geo.records.length,11);
assert.equal(byStem.get("sspx-mexico-completion-20261009").geo.records.length,2);
assert.equal(byStem.get("sspx-four-district-bulk").geo.records.length,60);
assert.equal(report.cases.filter(x=>x.provider_file==="sspx-four-district-bulk").length,5);
assert.equal(report.cases.filter(x=>x.provider_file==="sspx-mexico-completion-20261009").length,2);
assert.equal(report.cases.filter(x=>x.provider_file==="sspx-priority-europe-pacific-20261009").length,11);
const refs=new Set(),vIds=new Set(),precision={address:0,locality:0};
for(const item of report.cases){
 assert.ok(!refs.has(item.official_map_place_id),"Same SSPX official place used twice");
 assert.ok(!vIds.has(item.venue_id),"Same physical SSPX venue pinned twice");
 refs.add(item.official_map_place_id);vIds.add(item.venue_id);
 const entry=byStem.get(item.provider_file);
 assert.ok(entry,"Unknown overlay "+item.provider_file);
 const record=entry.geo.records.find(x=>x.venue_id===item.venue_id);
 assert.ok(record,"Geo overlay omitted physical venue "+item.venue_id);
 const canonical=entry.expanded.venues.find(x=>x.venue_id===item.venue_id);
 assert.ok(canonical,"Directory consumer lost "+item.venue_id);
 assert.equal(record.geo.source_ref,"SSPX:MAP:"+item.official_map_place_id);
 assert.equal(record.geo.source_url,"https://map.fsspx.org/de/places/"+item.official_map_place_id);
 assert.equal(record.geo.geocoding_source,"OFFICIAL_SOURCE");
 assert.equal(record.geo.source_observed_at,"2026-10-09");
 assert.equal(record.geo.precision,item.precision);
 assert.equal(record.geo.matched_country_code,item.matched_country);
 assert.equal(record.geo.lat,item.route_destination.lat);
 assert.equal(record.geo.lng,item.route_destination.lng);
 assert.equal(canonical.geo.lat,item.route_destination.lat);
 assert.equal(canonical.geo.lng,item.route_destination.lng);
 assert.ok(isMapPublishableGeo(record.geo,canonical.address.country_code),"Unpublishable pin "+item.official_map_place_id);
 assert.deepEqual(auditDirectoryGeo(record.geo,{countryCode:canonical.address.country_code}),[]);
 assert.ok(["address","locality"].includes(item.precision));
 precision[item.precision]++;
}
assert.deepEqual(precision,{address:17,locality:1});
assert.equal(report.cases.find(x=>x.official_map_place_id==="maungatapere-memorial-chapel").precision,"locality");
assert.ok(!refs.has("east-devonport"));
assert.equal(report.unpin_hold.official_place_id,"east-devonport");
assert.match(report.unpin_hold.reason,/displaced/);
const allGeo=[...["sspx-district-seed","sspx-france-first-party","sspx-france-second-pass","sspx-four-district-bulk","sspx-oct26-europe","sspx-oct26-americas","sspx-oct26-poland","sspx-asia-central-americas","sspx-north-america-20261008","sspx-priority-europe-pacific-20261009","sspx-mexico-completion-20261009","sspx-oct26-followup-65","sspx-global-completion-20261009","sspx-official-route-oct26-20261009"]].flatMap(n=>get(root+n+".geo.v1.json").records);
assert.equal(allGeo.length,391,"SSPX official map point totals drifted");
assert.equal(new Set(allGeo.map(x=>x.venue_id)).size,391,"Duplicate physical venue in map overlays");
assert.equal(new Set(allGeo.map(x=>x.geo.source_ref)).size,391,"Duplicate first-party source in map overlays");
console.log("SSPX existing-site official map completion: PASS — 18 vetted additional points (17 address, 1 locality); total 391 pinned / 614 Mass records; East Devonport held");
