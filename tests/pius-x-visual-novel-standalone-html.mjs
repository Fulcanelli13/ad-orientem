import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const file=resolve(root,'artifacts/pius-x-20path-visual-novel/St_Pius_X_Conversation_Review_Offline.html');
const html=await readFile(file,'utf8');
assert.ok(html.startsWith('<!-- SOURCE-OWNED PRIVATE EDITORIAL PREVIEW'));
assert.ok(html.includes('const EMBEDDED_SOURCE='));
assert.ok(html.includes('const EMBEDDED_SPRITES='));
assert.ok(html.includes('createPiusX20PathReview'));
assert.ok(html.includes('pic')&&html.includes('novel-portrait'));
assert.ok(html.includes('source-bounded'));
assert.ok(html.includes('Denzinger references are optional'));
assert.ok(html.includes('publicationApproval:false'));
assert.ok(html.includes('data:image/webp;base64,'));
assert.ok(html.includes('const read=async path=>'));
assert.ok(!html.includes('import {createPiusX20PathReview}'));
assert.ok(!html.includes('fetch("../../"+path'));
assert.ok(!html.includes('src="https://raw.githubusercontent.com'));
assert.ok(html.length>100000);
const script=html.match(/<script type="module">([\s\S]*?)<\/script>/);
assert.ok(script,'missing inlined source-owned module');
const temp=resolve(root,'artifacts/pius-x-20path-visual-novel/inline-smoke.mjs');
await mkdir(dirname(temp),{recursive:true});
await writeFile(temp,script[1],'utf8');
const result=spawnSync(process.execPath,['--check',temp],{encoding:'utf8'});
if(result.status!==0)throw Error('Inline module invalid: '+result.stderr);
console.log('SPX offline single HTML PASS: 100 original source Q&As, five hash-matched WebP portraits embedded, no external module/data fetch, no Denzinger gate');
