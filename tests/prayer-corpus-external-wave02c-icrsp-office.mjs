import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const root=new URL("../data/pray/",import.meta.url);
const owned=JSON.parse(readFileSync(new URL("prayer-corpus-ownership-foundation.v1.json",root),"utf8"));
const a=JSON.parse(readFileSync(new URL("prayer-corpus-external-discovery-wave02-icksp-firstpass.v1.json",root),"utf8"));
const b=JSON.parse(readFileSync(new URL("prayer-corpus-external-discovery-wave02-icksp-uk-fr-secondpass.v1.json",root),"utf8"));
const c=JSON.parse(readFileSync(new URL("prayer-corpus-external-index-wave02c-icrsp-office-20261028.v1.json",root),"utf8"));
const ownerKeys=new Set(owned.records.map(x=>x.key));
assert.equal(owned.records.length,94);
assert.equal(a.records.length,40);
assert.equal(b.records.length,76);
assert.equal(c.records.length,109);
assert.equal(new Set(c.records.map(x=>x.lead_id)).size,109);
assert.equal(c.counts.index_items,109);
assert.equal(c.counts.source_texts_individually_verified,0);
assert.equal(c.counts.edition_print_certified,0);
assert.equal(c.counts.canonical_imports,0);
assert.equal(c.records.filter(x=>x.unit_kind==="OFFICE_PSALM_PORTION").length,65);
assert.equal(c.records.filter(x=>x.unit_kind==="OFFICE_ANTIPHON").length,7);
assert.equal(c.records.filter(x=>x.unit_kind==="ROMAN_RITUAL_REFERENCE").length,3);
assert.ok(c.records.every(x=>x.source_index_url==="https://icrspfrance.fr/textes-liturgiques.php"));
assert.ok(c.records.every(x=>x.evidence_status==="INDEX_TITLE_PRESENT__ARTICLE_UNCOLLATED"));
assert.ok(c.records.every(x=>!x.edition_print_verified&&!x.canonical_imported&&!x.text_copyright_cleared));
assert.ok(c.records.filter(x=>x.existing_anchor_candidate).every(x=>ownerKeys.has(x.existing_anchor_candidate)));
assert.equal(c.counts.owner_key_matches,c.records.filter(x=>x.existing_anchor_candidate).length);
