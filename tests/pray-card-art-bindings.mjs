import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {prayerCardArtSlot,prayerCardArtAttributes,PRAYER_CARD_ART_SLOT_BY_PRAYER_ID} from "../src/pray/prayer-card-art-slots.v1.js";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const slots=read("data/pray/art-placement-slots-20261030.v1.json").slots.filter(x=>x.level==="Prayer card vignette");
const queue=read("data/pray/research/prayer-card-vignette-wikimedia-queue-20261030.v1.json");
const candidate=read("data/pray/artwork-candidate-join-20261030.v1.json");
assert.equal(slots.length,48);
assert.equal(Object.keys(PRAYER_CARD_ART_SLOT_BY_PRAYER_ID).length,48);
assert.equal(queue.queue.length,48);
assert.equal(queue.statistics.production_ready,0);
const unique=new Set();
for(const slot of slots){
 assert.ok(slot.id.startsWith("COV-"));
 assert.equal(prayerCardArtSlot(slot.source_module_reference),slot.id);
 assert.match(prayerCardArtAttributes(slot.source_module_reference),new RegExp("data-ao-art-slot-id=\""+slot.id+"\""));
 assert.match(prayerCardArtAttributes(slot.source_module_reference),/data-ao-art-binding="unassigned"/);
 const row=queue.queue.find(x=>x.slot_id===slot.id);
 assert.ok(row,slot.id);
 assert.equal(row.source_prayer_id,slot.source_module_reference);
 assert.deepEqual(row.eligible_subject_codes,slot.eligible_subjects);
 assert.match(row.wikimedia_search_state,/PENDING|NOT_STARTED/);
 assert.deepEqual(row.combined_candidate_identity_ids,[...new Set([...row.candidate_identity_ids,...row.gallery_candidate_identity_ids])]);
 assert.equal(row.publication_state,"NO_RELEASE_CLEARED_VIGNETTE");
 assert.equal(row.verified_original_url,null);
 const proposal=candidate.slot_proposals.find(x=>x.slot_id===slot.id);
 assert.deepEqual(row.candidate_identity_ids,(proposal?.proposals||[]).map(x=>x.artwork_id));
 assert.ok(!unique.has(slot.source_module_reference));
 unique.add(slot.source_module_reference);
}
assert.equal(prayerCardArtSlot("missing"),null);
assert.equal(prayerCardArtAttributes("missing"),"");
assert.equal(prayerCardArtAttributes("<script>"),"");
assert.equal(queue.queue.filter(x=>x.candidate_count>0).length,32);
assert.equal(queue.queue.filter(x=>x.candidate_count===0).length,16);
assert.equal(queue.queue.filter(x=>x.combined_candidate_count>0).length,39);
assert.equal(queue.queue.filter(x=>x.combined_candidate_count===0).length,9);
assert.equal(queue.queue.filter(x=>x.wikimedia_candidates.length).length,4);
assert.equal(queue.queue.filter(x=>!x.combined_candidate_count&&!x.wikimedia_candidates.length).length,5);
const runtime=readFileSync(new URL("../src/pray/presentation-runtime.js",import.meta.url),"utf8");
const traditional=readFileSync(new URL("../src/pray/traditional-pray-runtime.js",import.meta.url),"utf8");
assert.match(runtime,/data-ao-devo-card="\$\{esc\(id\)\}"\$\{prayerCardArtAttributes\(id\)\}/);
assert.match(traditional,/aoTP381PrayerCard"\$\{prayerCardArtAttributes\(id\)\}/);
console.log("Prayer 48-vignette identity binding and Wikimedia queue: passed");
