import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createAskChurchObjectiveEngine} from '../src/learn/ask-church-objective-engine.js';
import {createAskChurchNativeHandoff} from '../src/learn/ask-church-native-handoff.js';
const survey=JSON.parse(readFileSync(new URL('../data/learn/ask-church-app-route-survey.v1.json',import.meta.url),'utf8'));
const guide=createAskChurchObjectiveEngine(survey);
assert.equal(guide.objectives().length,7);
assert.equal(guide.interpret("I haven't confessed in years").branch,'confession_return');
assert.equal(guide.targets()[0].id,'apostolate:HS02');
assert.equal(guide.targets()[1].id,'pray.confession');
assert.ok(guide.back());
assert.equal(guide.snapshot().branch,null);
assert.ok(guide.setObjective('defend'));
assert.ok(guide.setBranch('protestant'));
assert.ok(guide.targets().some(x=>x.id==='apostolate:AQ08'));
guide.reset();
assert.equal(guide.interpret('my protestant friend believes sola scriptura').branch,'protestant');
guide.reset();
assert.equal(guide.interpret('Je veux prier en famille').branch,'family');
guide.language('fr');assert.match(guide.prompt(),/Débutez|priez|dévotion/);
assert.equal(guide.lookup('learn.apologetics'),null);
assert.equal(guide.lookup('learn.church_crisis'),null);
assert.equal(guide.interpret('personal private issue with no clear keywords').kind,'clarify');
const native=createAskChurchNativeHandoff({}, {survey});
assert.equal((await native.open('learn.apologetics')).code,'PUBLICATION_HOLD');
assert.equal((await native.open('pray.confession')).code,'NATIVE_SHELL_UNAVAILABLE');
assert.equal((await native.open('imaginary.module')).code,'UNKNOWN_DESTINATION');
const events=[];
const host={AO_APP_SHELL_V1:{navigate:async x=>(events.push('navigate:'+x),{ok:true})},AO_MODULES:{open:async(id)=>(events.push('open:'+id),{ok:true})},AO_APOSTOLATE_APP_V1:{open:opts=>(events.push('apostolate:'+opts.scenarioId),true)},AO_LEARN_APP_V1:{status:()=>({open:true}),openModule:async id=>(events.push('learn:'+id),true)}};
const bridge=createAskChurchNativeHandoff(host,{survey});
assert.equal((await bridge.open('pray.confession')).ok,true);
assert.equal((await bridge.open('apostolate:HS02')).ok,true);
assert.equal((await bridge.open('learn.spiritual_life')).ok,true);
assert.deepEqual(events,['navigate:pray','open:pray.confession','navigate:apostolate','apostolate:HS02','navigate:learn','learn:learn.spiritual_life']);
const refused=createAskChurchNativeHandoff({AO_APP_SHELL_V1:{navigate:async()=>true},AO_MODULES:{open:async()=>({ok:false})}},{survey});
assert.equal((await refused.open('pray.confession')).code,'PRAY_OPEN_FAILED');
const tampered=structuredClone(survey);tampered.objectives[0].paths[0].targets.push('learn.apologetics');assert.throws(()=>createAskChurchObjectiveEngine(tampered),/research-only/);
console.log('Ask the Church: 7 objectives / 26 branches, source gates, language, sensitive data and native handoffs PASS');
