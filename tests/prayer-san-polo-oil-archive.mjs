import assert from "node:assert/strict";
import {readFileSync, existsSync, readdirSync} from "node:fs";
import {join} from "node:path";
import {createHash} from "node:crypto";

const root="data/prayer/stations/san-polo-tiepolo-oils-1747";
const read=(name)=>JSON.parse(readFileSync(join(root,name),"utf8"));
const manifest=read("manifest.v1.json");
const archive=read("acquisition-results.v1.json");
const stages=read("research-stage-bindings.v1.json");

assert.equal(manifest.count,14);
assert.equal(archive.photographsAcquired,14);
assert.equal(archive.failedCount,0);
assert.equal(archive.fullyAcquired,true);
assert.equal(archive.productionImagesEnabled,0);
assert.equal(archive.artworksNewlyApproved,0);
assert.equal(archive.artworkMedium,"oil on canvas");
assert.equal(archive.researchOnly,true);
assert.match(archive.photographsLicense,/CC BY-SA 4.0/);
assert.equal(stages.distribution.productionEnabled,false);
assert.equal(stages.distribution.matchesStrictPDCC0Policy,false);
assert.equal(stages.distribution.sourceArtEditorialUserSelectionsPreserved,true);
assert.equal(stages.counts.newProductionImages,0);
assert.equal(stages.entries.length,14);
assert.equal(manifest.files.length,14);
assert.equal(archive.files.length,14);
assert.equal(new Set(archive.files.map(x=>x.originalCommonsSHA1)).size,14);
assert.equal(new Set(archive.files.map(x=>x.derivativeSHA256)).size,14);
assert.equal(new Set(archive.files.map(x=>x.sourceTitle)).size,14);
assert.equal(new Set(stages.entries.map(x=>x.slotId)).size,14);

let bytes=0;
for(let i=0;i<14;i++){
 const n=i+1;
 const m=manifest.files[i], a=archive.files[i], s=stages.entries[i];
 assert.equal(m.station,n);assert.equal(a.station,n);assert.equal(s.station,n);
 assert.equal(s.slotId,"STG-pray.stations-"+String(n).padStart(2,"0"));
 assert.equal(m.targetPath,a.file);
 assert.equal(a.file,s.repositoryPath);
 assert.equal(s.sha256,a.derivativeSHA256);
 assert.equal(a.artMedium,"oil on canvas");
 assert.equal(a.photographLicenceURL.replace(/\/+$/,""),"https://creativecommons.org/licenses/by-sa/4.0");
 assert.equal(a.productionRightsGate,"NOT_PD_CC0");
 assert.equal(a.artworkApproved,false);
 assert.equal(a.runtimeEnabled,false);
 assert.deepEqual(s.release,{editorialFinalApproval:false,exactImageLicencePDCC0:false,visualHumanQA:false,liveReaderVerified:false,enabled:false});
 const b=readFileSync(a.file);
 assert.equal(createHash("sha256").update(b).digest("hex"),a.derivativeSHA256);
 assert.equal(b.subarray(0,4).toString(),"RIFF","WEBP RIFF header required");
 assert.equal(b.subarray(8,12).toString(),"WEBP","WEBP content required");
 assert.equal(b.length,a.derivativeBytes);
 assert.ok(a.derivativeDimensions[0]>=1800,"Image too narrow");
 assert.ok(a.derivativeDimensions[1]>=2000,"Image too short");
 assert.equal(s.bytes,b.length);
 assert.ok(!/lybaert|etching|engraving|sketch/i.test(m.subject),"Wrong medium or rejected artwork");
 bytes+=b.length;
}
assert.equal(bytes,archive.derivativeTotalBytes);
assert.equal(bytes,stages.counts.archivedBytes);
assert.equal(readdirSync(join(root,"images")).filter(x=>x.endsWith(".webp")).length,14);
assert.ok(existsSync(join(root,"ATTRIBUTION.md")));
const credits=readFileSync(join(root,"ATTRIBUTION.md"),"utf8");
assert.match(credits,/Didier Descouens/);
assert.match(credits,/CC BY-SA 4.0/);
assert.match(credits,/RESEARCH ONLY/);
const gallery=readFileSync("docs/research/san-polo-oil-stations-gallery.html","utf8");
assert.equal((gallery.match(/<img /g)||[]).length,14);
assert.match(gallery,/research gallery, not the live Prayer reader/i);
assert.match(gallery,/CC BY-SA 4.0/);
