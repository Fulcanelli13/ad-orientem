import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {chromium} from '@playwright/test';
const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const filepath=resolve(root,'artifacts/pius-x-release-review/SPX_40_Answer_Editorial_Batch_Review.html');
const html=await readFile(filepath,'utf8');
assert.ok(html.includes('const EMBEDDED={'));
assert.ok(html.includes('const EMBEDDED_AUDIT={'));
assert.ok(html.includes('AO_SPX_40_SOURCE_CLAIM_AUDIT_V1'));

assert.ok(!html.includes('const EMBEDDED=null;'));
assert.ok(html.includes('AO_SPX_100ANSWER_EDITORIAL_RELEASE_TRIAGE_V1'));
const screenshots=resolve(root,'artifacts/pius-x-release-review');
await mkdir(screenshots,{recursive:true});
let browser;
try{
 browser=await chromium.launch({headless:true});
 for(const width of [390,1280]){
  const context=await browser.newContext({viewport:{width,height:width===390?844:830},isMobile:width===390,hasTouch:width===390,acceptDownloads:true,reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(pathToFileURL(filepath).href,{waitUntil:'load'});
  await page.locator('article[data-qid]').first().waitFor();
  assert.equal(await page.locator('article[data-qid]').count(),10);
  assert.equal(await page.locator('nav button').count(),5);
  assert.match(await page.locator('#counts').innerText(),/10 items/);
  assert.ok((await page.locator('article[data-qid="PX1905-Q607"] a[href^="https://"]').count())===2);
  const q=page.locator('article[data-qid="PX1905-Q607"]');
  await q.getByRole('button',{name:'Source correction'}).click();
  assert.match(await q.locator('textarea[data-field="en"]').inputValue(),/transubstantiation/i);
  await q.getByRole('button',{name:'Period-register option'}).click();
  assert.match(await q.locator('textarea[data-field="en"]').inputValue(),/The Church gives/i);
  await q.locator('textarea[data-field="en"]').fill('Editorial review text; not a historical quotation.');
  await q.getByRole('button',{name:'Original draft'}).click();
  await q.getByRole('button',{name:'Period-register option'}).click();
  assert.equal(await q.locator('textarea[data-field="en"]').inputValue(),'Editorial review text; not a historical quotation.');
  await page.locator('nav button').nth(1).click();
  const q613=page.locator('article[data-qid="PX1905-Q613"]');
  await q613.locator('details').last().locator('summary').click();
  assert.match(await q613.locator('details').last().innerText(),/living and immortal|Body Blood Soul Divinity/);
  await q613.getByRole('button',{name:'Italian-source proposal'}).click();
  assert.match(await q613.locator('textarea[data-field="en"]').inputValue(),/Because Christ is living and immortal/);
  await page.locator('nav button').first().click();
  await q.getByRole('button',{name:'For expert review'}).click();
  await q.locator('.notes').fill('Check the period wording against Italian original and theological meaning.');
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
  assert.equal(download.suggestedFilename(),'SPX_40_Batch_Editorial_Review.json');
  const reviewFile=resolve(screenshots,'sample-review-'+width+'.json');
  await download.saveAs(reviewFile);
  const data=JSON.parse(await readFile(reviewFile,'utf8'));
  assert.equal(data.independentApproval,false);assert.equal(data.published,false);
  const review=data.decisions.find(x=>x.id==='PX1905-Q607');
  assert.equal(review.status,'FOR_EXPERT_REVIEW');
  assert.equal(review.variant,'period');
  assert.equal(review.en,'Editorial review text; not a historical quotation.');
  await page.locator('nav button').nth(3).click();
  assert.equal(await page.locator('article[data-qid]').count(),10);
  await page.locator('#batch-hold').click();
  assert.match(await page.locator('#overview').innerText(),/Held: 10/);
  const chooser=page.waitForEvent('filechooser');
  await page.locator('#load').click();
  (await chooser).setFiles(reviewFile);
  await page.waitForFunction(()=>document.getElementById('message').textContent.includes('Imported'));
  await page.locator('nav button').first().click();
  assert.equal(await page.locator('article[data-qid="PX1905-Q607"] textarea[data-field="en"]').inputValue(),'Editorial review text; not a historical quotation.');
  await page.locator('#fr').click();
  assert.equal(await page.locator('article[data-qid]').count(),10);
  assert.match(await page.locator('#section-title').innerText(),/Présence réelle/i);
  await page.locator('nav button').nth(4).click();
  assert.equal(await page.locator('article[data-qid]').count(),60);
  await page.locator('#lane').selectOption('HISTORICAL_PASTORAL_HOLD');
  assert.ok(await page.locator('article[data-qid]').count()>0);
  await page.locator('#search').fill('PX1905-Q633');
  assert.equal(await page.locator('article[data-qid]').count(),1);
  const historic=page.locator('article[data-qid="PX1905-Q633"]');
  await historic.locator('details summary').click();
  assert.match(await historic.innerText(),/NOTE ÉDITORIALE|Note historique/i);
  const extent=await page.evaluate(()=>({body:document.documentElement.scrollWidth,width:window.innerWidth}));
  assert.ok(extent.body<=extent.width+3,'Horizontal overflow '+JSON.stringify(extent));
  assert.deepEqual(errors,[]);
  await page.screenshot({path:resolve(screenshots,'SPX_Release_Review_'+width+'.png'),fullPage:false});
  await context.close();
 }
 console.log('PASS SPX bilingual batch review in Chromium: 40+60 items, offline load, variants, preserved edits, JSON export/import, bulk holds, historical warnings and phone/desktop layouts');
}finally{await browser?.close();}
