import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=path=>JSON.parse(readFileSync(new URL("../"+path,import.meta.url),"utf8"));
const research="data/scripture/catena/research/full-corpus-pass-20261021/";
const cross=read(research+"mark-ten-original-work-crosswalk.v1.json");
const spots=read(research+"mark-batch-01-contextual-spotchecks.v1.json");
const mark=read("data/scripture/catena/mark.json");
const pericopes=new Map(mark.pericopes.map(x=>[x.id,x]));
const reviewed=new Map(spots.records.map(x=>[x.pointer,x]));
assert.equal(cross.schema,"ao.catena.mark-ten-original-work-crosswalk.v1");
assert.equal(cross.state,"research_only_not_human_approved");
assert.equal(cross.canonicalPack,"data/scripture/catena/mark.json");
assert.equal(cross.sourceSpotChecks,research+"mark-batch-01-contextual-spotchecks.v1.json");
assert.equal(cross.rows.length,10);
assert.equal(reviewed.size,10);
assert.equal(cross.counts.records,10);
const seen=new Set();
for(const row of cross.rows){
 assert.ok(!seen.has(row.sourcePointer),"duplicate source record");
 seen.add(row.sourcePointer);
 const base=reviewed.get(row.sourcePointer);
 assert.ok(base,"outside approved research-only contextual shortlist");
 assert.equal(row.inheritedFatherLabel,base.originalFatherLabel);
 assert.equal(row.editorialQuestion,base.modernEditorialReaderQuestion);
 assert.equal(base.publishStatus,"blocked");
 const [pericopeId,indexString]=row.sourcePointer.split(":");
 const p=pericopes.get(pericopeId);
 const n=Number(indexString);
 assert.ok(p&&Number.isSafeInteger(n)&&n>=0);
 const original=p.segments[n];
 assert.ok(original);
 assert.equal(original.father,row.inheritedFatherLabel);
 assert.equal(original.text.length,row.canonicalCharLength);
 assert.equal(row.canonicalExcerptCopied,false);
 assert.ok(row.originalWork.length>=10 && row.originalWorkLocus.length>=12);
 const url=new URL(row.witnessUrl);
 assert.equal(url.protocol,"https:");
 assert.ok(row.witnessAnchor.length>=10 && row.contextFinding.length>=50 && row.readerGuard.length>=55);
 assert.equal(row.originalGreekOrLatinCriticalCollation,false);
 assert.equal(row.criticalEditionChecked,false);
 assert.equal(row.independentHumanEditorApproved,false);
 assert.equal(row.publicationEligibility,"blocked_research_only");
 assert.ok(["original_work_translation_located","original_language_work_located","original_language_work_located_with_catena_abridgment","only_secondary_work_attribution_excerpt_found"].includes(row.witnessAssessment));
 if(row.originalLanguageInspected)assert.equal(row.independentWorkTextInspected,true);
}
assert.deepEqual(seen,new Set(reviewed.keys()),"every contextual Mark check mapped exactly once");
const inspected=cross.rows.filter(x=>x.independentWorkTextInspected);
const latin=cross.rows.filter(x=>x.originalLanguageInspected);
assert.equal(inspected.length,cross.counts.independentWorkTextInspected);
assert.equal(latin.length,cross.counts.originalLanguageInspected);
assert.equal(inspected.length,9);
assert.equal(latin.length,3);
assert.equal(cross.counts.criticalEditionChecked,0);
assert.equal(cross.counts.humanApproved,0);
const byPointer=new Map(cross.rows.map(x=>[x.sourcePointer,x]));
const bed=byPointer.get("catena.mark.10.17:19");
assert.equal(bed.witnessAssessment,"original_language_work_located_with_catena_abridgment");
assert.match(bed.readerGuard,/Zacchaeus/);
assert.doesNotMatch(pericopes.get("catena.mark.10.17").segments[19].text,/Zacchaeus/);
const theoph=byPointer.get("catena.mark.14.17:2");
assert.equal(theoph.independentWorkTextInspected,false);
assert.match(theoph.readerGuard,/probable/);
assert.match(byPointer.get("catena.mark.16.14:3").readerGuard,/pre-Ascension/);
assert.match(byPointer.get("catena.mark.16.14:3").contextFinding,/favors/);
assert.match(byPointer.get("catena.mark.15.29:4").readerGuard,/adjacent alternative/);
console.log("PASS Mark ten original-work crosswalk: 10 exact Catena pointers, 9 inspected witnesses, 3 Latin, 0 approvals; Bede and Theophylact exceptions preserved");
