#!/usr/bin/env node
import fs from "node:fs";
import crypto from "node:crypto";
import assert from "node:assert/strict";
const root="data/research/";
const j=JSON.parse(fs.readFileSync(root+"sacred-art-b51-batch01-50-source-sha-and-thumb-audit.json","utf8"));
const src=JSON.parse(fs.readFileSync(root+"sacred-art-b51-review-batch01-index.json","utf8"));
const prior=fs.readFileSync(root+"sacred-art-b49-95-frozen-approved-rights-review-queue.csv","utf8");
const html=fs.readFileSync("previews/sacred-art-b51-review-batch-01-of-50-offline.html","utf8");
assert.equal(j.schema,"AO_B51_BATCH01_OF_50_SACRED_ART_REVIEW_SOURCE_V1");
assert.equal(j.review_artworks,50);
assert.equal(j.source_image_orig_sha_verified,50);
assert.equal(j.next_approved_review_batch_size,45);
assert.equal(j.entire_approved_queue_artworks,95);
assert.equal(j.unchanged_frozen_active_artworks,383);
assert.equal(j.unchanged_complete_source_artworks,358);
assert.equal(j.unchanged_incomplete_sources,25);
assert.equal(j.originals_newly_acquired,0);
assert.equal(j.full_resolution_originals_embedded,0);
assert.equal(j.review_decisions_recorded_by_bot,0);
assert.equal(j.photo_reuse_permissions_newly_granted,0);
assert.equal(j.app_publication_decisions_created,0);
assert.equal(j.strict_zero_euro,true);
assert.equal(j.offline_gallery_with_50_real_photos,true);
assert.equal(j.user_review_action_only_no_catalogue_change,true);
assert.equal(j.user_exports_decisions_via_browser_json,true);
assert.equal(j.resume_via_import_json_and_optional_browser_local_cache,true);
assert.deepEqual(j.visual_decision_vocabulary,["keep_image","replace_image","reject_artwork","hold"]);
assert.equal(j.audit.length,50);
assert.equal(j.source_metadata_records.length,50);
assert.equal(new Set(j.artwork_ids_in_order).size,50);
assert.deepEqual(src.artwork_ids_in_order,j.artwork_ids_in_order);
assert.equal(j.source_metadata_records.every(x=>x.readyToPublish===false),true);
assert.equal(j.source_metadata_records.every(x=>x.archiveVerified===true),true);
assert.equal(Buffer.byteLength(html),j.self_contained_html_bytes);
assert.ok(j.self_contained_html_bytes<16_000_000);
assert.match(html,/<!doctype html>/i);
assert.match(html,/const artworks=\[/);
assert.match(html,/id="gallery"/);
assert.match(html,/data-decision="keep_image"/);
assert.match(html,/data-decision="replace_image"/);
assert.match(html,/data-decision="reject_artwork"/);
assert.match(html,/data-decision="hold"/);
assert.match(html,/Export decisions/);
assert.match(html,/Import previous review/);
assert.match(html,/AO_SACRED_ART_USER_VISUAL_REVIEW_BATCH_V1/);
assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|navigator\.sendBeacon|<script[^>]*src=/);
assert.doesNotMatch(html,/<link[^>]*rel=["']stylesheet["'][^>]*href=/);
const m=html.match(/const artworks=(\[[\s\S]*?\]);\s*const KEY=/);
assert.ok(m,"No inline artwork data");
const cards=JSON.parse(m[1]);
assert.equal(cards.length,50);
let total=0;
for(let i=0;i<50;i++){
 const a=cards[i],record=j.audit[i],meta=j.source_metadata_records[i];
 assert.equal(a.number,i+1);
 assert.equal(a.id,j.artwork_ids_in_order[i]);
 assert.equal(a.id,record.artwork_id);
 assert.equal(a.sourceHash,record.sha256);
 assert.equal(a.sourceHash,meta.sourceHash);
 assert.equal(a.originalBytes,record.full_original_bytes);
 assert.equal(record.archived_full_original_independently_sha_verified,true);
 assert.equal(record.photograph_rights_published,false);
 assert.equal(record.previous_editorial_artwork_selection_preserved,true);
 assert.equal(a.readyToPublish,false);
 assert.equal(a.archiveVerified,true);
 assert.ok(a.image.startsWith("data:image/webp;base64,"));
 const binary=Buffer.from(a.image.split(",")[1],"base64");
 assert.equal(binary.toString("ascii",0,4),"RIFF");
 assert.equal(binary.toString("ascii",8,12),"WEBP");
 assert.equal(binary.length,record.thumbnail_bytes);
 assert.equal(crypto.createHash("sha256").update(binary).digest("hex"),record.thumbnail_sha256);
 assert.ok(record.thumbnail_dimensions.every(z=>z>0&&z<=1190));
 total+=binary.length;
}
assert.equal(total,j.offline_preview_webp_bytes);
assert.ok(j.original_archive_groups.length>=3);
assert.equal(j.original_archive_groups.every(a=>a.draft_tag&&a.archive_asset.endsWith(".tar")),true);
assert.ok(prior.split(/\r?\n/).length>=96);
console.log("B51_50_OFFLINE_REVIEW_PASS 50 full original SHA-proven photos, 50 offline WebP preview decodes, 50 distinct frozen art IDs, 4 review decisions + note export/import, zero publication/€0");
