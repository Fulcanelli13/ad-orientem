import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { CSE_DEBATE_MAP, CSE_DEBATE_FIELDS, CSE_SOURCE_MAP } from "../src/learn/sexual-ethics-data/index.js";
const old=JSON.parse(readFileSync("data/learn/sexual-ethics-practical-relationships-source-batch-20261009.v1.json","utf8"));
const now=JSON.parse(readFileSync("data/learn/sexual-ethics-practical-original-passages-15-20261009.v1.json","utf8"));
const ids=old.cases.map(x=>x.id).sort();
assert.equal(old.summary.debates,15);
assert.equal(old.summary.stages,120);
assert.equal(old.summary.category_counts.BOUNDED_ORIGINAL_SOURCE_SCOPE_CHECKED,24);
assert.equal(now.summary.new_bounded_original_passage_checks,15);
assert.equal(now.summary.practical_bounded_scopes_total,39);
assert.equal(now.summary.other_stages_pending_full_primary_collation,81);
assert.equal(now.summary.full_debate_certifications,0);
assert.equal(now.summary.independent_french_approvals,0);
assert.equal(now.summary.independent_theology_approvals,0);
assert.deepEqual(now.records.map(x=>x.id).sort(),ids);
assert.equal(new Set(now.records.map(x=>x.id)).size,15);
let newCount=0;
for(const c of now.records){
 const original=old.cases.find(x=>x.id===c.id);
 const oldStage=original.stages.find(x=>x.stage===c.stage);
 assert.ok(oldStage,"not an existing stage: "+c.id);
 assert.notEqual(oldStage.status,"BOUNDED_ORIGINAL_SOURCE_SCOPE_CHECKED","duplicate "+c.id);
 assert.ok(CSE_DEBATE_MAP[c.id],"missing live debate: "+c.id);
 assert.ok(CSE_DEBATE_FIELDS.includes(c.stage));
 assert.ok(CSE_DEBATE_MAP[c.id][c.stage]?.[0].length>35,"English claim missing "+c.id);
 assert.ok(CSE_DEBATE_MAP[c.id][c.stage]?.[1].length>35,"French claim missing "+c.id);
 assert.ok(CSE_SOURCE_MAP[c.source_id]);
 assert.equal(c.source_url,CSE_SOURCE_MAP[c.source_id].canonical_url);
 assert.ok(oldStage.selected_sources.some(x=>x.id===c.source_id),"source not registered for stage "+c.id);
 assert.equal(c.original_en_text_examined,true);
 assert.ok(c.exact_locator.length>2 && c.bounded_finding_en.length>80 && c.not_supported_by_selected_passage_en.length>85);
 assert.ok(c.opponent_provenance_en.length>70 && c.opponent_provenance_class.length>15);
 assert.equal(c.original_complete_opponent_work_collated,false);
 assert.equal(c.entire_eight_stage_debate_certified,false);
 assert.equal(c.complete_EN_claim_by_claim_certified,false);
 assert.equal(c.original_fr_independently_collated,false);
 assert.equal(c.competent_independent_theology_approved,false);
 newCount++;
}
assert.equal(newCount,15);
assert.equal(now.records.find(x=>x.id==="CSE054").exact_locator,"§13");
assert.equal(now.records.find(x=>x.id==="CSE044").exact_locator,"can. 1084 §§1–3");
assert.equal(now.records.find(x=>x.id==="CSE071").exact_locator,"§9");
assert.equal(now.records.find(x=>x.id==="CSE076").review_class,"DOCTRINAL_CONTEXT_AND_ANALOGY_BOUNDED");
assert.equal(now.records.find(x=>x.id==="CSE040").review_class,"DOCTRINAL_CONTEXT_AND_ANALOGY_BOUNDED");
assert.ok(now.records.find(x=>x.id==="CSE044").opponent_provenance_en.includes("not shown to be her own"));
for(const id of ["CSE055","CSE056","CSE058"]) assert.ok(!now.records.some(x=>x.id===id),"archive must stay hidden");
console.log("PASS 15 additional original-source scoped practical stages (39/120 bounded); zero full certifications.");
