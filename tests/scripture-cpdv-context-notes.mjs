import assert from "node:assert/strict";
import {cpdvTextualNotesFor,CPDV_TEXTUAL_NOTES} from "../src/scripture/cpdv-textual-notes.js";
assert.equal(CPDV_TEXTUAL_NOTES.length,7);
assert.ok(CPDV_TEXTUAL_NOTES.every(x=>x.latin&&x.text&&x.severity));
const p={book:"Revelation",chapter:22,verseStart:15,verseEnd:15};
const [note]=cpdvTextualNotesFor("cpdv-2009",p);
assert.equal(note.reference,"Revelation 22:15");
assert.match(note.text,/sorcery/);
assert.equal(note.authorSource,"https://sacredbible.org/catholic/NT-27_Revelation.htm");
assert.match(note.traditionalSource,/biblegateway\.com.*version=DRA/);
assert.equal(cpdvTextualNotesFor("dr-challoner",p).length,0);
assert.equal(cpdvTextualNotesFor("cpdv-2009",{book:"Revelation",chapter:22,verseStart:14}).length,0);
assert.equal(cpdvTextualNotesFor("cpdv-2009",{book:"Revelation",chapter:21,verseStart:8}).length,1);
assert.equal(cpdvTextualNotesFor("cpdv-2009",{book:"Luke",chapter:1,verseStart:43}).length,1);
assert.equal(cpdvTextualNotesFor("cpdv-2009",{book:"Sirach",chapter:24,verseStart:1}).length,1);
assert.equal(cpdvTextualNotesFor("cpdv-2009",{book:"John",chapter:1,verseStart:1}).length,1);
assert.equal(cpdvTextualNotesFor("cpdv-2009",{book:"Matthew",chapter:5,verseStart:28}).length,1);
assert.equal(cpdvTextualNotesFor("cpdv-2009",{book:"1Corinthians",chapter:11,verseStart:27}).length,1);
assert.deepEqual(cpdvTextualNotesFor("cpdv-2009",null),[]);
console.log("Seven source-linked original-context CPDV notes: exact verse ownership and no other-edition contamination passed");
