import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry,auditShrineSource} from "../src/find/shrines-contracts.js";
const get=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=get("data/geography/research/sacred-places-p22-map-first-ten-sites.v1.json");
const policy=get("data/geography/sacred-places-map-first-minimum.v1.json");
const geo=get("data/geography/seed-registry.v1.json");
const sources=get("data/shrines/source-registry.v1.json");
const cross=get("data/explore/heritage-place-reconciliation.review.v1.json");
const shrine=get("data/shrines/shrines-pilgrimages-seed.v1.json");
const p16=get("data/geography/research/sacred-places-p16-three-qualified-site-release.v1.json");
const p21=get("data/geography/research/sacred-places-p21-first200-source-review.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P22_MAP_FIRST_TEN_SITE_RELEASE_V1");
assert.equal(policy.schema,"AO_SACRED_PLACES_MAP_FIRST_MINIMUM_V1");
assert.deepEqual([m.baseline.places,m.baseline.sources,m.baseline.crosswalk,m.baseline.unlinked,m.baseline.p16_holds],[361,659,361,102,16]);
assert.deepEqual([geo.places.length,sources.sources.length,cross.place_crosswalk.length,cross.counts.places_without_direct_claim,geo.geoAreas.length,geo.directoryPlaceLinks.length],[371,669,371,112,141,9]);
assert.deepEqual([m.proposed.places,m.proposed.sources,m.proposed.crosswalk,m.proposed.unlinked,m.proposed.directory_links],[371,669,371,112,9]);
assert.equal(p16.held_exceptions.length,16);
assert.equal(m.published_new.length,10);
assert.equal(new Set(m.published_new.map(x=>x.place_id)).size,10);
assert.equal(new Set(m.published_new.map(x=>x.candidate_id)).size,10);
assert.equal(new Set(m.published_new.map(x=>x.country)).size,8);
const byPlace=new Map(geo.places.map(x=>[x.place_id,x])), bySource=new Map(sources.sources.map(x=>[x.id,x]));
assert.equal(byPlace.size,371);
assert.equal(bySource.size,669);
const original=new Set(p21.reviewed_200.map(x=>x.candidate_id));
for(const row of m.published_new){
 assert.ok(original.has(row.candidate_id),"P22 needs traced P21 source review: "+row.candidate_id);
 const old=p21.reviewed_200.find(x=>x.candidate_id===row.candidate_id);
 assert.equal(old.source_status,"SOURCE_SNIPPET_REVIEWED_2026_10_24");
 const place=byPlace.get(row.place_id), src=bySource.get(row.typed_source_id);
 assert.ok(place&&src);
 assert.equal(place.name.official,row.name);
 assert.equal(place.address.country_code,row.country);
 assert.equal(place.geo.matched_country_code,row.country);
 assert.equal(place.geo_area_ids[0],"geo:country:"+row.country);
 assert.equal(place.place_type,row.place_type);
 assert.deepEqual([place.geo.lat,place.geo.lng],[row.lat,row.lng]);
 assert.equal(place.geo.source_url,row.geo_source);
 assert.equal(place.geo.source_ref,row.geo_source_ref);
 assert.equal(place.geo.geocoding_source,"OSM");
 assert.equal(place.geo.precision,"site");
 assert.match(place.geo.source_ref,/^osm:way:[0-9]+$/);
 assert.match(place.geo.attribution,/OpenStreetMap/);
 assert.ok(isMapPublishablePlaceGeo(place.geo,row.country));
 assert.deepEqual(place.source_ids,[row.typed_source_id],"One identity source suffices; do not force duplicate typed OSM citation");
 assert.equal(src.url,row.identity_source);
 assert.equal(src.issuer,row.identity_issuer);
 assert.equal(auditShrineSource(src).length,0,"Source contract must survive simpler release");
 assert.equal(geo.directoryPlaceLinks.some(l=>l.place_id===row.place_id),false,"No inferred Mass bridge");
 assert.equal(shrine.shrines.some(s=>s.place_id===row.place_id),false,"No unsupported shrine-domain owner");
 assert.equal(shrine.pilgrimages.some(p=>p.destination_place_id===row.place_id),false,"No inferred pilgrimage record");
 const links=cross.place_crosswalk.filter(x=>x.place_id===row.place_id);
 assert.equal(links.length,1);
 assert.deepEqual(links[0].record_ids,{});
 assert.ok(cross.exception_queues.places_without_direct_claim.includes(row.place_id));
 for(const prop of ["hero_image","intro_en","intro_fr","opening_hours","mass_times","external_website_url"])
  assert.equal(place[prop],undefined,"Optional enrichment must not be made a publication gate: "+prop);
}
assert.deepEqual(new Set(geo.places.slice(-10).map(x=>x.place_id)),new Set(m.published_new.map(x=>x.place_id)),"Append exactly the ten new IDs without changing existing Place identities");
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrine,sources:sources.sources,places:geo.places}).pass,true);
const sourcesNew=m.published_new.map(x=>x.typed_source_id);
assert.equal(new Set(sourcesNew).size,10);
assert.equal(sources.sources.slice(-10).filter(x=>sourcesNew.includes(x.id)).length,10);
assert.ok(policy.deferred_not_publication_gates.some(x=>x.includes("Directory")));
console.log("PASS P22: 10 unique map-first Catholic physical Places across 8 countries; +10 typed sources only; 16 historical holds and nine Directory links frozen");
