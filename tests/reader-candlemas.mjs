import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {buildCandlemasPayload,createCandlemasReaderController} from "../src/mass/reader-candlemas.js";
const load=p=>JSON.parse(readFileSync(new URL(p,import.meta.url),"utf8"));
const payload=load("../data/presentation/reader-candlemas.v1.json");
const graph=load("../data/mass/special-days-extension.v1.3.json").graphs.CND;
const built=buildCandlemasPayload({graph,payload});
assert.equal(built.cards.length,4);
assert.equal(built.cards[0].paragraphs.length,5);
assert.equal(built.cards[2].objectState,"CANDLE_LIT");
assert.equal(built.cards.at(-1).handoff,"INTROIT");
const c=createCandlemasReaderController({graph,payload});
c.goTo("CND-R02");
c.setRecipientState("RECEIVE_CANDLE");
assert.equal(c.project().recipientPosture,"KNEEL");
assert.equal(c.project().hasBlessedCandle,true);
assert.equal(c.projectMassCue("AO.SM.C0084").objectState,"CANDLE_LIT");
assert.equal(c.projectMassCue("AO.SM.C0088").objectState,"CANDLE_LIT");
assert.equal(c.projectMassCue("AO.SM.C0145").objectState,"CANDLE_LIT");
assert.equal(c.projectMassCue("AO.SM.C0210").objectState,"CANDLE_LIT");
assert.equal(c.projectMassCue("AO.SM.C0211").objectState,"CANDLE_STATE_UNCONSTRAINED_AFTER_PATER");
assert.equal(c.projectMassCue("AO.SM.C0100").objectState,null);
console.log("native Candlemas payload: PASS — five prayers, personal candle state, procession and Mass candle overlay.");
