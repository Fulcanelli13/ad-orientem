import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_CORPUS_V4_IDS} from "../src/pray/novena-corpus-v4.js";
const runtime=readFileSync(new URL("../src/pray/novena-runtime.js",import.meta.url),"utf8");
const styles=readFileSync(new URL("../src/pray/novena-styles.js",import.meta.url),"utf8");
assert.equal(NOVENA_CORPUS_V4_IDS.length,16,"Do not modify the frozen Novena corpus");
const stage=runtime.slice(runtime.indexOf("function stageRail(n){"),runtime.indexOf("function commonNote(n){"));
const guided=runtime.slice(runtime.indexOf("const total=stages(n);const chapter=novenaChapters(n)[N.stage];"),runtime.indexOf("function renderInstituteThereseWeekly()"));
const simple=runtime.slice(runtime.indexOf("function renderDay(n){"),runtime.indexOf("const total=stages(n);const chapter=novenaChapters(n)[N.stage];"));
assert.ok(stage.startsWith("function stageRail(n){"));
assert.match(stage,/const total=stages\(n\),current=N\.stage\+1/,"Stage count must follow the real historical pattern");
assert.match(stage,/data-ao-novena-stage-progress role="progressbar"/);
for(const s of ['aria-valuemin="1"','aria-valuemax="${total}"','aria-valuenow="${current}"','aria-valuetext="${esc(progress)}"'])assert.ok(stage.includes(s),"Missing accessible progress contract "+s);
assert.match(stage,/repeat\(\$\{total\},minmax\(0,1fr\)\)/,"Segment count must not be hard-coded to five");
assert.match(stage,/aria-hidden="true"/,"Visual bars should not announce individual blank segments");
assert.match(guided,/\$\{novenaDayFolio\(n,N\.day,\{compact:true\}\)\}\$\{stageRail\(n\)\}/,"Guided reader must visibly mount the stage rail after the nine-day folio");
assert.doesNotMatch(simple,/\$\{stageRail\(n\)\}/,"Simple mode must not invent prayer stages");
assert.match(styles,/#aoPray435930 \.aoN1Reader \.aoN1StageCaption/);
assert.match(styles,/font:500 13px\/1\.35/,"Progress label must remain readable on small screens");
assert.match(styles,/#aoPray435930 \.aoN1Reader \.aoN1StageIndicator/);
console.log("PASS Novena stage-progress contract: sourced 3-6 stages, visible FR/EN label, correct accessible values, no Simple-mode counter");
