import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const load=path=>JSON.parse(readFileSync(new URL('../'+path,import.meta.url),'utf8'));
const d=load('data/learn/research/mystery-mass-creed-25-source-verdicts-nobis-ritus-20261015.v1.json');
const text=load('data/presentation/reader-text-sung.v1.json');
const published=load('data/presentation/reader-rubric-events.v1.json');
const draft=load('data/presentation/reader-canon-rubric-review.v1.json');
const cueMap=new Map(text.blocks.flatMap(block=>block.units.map(unit=>[unit.cue_id,unit.latin])));
const rows=d.creedSourceCrosslinks;
assert.equal(rows.length,25);
assert.equal(new Set(rows.map(r=>r.unitId)).size,25);
assert.equal(rows.filter(r=>r.inheritedIncarnationStudy).length,2);
assert.equal(rows.filter(r=>!r.inheritedIncarnationStudy).length,23);
let exact=0,parallel=0,partial=0;
for(const r of rows) {
 assert(cueMap.has(r.massCueId), 'missing canonical cue '+r.massCueId);
 assert(r.historicalSourceUrl.endsWith('_'+r.historicalCatechismArticle));
 assert(r.historicalSourceUrl.startsWith('https://en.wikisource.org/wiki/The_Catechism_of_the_Council_of_Trent/Part_1'));
 assert.equal(r.original1962MissalWordSpanIndependentlyVerified,false);
 assert.equal(r.publicationApproved,false);
 if(r.inheritedIncarnationStudy) continue;
 if(r.unitId==='AO.V3.0098.U002') partial++;
 else if(r.sourceRelationship.startsWith('ROMAN_CATECHISM_CITES')) exact++;
 else if(r.sourceRelationship.startsWith('PARALLEL')) parallel++;
 else assert.fail('Unclassified source relationship '+r.unitId);
}
assert.deepEqual([exact,parallel,partial],[12,10,1]);
assert.equal(d.counts.newApprovals,0);
assert.equal(d.offertoryExistingPrayerOwners.length,7);
assert.equal(d.offertoryExistingPrayerOwners.reduce((n,x)=>n+x.clauseCount,0),10);
assert.equal(new Set(d.offertoryExistingPrayerOwners.map(x=>x.parent)).size,7);
const n=d.nobisQuoque;
assert.equal(n.cueId,'AO.SM.C0196');
assert(cueMap.get(n.cueId).includes('Nobis quoque peccat'));
assert.equal(n.existingEditorialCandidateId,'AO.CANON.R62.050');
assert.equal(n.publishedRubricEventsFoundForThisCue,0);
assert(published.items.every(x=>x.cueId!==n.cueId),'New published event may exist: reconcile instead of double authoring');
const existing=draft.rows.find(x=>x.cueId===n.cueId);
assert(existing && existing.candidateActions.some(x=>x.id===n.existingEditorialCandidateId));
assert.equal(n.priestAct,'ONE_CHEST_STRIKE');
assert.equal(n.leftHand,'RESTS_ON_CORPORAL');
assert.equal(n.publicationApproved,false);
assert.equal(n.faithfulPostureInstruction,'NONE_UNIVERSAL_BY_PRIEST_ACTION');
assert(d.sourceIntegrityHolds.some(x=>x.unitId==='AO.V3.0099.U002'));
assert(d.sourceIntegrityHolds.some(x=>x.unitId==='AO.V3.0248.U002'));
assert(d.sourceIntegrityHolds.some(x=>x.unitId==='AO.V3.0261.U002'));
console.log('PASS Mystery Creed: 25 units / 23 new crosslinks (12 quoted; 10 parallels; 1 partial), 7 reuse owners / 10 clause references, Nobis IX.3 source verified without duplicate published rubric.');
