import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
import {projectExploreDataset} from "../src/find/explore-projection.js";
import {exploreMapFeatures} from "../src/find/map-runtime.js";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const g=read("data/geography/seed-registry.v1.json");
const s=read("data/shrines/shrines-pilgrimages-seed.v1.json");
const sources=read("data/shrines/source-registry.v1.json");
const ph=read("data/explore/sacred-phenomena-seed.v1.json");
const r=read("data/geography/research/sacred-geography-coverage-first-r70.v1.json");
const q=read("data/geography/research/sacred-geography-r70-worldwide-coverage-queue.v1.json");
const h=read("data/explore/heritage-place-reconciliation.review.v1.json");
const m=read("data/geography/research/sacred-geography-r75-essential-sites.v1.json");
assert.equal(m.schema,"AO_SACRED_GEOGRAPHY_R75_ESSENTIAL_SITES_V1");
assert.deepEqual([m.published_new.length,m.existing_confirmed.length,m.held.length],[4,4,2]);
assert.deepEqual([g.places.length,s.shrines.length,s.pilgrimages.length,sources.sources.length],[353,257,240,639]);
assert.equal(assertExploreGeographyRegistry(g).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...s,sources:sources.sources,places:g.places}).pass,true);
assert.equal(r.candidates.length,750);
assert.equal(q.rows.length,750);
assert.deepEqual([r.summary.candidate_status.CONFIRMED_EXISTING_PROMOTION,r.summary.candidate_status.POTENTIAL_EXISTING_ID_REVIEW,r.summary.candidate_status.PHYSICAL_IDENTITY_SOURCE_AND_PIN_REVIEW],[166,6,578]);
assert.deepEqual([q.counts.explicit_promoted,q.counts.text_hint_review,q.counts.unmatched,q.counts.essential_remaining],[164,6,580,6]);
const pBy=new Map(g.places.map(x=>[x.place_id,x])),shBy=new Map(s.shrines.map(x=>[x.shrine_id,x])),piBy=new Map(s.pilgrimages.map(x=>[x.pilgrimage_id,x]));
const srcBy=new Map(sources.sources.map(x=>[x.id,x]));
assert.equal(pBy.size,g.places.length,"Duplicate physical sites");
assert.equal(new Set(s.shrines.map(x=>x.place_id)).size,257);
assert.equal(new Set(s.shrines.map(x=>g.places.find(p=>p.place_id===x.place_id)?.address.country_code)).size,69);
const projected=projectExploreDataset({directory:{records:[],communities:[]},geography:g,shrines:{...s,sources:sources.sources},sacredPhenomena:ph,customs:{customs:[],attestations:[],sources:[]},novenas:{records:[],links:[],sources:[]},editorial:{featured:[],placeGuides:[]},media:{approved:[],gallery:[]}});
for(const entry of m.published_new){
 const p=pBy.get(entry.place_id),sh=shBy.get(entry.shrine_id),pil=piBy.get(entry.pilgrimage_id);
 assert.ok(p&&sh&&pil,"missing canonical publication "+entry.candidate_id);
 assert.equal(p.address.country_code,entry.country);
 assert.deepEqual([p.geo.lat,p.geo.lng,p.geo.precision,p.geo.source_url],[entry.lat,entry.lng,entry.precision,entry.geo_url]);
 assert.ok(isMapPublishablePlaceGeo(p.geo,entry.country));
 assert.equal(sh.place_id,entry.place_id);
 assert.equal(pil.destination_shrine_id,entry.shrine_id);
 assert.ok(sh.source_ids.every(id=>srcBy.has(id)));
 assert.ok(sh.origin_summary.length>60&&sh.origin_summary_fr.length>60);
 assert.equal(exploreMapFeatures(projected.byLens.shrines.filter(x=>x.place_id===entry.place_id)).length,1);
 assert.equal(exploreMapFeatures(projected.byLens.pilgrimages.filter(x=>x.place_id===entry.place_id)).length,1);
 assert.ok(!ph.apparitions.some(x=>x.place_id===entry.place_id));
 assert.ok(!ph.relics.some(x=>x.place_id===entry.place_id));
 assert.equal(q.rows.find(x=>x.candidate_id===entry.candidate_id)?.canonical_place_id,entry.place_id);
 assert.equal(r.candidates.find(x=>x.candidate_id===entry.candidate_id)?.confirmed_place_id,entry.place_id);
}
for(const entry of m.existing_confirmed){
 assert.ok(pBy.has(entry.place_id)&&shBy.has(entry.shrine_id));
 assert.equal(q.rows.find(x=>x.candidate_id===entry.candidate_id)?.canonical_place_id,entry.place_id);
 assert.equal(q.rows.find(x=>x.candidate_id===entry.candidate_id)?.status,"EXPLICIT_PROMOTED");
 assert.equal(g.places.filter(x=>x.place_id===entry.place_id).length,1);
}
assert.equal(q.rows.find(x=>x.candidate_id==="SG-INV-0248")?.status,"UNMATCHED");
assert.equal(q.rows.find(x=>x.candidate_id==="SG-INV-0746")?.status,"TEXT_HINT_REVIEW");
assert.equal(h.place_crosswalk.length,353);
assert.equal(exploreMapFeatures(projected.byLens.shrines).length,257);
assert.equal(exploreMapFeatures(projected.byLens.pilgrimages).length,240);
console.log("PASS R75: four sourced physical pilgrimage Places, four canonical research reuses and 750 research candidates intact");
