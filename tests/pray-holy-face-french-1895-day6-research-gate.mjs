import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_HOLY_FACE_1887_B25,HOLY_FACE_SOURCE_GATES_B25} from "../src/pray/holy-face-janvier-1887-b25.js";
const research=name=>JSON.parse(readFileSync(new URL("../data/pray/research/"+name,import.meta.url),"utf8"));
const day=research("pray-holy-face-1895-fr-day06-transcribed-first-pass.v1.json");
const day1=research("pray-holy-face-1895-fr-day01-transcribed-proofread.v1.json");
const map=research("pray-holy-face-original-french-1895-printed-9day-page-map.v1.json");
assert.equal(day.schema,"ao.pray.holy-face.french-1895-day-transcription.v1");
assert.equal(day.canonicalId,NOVENA_HOLY_FACE_1887_B25.id);
assert.equal(day.day,6);
assert.deepEqual(day.printedPages,[130,131,132,133]);
assert.deepEqual(day.pdfZeroBasedPages,[136,137,138,139]);
assert.equal(day.dayHeading,"La sainte Face au prétoire de Pilate");
assert.equal(map.dayMap[5].printedPages.from,130);
assert.equal(map.dayMap[5].printedPages.to,133);
assert.deepEqual(day.dayComponents.map(x=>x.key),["opening_reference","narrative","point1","point2","point3","act","virtue","bouquet","conclusion_reference"]);
const original=day.dayComponents.filter(x=>typeof x.text==="string");
const references=day.dayComponents.filter(x=>x.text===null);
assert.equal(original.length,7);
assert.equal(references.length,2);
assert.ok(original.reduce((a,x)=>a+x.text.length,0)>3500);
assert.ok(original.every(x=>x.text.length>85 && x.pages.every(p=>p>=130&&p<=133)));
assert.deepEqual(references.map(x=>x.refDay),[1,1]);
assert.equal(references[0].refSection,"opening");
assert.deepEqual(references[1].refSections,["prayers","collect"]);
for(const key of ["opening","prayers","collect"])assert.ok(day1.dayComponents.some(x=>x.key===key && x.text.length>90));
assert.match(day.dayComponents[1].text,/Le prétoire de Pilate fut pour Notre-Seigneur le théâtre sanglant/);
assert.match(day.dayComponents[2].text,/I\. Douleurs de Jésus/);
assert.match(day.dayComponents[3].text,/II\. Humiliations de Jésus/);
assert.match(day.dayComponents[4].text,/III\. Honneur dû à Jésus/);
assert.match(day.dayComponents[4].text,/Non, ô bon Maître/);
assert.match(day.dayComponents[5].text,/Ô Jésus, mon roi et mon Dieu/);
assert.match(day.dayComponents[6].text,/offenser Notre-Seigneur/);
assert.match(day.dayComponents[7].text,/Un membre doit-il être délicat et sensuel/);
assert.equal(day.comparison.variants.length,8);
assert.deepEqual(day.comparison.englishParagraphIndicesByFrenchSection.narrative,[]);
assert.deepEqual(day.comparison.englishParagraphIndicesByFrenchSection.point3,[3,4]);
assert.deepEqual(day.comparison.englishParagraphIndicesByFrenchSection.conclusion_reference,[8,9]);
const english=NOVENA_HOLY_FACE_1887_B25.days[5].text.en;
assert.ok(!english.includes("the theatre of two") && !english.includes("theater of two"),"Printed French standalone introduction must remain unclaimed in English witness");
assert.match(english,/I\. The sufferings of the Holy Face/);
assert.equal(day.independentSecondProofComplete,false);
assert.equal(day.release,"RESEARCH_ONLY_NOT_BOUND_TO_PUBLIC_READER");
assert.equal(day.frenchBodyInCanonicalReader,"EMPTY");
assert.equal(NOVENA_HOLY_FACE_1887_B25.days.length,9);
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every((x,i)=>x.originalSourceDay===i+1&&x.text.fr===""));
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every(x=>x.text.en.length>3000));
assert.equal(HOLY_FACE_SOURCE_GATES_B25.verifiedFrenchPrayerBody,false);
assert.equal(HOLY_FACE_SOURCE_GATES_B25.originalPrintPhotoCollated,false);
console.log("PASS Day VI original 1895 French 7 sections, 2 print references, 8 edition/translation holds; English remains unchanged; 0 French public day bodies");
