import assert from "node:assert/strict";
import fs from "node:fs";
import {auditTravellerMarkets} from "../tools/directory/audit-traveller-markets.mjs";
const data=JSON.parse(fs.readFileSync("data/directory/generated/v19/icksp-federated.v1.json","utf8"));
const held=JSON.parse(fs.readFileSync("data/directory/research/mauritius-icksp-venue-evidence-audit-20261009.v1.json","utf8"));
const rows=data.records.filter(x=>x.cc==="MU");
assert.equal(rows.length,4);
assert.ok(!data.records.some(x=>x.u==="ICKSP-STG-093"));
assert.equal(held.held[0].venue_id,"ICKSP-STG-093");
const url="https://icrspmaurice.org/index.php/horaires-de-lapostolat/";
assert.ok(rows.every(x=>x.su===url && x.vs==="SOURCE_PAGE_UNDATED_CONFIRM_TRAVEL_TIMES"));
assert.ok(rows.find(x=>x.u==="ICKSP-STG-095").sr.includes("CONFIRM_WITH_CANON"));
assert.ok(rows.find(x=>x.u==="ICKSP-STG-096").sr.includes("CONFIRM_WITH_CANON"));
const report=auditTravellerMarkets({today:"2026-10-09"});
const mu=report.priority_markets.find(x=>x.country_code==="MU");
assert.equal(mu.source_records,4);
assert.equal(mu.mass_asserted_source_records,4);
assert.equal(mu.official_inventory_completeness,null);
console.log("Mauritius local source: PASS — four Mass venues, unverified church removed and monthly dates flagged");
