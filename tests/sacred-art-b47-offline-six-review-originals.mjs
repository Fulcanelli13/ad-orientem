#!/usr/bin/env node
import fs from "node:fs";
import crypto from "node:crypto";
import assert from "node:assert/strict";
const root="data/research/";
const read=x=>JSON.parse(fs.readFileSync(root+x,"utf8"));
const prior=read("sacred-art-b46-six-cc0-comparison-review.json");
const b46=read("sacred-art-b46-editorial-preview-no-promotion-closeout.json");
const b45=read("sacred-art-b45-383-source-iconography-and-rights-closeout.json");
const audit=read("sacred-art-b47-six-offline-thumbnail-audit.json");
assert.equal(audit.schema,"AO_B47_SIX_OFFLINE_CC0_THUMBNAILS_SHA_FROM_DRAFT_RELEASES_V1");
assert.equal(audit.original_releases_still_draft,true);
assert.equal(audit.source_originals_verified_count,6);
assert.equal(audit.derivative_webp_previews_embedded,6);
assert.equal(audit.owner_public_domain_or_CC0_sources,true);
assert.equal(audit.original_images_newly_recovered,0);
assert.equal(audit.new_full_resolution_original_files,0);
assert.equal(audit.original_frozen_383_source_gaps_closed,0);
assert.equal(audit.editorial_decisions,0);
assert.equal(audit.app_publication_approvals,0);
assert.equal(audit.cost_eur,0);
assert.equal(audit.strict_zero_euro,true);
assert.equal(audit.production_app_changed,false);
assert.equal(audit.offline_image_display_requires_network,false);
assert.equal(audit.museum_original_links_require_network,true);
assert.equal(prior.editorial_approvals,0);
assert.equal(b46.remaining_source_gaps,25);
assert.equal(b45.B45_cumulative_research_files,122);
assert.equal(b45.B45_cumulative_research_image_bytes,710773181);
assert.equal(audit.items.length,6);
assert.equal(audit.html_gallery_path,"previews/sacred-art-b47-offline-cc0-editorial-gallery.html");
const html=fs.readFileSync(audit.html_gallery_path,"utf8");
assert.equal(Buffer.byteLength(html,"utf8"),audit.self_contained_html_file_bytes);
assert.ok(audit.self_contained_html_file_bytes<3_000_000);
assert.match(html,/<!doctype html>/i);
assert.match(html,/offline/i);
assert.ok(!html.includes("img.src=item.image_url;"));
assert.ok(html.includes("img.src=item.offline_preview_data_url;"));
assert.ok(!/<script[^>]+src=/i.test(html));
assert.ok(!/<link[^>]+rel=['"]?stylesheet[^>]+href=/i.test(html));
assert.ok(!html.includes("localStorage"));
assert.ok(!html.includes("fetch("));
assert.ok(!/<form[\s>]/i.test(html));
assert.ok(!/<button[^>]+(?:approve|publish)/i.test(html));
assert.ok(html.includes('data-filter="shortlist"'));
assert.ok(html.includes('data-filter="contextual"'));
assert.ok(html.includes('data-filter="hold"'));
const matched=html.match(/const items=(\[[\s\S]*?\]);\s*const gallery=/);
assert.ok(matched,"Inline data must be present without JSON fetch");
const pictures=JSON.parse(matched[1]);
assert.equal(pictures.length,6);
const map=new Map(prior.items.map(i=>[i.id,i]));
assert.deepEqual(new Set(pictures.map(i=>i.id)),new Set(prior.items.map(i=>i.id)));
const records=new Map(audit.items.map(i=>[i.candidate_id,i]));
let total=0;
for(const art of pictures){
  const o=map.get(art.id), evidence=records.get(art.id);
  assert.ok(o && evidence);
  const {offline_preview_data_url,offline_source_is_verified,...rest}=art;
  assert.deepEqual(rest,o);
  assert.equal(offline_source_is_verified,true);
  assert.ok(offline_preview_data_url.startsWith("data:image/webp;base64,"));
  const binary=Buffer.from(offline_preview_data_url.split(",")[1],"base64");
  assert.equal(binary.toString("ascii",0,4),"RIFF");
  assert.equal(binary.toString("ascii",8,12),"WEBP");
  assert.equal(crypto.createHash("sha256").update(binary).digest("hex"),evidence.thumbnail_sha256);
  assert.equal(binary.byteLength,evidence.thumbnail_bytes);
  assert.equal(evidence.source_original_sha256,art.research_original_sha256);
  assert.equal(evidence.source_original_image_bytes,art.research_original_size_bytes);
  assert.equal(evidence.thumbnail_verified_by_image_decoder,true);
  assert.equal(evidence.preview_captured_from_original_sha_not_external_thumbnail,true);
  assert.equal(evidence.editorially_selected,false);
  assert.equal(evidence.published_to_app,false);
  assert.ok(evidence.preview_width>300 && evidence.preview_height>300);
  assert.ok(evidence.preview_width<=1130 && evidence.preview_height<=1130);
  assert.equal(art.app_published,false);
  total+=binary.byteLength;
}
assert.equal(total,audit.total_offline_preview_binary_bytes);
assert.equal(audit.items.filter(x=>x.source_draft_release_tag==="ao-art-originals-40082818225-1").length,1);
assert.equal(audit.items.filter(x=>x.source_draft_release_tag==="ao-art-originals-40089028479-1").length,3);
assert.equal(audit.items.filter(x=>x.source_draft_release_tag==="ao-art-originals-40090336600-1").length,2);
console.log("B47_OFFLINE_PASS 6 SHA-authenticated preserved museum originals, 6 embedded validated WebP previews, no external image dependence, frozen 25 gaps and 122 original images unchanged; €0.");
