import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {execFileSync} from "node:child_process";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const a=read("data/explore/worldwide-relic-subject-census.research.v1.json");
const w=read("data/explore/worldwide-relic-subject-census.wave4.research.v1.json");
const published=read("data/explore/sacred-phenomena-seed.v1.json");
assert.equal(w.schema,"SACRED_ATLAS_WORLD_RELIC_CENSUS_WAVE4_V1");
assert.equal(w.status,"RESEARCH_ONLY_NO_PUBLISHED_MAP_CHANGES");
assert.equal(w.reviewed_legacy_subjects.length,20);
assert.equal(w.legacy_relic_object_reviews.length,30);
assert.equal(w.new_institutional_case_reviews.length,8);
assert.equal(w.queue_covered_by_wave4.length,26);
assert.equal(w.queue_currently_uncovered.length,45);
assert.equal(w.queue_subjects_without_any_new_wave_evidence_at_start.length,71);
const subjects=new Set(a.subjects.map(s=>s.subject_id));
const originals=new Map(a.legacy_object_crosswalk.map(s=>[s.legacy_relic_id,s]));
const ids=new Set(),newIds=new Set(),sourceUrls=new Set();
for(const x of w.legacy_relic_object_reviews){
 assert.ok(subjects.has(x.subject_id)&&originals.has(x.object_id));
 assert.ok(!ids.has(x.review_id));ids.add(x.review_id);
 const y=originals.get(x.object_id);assert.equal(y.subject_id,x.subject_id);
 assert.equal(y.custody_place_id,x.custody_place_id);
 assert.match(x.original_source_url,/^https:\/\//);
 assert.match(x.research_source_url,/^https:\/\//);
 assert.equal(x.identity_authenticity,"NOT_INDEPENDENTLY_CERTIFIED");
 assert.equal(x.candidate_prominence_rank,"NOT_ASSIGNED");
 assert.equal(x.new_relic_record,false);
 assert.equal(x.new_map_pin,false);
 assert.ok(x.source_validation==="SITE_OR_ORIGINAL_PASSAGE_SPOT_CHECKED_2026_10_09"||x.source_validation==="LEGACY_URL_INHERITED_PASSAGE_NOT_RECHECKED");
 assert.ok(x.provisional_material_classification);
}
for(const x of w.new_institutional_case_reviews){
 assert.ok(subjects.has(x.subject_id));
 assert.ok(!newIds.has(x.evidence_id));newIds.add(x.evidence_id);
 assert.match(x.source_url,/^https:\/\//);
 sourceUrls.add(x.source_url);
 assert.equal(x.source_screening,"INSTITUTIONAL_OR_GOVERNMENT_PASSAGE_REVIEWED");
 assert.equal(x.identification_authenticated_by_app,false);
 assert.equal(x.new_published_pin,false);
 assert.equal(x.publication_decision,"RESEARCH_ONLY");
 assert.ok(x.reported_custodian&&x.source_role&&x.class_review);
 if(x.material_kind.includes("MARTYRDOM_SITE"))assert.equal(x.class_review,"NOT_RELIC_CUSTODY");
}
assert.ok(sourceUrls.size>=6);
const more=w.new_institutional_case_reviews.filter(x=>x.subject_id==="subject:saint-thomas-more");
assert.equal(more.length,2);
assert.ok(more.some(x=>x.country_code==="GB"&&x.material_kind==="REPORTED_BODILY_MAJOR_PART"));
const simon=w.new_institutional_case_reviews.find(x=>x.subject_id==="subject:saint-simon-the-zealot");
const jude=w.new_institutional_case_reviews.find(x=>x.subject_id==="subject:saint-jude-thaddeus");
assert.equal(simon.source_url,jude.source_url);
assert.equal(simon.reported_custodian,jude.reported_custodian);
assert.ok(w.new_institutional_case_reviews.some(x=>x.subject_id==="subject:saint-paul-miki"&&x.class_review==="NOT_RELIC_CUSTODY"));
assert.ok(w.new_institutional_case_reviews.some(x=>x.subject_id==="subject:saint-david-of-wales"&&x.class_review.includes("NOT_RELIQUARY_FIRST_CLASS")));
const all=new Set(w.queue_covered_by_wave4);
assert.ok(w.queue_currently_uncovered.every(x=>!all.has(x)));
assert.equal(new Set([...w.queue_covered_by_wave4,...w.queue_currently_uncovered]).size,71);
assert.ok(published.relics.length>=a.legacy_object_crosswalk.length,"must not alter production atlas");
assert.ok(a.legacy_object_crosswalk.every(x=>published.relics.some(r=>r.id===x.legacy_relic_id)),"All frozen legacy relic identities must survive expansion");
const stats=JSON.parse(execFileSync(process.execPath,["tools/atlas/report-world-relic-census.mjs"],{encoding:"utf8"}));
assert.equal(stats.first_wave_claims+stats.second_wave_claims+stats.third_wave_claims+stats.fourth_wave_fresh_institutional_cases,85);
assert.equal(stats.fourth_wave_legacy_object_link_reviews,30);
assert.equal(stats.fourth_wave_fresh_institutional_cases,8);
assert.equal(stats.backlog_addressed_after_wave4,88);
assert.equal(stats.backlog_pending_after_wave4,45);
assert.equal(stats.published_place_impact,0);
console.log("PASS wave4: 30 legacy objects reconciled under 20 subjects, 8 separate institutionally documented cases across six more subjects; 88/133 addressed by research or legacy reconciliation, 45 still pending, 0 map pins");
