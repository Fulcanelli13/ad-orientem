import assert from "node:assert/strict";
import fs from "node:fs";
import {createHash} from "node:crypto";
import {eligibleDirectoryImage,attachApprovedDirectoryMedia,renderDirectoryVenueCard,DIRECTORY_CARD_STYLE} from "../src/find/directory-card.js";
import {buildExploreViewModel,renderExploreToString} from "../src/find/explore-presentation.js";
const read=p=>JSON.parse(fs.readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const src=read("data/directory/research/p108-jihlava-source-locked-approved-cover-input.v1.json");
const receipt=read("data/geography/research/directory-p108-one-approved-jihlava-cover.v1.json");
const binary=read("data/directory/research/p108-jihlava-approved-cover-byte-audit.v1.json");
const covers=read("data/geography/approved-place-media.v1.json");
const places=read("data/geography/seed-registry.v1.json");
const screen=read("data/geography/research/directory-place-photo-screen-p92-20261029.v1.json");
const gallery=read("data/geography/approved-place-gallery.v1.json");
const rec=src.record;
const hash=x=>createHash("sha256").update(x).digest("hex");
assert.equal(src.schema,"AO_P108_JIHLAVA_SOURCE_LOCKED_COVER_INPUT_V1");
assert.equal(receipt.schema,"AO_P108_ONE_APPROVED_JIHLAVA_DIRECTORY_COVER_V1");
assert.equal(binary.schema,"AO_P108_ONE_EXACT_JIHLAVA_WEBP_BYTE_AUDIT_V1");
assert.deepEqual([covers.items.length,places.places.length,places.directoryPlaceLinks.length],[41,529,22]);
assert.deepEqual([screen.counts.approved_covers,screen.counts.exact_confirmed_photo_joins,screen.counts.nearby_approved_photo_pairs],[41,10,17]);
assert.deepEqual([receipt.counts.approved_covers_before,receipt.counts.approved_covers_after,receipt.counts.new_covers],[40,41,1]);
assert.equal(rec.place_id,"place:CZ:st-ignatius-jihlava");
assert.equal(rec.venue_id,"ao-research-una-voce-cz-current-20261010-uvcz-r20-jihlava-st-ignatius");
const found=covers.items.filter(x=>x.place_id===rec.place_id);
assert.equal(found.length,1);
const img=found[0];
assert.equal(img.status,"APPROVED");
assert.ok(eligibleDirectoryImage(img,rec.place_id));
assert.equal(eligibleDirectoryImage(img,rec.place_id+"-wrong"),false);
assert.equal(img.asset_path,rec.approved_asset_path);
assert.equal(img.derivative_sha256,rec.derivative_sha256);
assert.equal(img.source_sha1,rec.source_sha1);
assert.equal(img.credit,"Gampe");
assert.equal(img.license,"CC-BY-SA-4.0");
assert.equal(img.license_url,rec.license_url);
assert.equal(img.source_url,rec.source_file_url);
assert.equal(img.source_place_ref,rec.source_place_ref);
assert.ok(img.rights_verified&&img.subject_verified&&img.crop_reviewed);
assert.deepEqual([img.width,img.height],[1050,1400]);
assert.equal(img.orientation,"portrait");
assert.equal(img.alt_en,rec.alt_en);
assert.equal(img.alt_fr,rec.alt_fr);
assert.ok(img.changes_en.includes("without cropping"));
assert.ok(img.changes_fr.includes("sans recadrage"));
const bytes=fs.readFileSync(new URL("../"+rec.approved_asset_path,import.meta.url));
assert.equal(bytes.length,rec.derivative_bytes);
assert.equal(hash(bytes),rec.derivative_sha256);
assert.equal(bytes.toString("ascii",0,4),"RIFF");
assert.equal(bytes.toString("ascii",8,12),"WEBP");
assert.equal(binary.source_commit,src.exact_research_source_commit);
assert.equal(binary.source_original_sha1,rec.source_sha1);
assert.equal(binary.approved_sha256,rec.derivative_sha256);
assert.equal(binary.byte_identical,true);
assert.equal(binary.reencoded,false);
const bridge=places.directoryPlaceLinks.filter(x=>x.venue_id===rec.venue_id);
assert.equal(bridge.length,1);
assert.equal(bridge[0].place_id,rec.place_id);
assert.equal(bridge[0].confidence,"CONFIRMED");
const attached=attachApprovedDirectoryMedia([{kind:"TLM_VENUE",source_id:rec.venue_id,item_id:"tlm:"+rec.venue_id,title:"Church",lens:"tlm"}],{directoryPlaceLinks:places.directoryPlaceLinks,approved:covers.items,gallery:gallery.items});
assert.equal(attached[0].cover_media?.asset_path,rec.approved_asset_path);
assert.ok(renderDirectoryVenueCard(attached[0],"en").includes(rec.alt_en.replaceAll("&","&amp;").replaceAll("'","&#039;")));
assert.ok(renderDirectoryVenueCard(attached[0],"fr").includes(rec.alt_fr.replaceAll("&","&amp;").replaceAll("'","&#039;")));
const html=renderExploreToString(buildExploreViewModel({language:"en",lens:"tlm",items:attached,view:"map",selectedId:"tlm:"+rec.venue_id,filters:{directoryGroup:"ALL"}}));
assert.ok(html.includes("aoTlmPreviewPhotoCredit"));
assert.ok(html.includes("Gampe"));
assert.ok(html.includes(rec.license_url));
assert.ok(html.includes(rec.source_file_url));
