import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const load=p=>JSON.parse(readFileSync(new URL("../data/geography/research/"+p+".v1.json",import.meta.url),"utf8"));
const q=load("mass-1962-edition-certification-priority-queue-20261011");
const p=load("mass-1962-high-priority-100-evidence-packets-20261011");
const b=load("mass-1962-precious-blood-printed-source-batch-20261011");
const high=q.rows.filter(x=>x.priority==="HIGH");
assert.equal(high.length,100);
assert.equal(p.schema,"MASS_1962_HIGH_PRIORITY_100_SOURCE_EVIDENCE_PACKETS_V1");
assert.equal(p.rows.length,100);
assert.deepEqual(new Set(p.rows.map(x=>x.sourcePath)),new Set(high.map(x=>x.sourcePath)));
assert.equal(new Set(p.rows.map(x=>x.sourcePath)).size,100);
assert.equal(p.stats.highPriorityPaths,100);
assert.equal(p.stats.fullyEditionCertified,0);
assert.equal(p.stats.editionCertified,0);
assert.equal(p.stats.publicationApproved,0);
assert.ok(p.rows.every(x=>!x.publishable && x.publicationStatus==="RESEARCH_ONLY_NOT_CERTIFIED"));
assert.ok(p.rows.every(x=>x.sectionEvidence.length+x.witnessPositions.length>0));
assert.ok(p.rows.every(x=>x.sectionEvidence.every(s=>!s.printed1962SectionVerified && !s.biblicalWordMatchVerified)));
assert.ok(p.rows.every(x=>x.witnessPositions.every(s=>!s.printed1962SectionVerified && !s.biblicalWordMatchVerified)));
assert.equal(p.rows.filter(x=>x.sectionEvidence.length>0).length,96);
assert.equal(p.rows.filter(x=>x.witnessPositions.length>0).length,4);
assert.ok(p.rows.some(x=>x.sourcePath==="Sancti/07-01" && x.sectionEvidence.some(s=>s.originalSection==="Tractus") && x.sectionEvidence.some(s=>s.originalSection==="GradualeP")));
assert.ok(p.rows.some(x=>x.sourcePath==="Sancti/10-07" && x.priorityReasons.includes("PRINTED_FEAST_VOTIVE_VARIANT_WITNESSED")));
assert.equal(b.rows.length,9);
assert.ok(b.rows.every(x=>x.sourcePath==="Sancti/07-01" && x.printedRubricChecked && !x.releaseApproved && !x.scriptureEditionTextCertified));
assert.ok(b.rows.every(x=>x.printedPage===533||x.printedPage===534));
assert.equal(b.rubricConditions.length,4);
assert.ok(b.rubricConditions.some(x=>x.id==="VOTIVE_AFTER_SEPTUAGESIMA"&&x.substitute.includes("TRACT")));
assert.ok(b.rubricConditions.some(x=>x.id==="VOTIVE_EASTERTIDE"&&x.substitute.includes("EASTERTIDE_TWO_ALLELUIAS")));
assert.ok(b.holds.some(x=>x.id==="PRECIOUS_BLOOD_1JOHN5_7"));
console.log("PASS: 100/100 high-priority source evidence packets, 96 section-extract + 4 old witness ownership, 9 printed Precious Blood comparisons, four conditions, publication gates closed.");
