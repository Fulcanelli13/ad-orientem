import {LIVE} from "./helpers/sacred-places-live-baseline.mjs";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
import {projectExploreDataset} from "../src/find/explore-projection.js";
import {exploreMapFeatures} from "../src/find/map-runtime.js";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const g=read("data/geography/seed-registry.v1.json"),s=read("data/shrines/shrines-pilgrimages-seed.v1.json"),sources=read("data/shrines/source-registry.v1.json");
const r=read("data/geography/research/sacred-geography-coverage-first-r70.v1.json"),q=read("data/geography/research/sacred-geography-r70-worldwide-coverage-queue.v1.json");
const ph=read("data/explore/sacred-phenomena-seed.v1.json"),h=read("data/explore/heritage-place-reconciliation.review.v1.json"),m=read("data/geography/research/sacred-geography-r77-essential-completeness.v1.json");
assert.equal(m.schema,"AO_SACRED_GEOGRAPHY_R77_ESSENTIAL_IDENTITY_AND_COMPLETENESS_V1");
assert.deepEqual([m.published_new.length,m.held.length],[4,6]);
assert.deepEqual([g.geoAreas.length,g.places.length,s.shrines.length,s.pilgrimages.length,sources.sources.length],[141,LIVE.places,257,240,LIVE.sources]);
assert.equal(assertExploreGeographyRegistry(g).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...s,sources:sources.sources,places:g.places}).pass,true);
assert.equal(r.candidates.length,750);
assert.equal(q.rows.length,750);
assert.deepEqual([r.summary.candidate_status.CONFIRMED_EXISTING_PROMOTION,r.summary.candidate_status.POTENTIAL_EXISTING_ID_REVIEW,r.summary.candidate_status.PHYSICAL_IDENTITY_SOURCE_AND_PIN_REVIEW],[166,6,578]);
assert.deepEqual([q.counts.explicit_promoted,q.counts.text_hint_review,q.counts.unmatched,q.counts.essential_remaining],[164,6,580,6]);
const pBy=new Map(g.places.map(x=>[x.place_id,x])),shBy=new Map(s.shrines.map(x=>[x.shrine_id,x])),pilBy=new Map(s.pilgrimages.map(x=>[x.pilgrimage_id,x])),sourceBy=new Map(sources.sources.map(x=>[x.id,x]));
assert.equal(pBy.size,g.places.length,"No duplicates");
assert.equal(new Set(s.shrines.map(x=>x.place_id)).size,257);
assert.equal(new Set(s.shrines.map(x=>pBy.get(x.place_id)?.address.country_code)).size,69);
const projected=projectExploreDataset({directory:{records:[],communities:[]},geography:g,shrines:{...s,sources:sources.sources},sacredPhenomena:ph,customs:{customs:[],attestations:[],sources:[]},novenas:{records:[],links:[],sources:[]},editorial:{featured:[],placeGuides:[]},media:{approved:[],gallery:[]}});
for(const entry of m.published_new){
 const p=pBy.get(entry.place_id),sh=shBy.get(entry.shrine_id);
 assert.ok(p&&sh,"Missing canonical physical site "+entry.candidate_id);
 assert.equal(p.address.country_code,entry.country);
 assert.equal(sh.place_id,p.place_id);
 assert.equal(sh.recognition_class,"UNKNOWN","Historical dedication does not imply a juridically approved shrine");
 assert.ok(isMapPublishablePlaceGeo(p.geo,entry.country));
 assert.deepEqual([p.geo.lat,p.geo.lng,p.geo.precision],[entry.latitude,entry.longitude,entry.coordinate_precision]);
 assert.ok(sh.source_ids.every(id=>sourceBy.has(id)));
 assert.ok(sh.origin_summary.length>60&&sh.origin_summary_fr.length>60);
 assert.equal(r.candidates.find(x=>x.candidate_id===entry.candidate_id)?.confirmed_place_id,entry.place_id);
 assert.equal(q.rows.find(x=>x.candidate_id===entry.candidate_id)?.canonical_place_id,entry.place_id);
 assert.equal(exploreMapFeatures(projected.byLens.shrines.filter(x=>x.place_id===entry.place_id)).length,1);
 assert.ok(!ph.apparitions.some(x=>x.place_id===entry.place_id));
 assert.ok(!ph.relics.some(x=>x.place_id===entry.place_id));
 if(entry.pilgrimage_id){
   assert.equal(pilBy.get(entry.pilgrimage_id)?.destination_shrine_id,entry.shrine_id);
   assert.equal(exploreMapFeatures(projected.byLens.pilgrimages.filter(x=>x.place_id===entry.place_id)).length,1);
 }else assert.equal(s.pilgrimages.some(x=>x.destination_shrine_id===entry.shrine_id),false,"Parish/co-cathedral not automatic pilgrim journey");
}
assert.equal(m.published_new.filter(x=>x.pilgrimage_id).length,1);
assert.equal(h.place_crosswalk.length,LIVE.places);
assert.equal(exploreMapFeatures(projected.byLens.shrines).length,257);
assert.equal(exploreMapFeatures(projected.byLens.pilgrimages).length,240);
const heldIds=new Set(m.held.map(x=>x.candidate_id));
assert.deepEqual(heldIds,new Set(q.rows.filter(x=>x.priority==="Essential"&&x.status!=="EXPLICIT_PROMOTED").map(x=>x.candidate_id)));
assert.equal(m.held.find(x=>x.candidate_id==="SG-INV-0248")?.disposition,"EXCLUDE_NON_CATHOLIC");
assert.equal(m.held.find(x=>x.candidate_id==="SG-INV-0415")?.disposition,"HOLD_AMBIGUOUS_DEMOLISHED");
const nz=pBy.get("place:NZ:st-peter-chanel-russell");
assert.equal(nz.geo.indicative_only,true);
assert.equal(q.rows.find(x=>x.candidate_id==="SG-INV-0746").publish_approved,false);
assert.equal(m.unmatched_country_priorities.length,12);
console.log("PASS R77: 4 physical Catholic sites, one documented shrine pilgrimage, 6 honest essential holds, no duplicate markers");
