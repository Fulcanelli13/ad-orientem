import assert from "node:assert/strict";
import fs from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(fs.readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const geo=load("data/geography/seed-registry.v1.json");
const sources=load("data/shrines/source-registry.v1.json");
const heritage=load("data/explore/heritage-place-reconciliation.review.v1.json");
const r90=load("data/geography/research/sacred-geography-r90-coverage-first-release.v1.json");
const r91=load("data/geography/research/sacred-geography-r91-coverage-first-release.v1.json");
const r92=load("data/geography/research/sacred-geography-r92-verified-site-cohort.v1.json");
const r93=load("data/geography/research/sacred-geography-r93-first-presence-release.v1.json");
const p17=load("data/geography/research/sacred-places-p17-separated-bergamo-asuncion.v1.json");
const shrines=load("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(r91.schema,"AO_SACRED_GEOGRAPHY_R91_COVERAGE_FIRST_RELEASE_V1");
assert.equal(r90.result.places,318,"R90 publication numbers are immutable");
assert.equal(r91.published_new.length,12);
assert.equal(r91.country_areas_added.length,12);
assert.equal(new Set(r91.published_new.map(x=>x.country)).size,12);
assert.equal(geo.places.length,318+r91.published_new.length+r92.published_new.length+r93.published_new.length+6+p17.published_new.length+3);
assert.equal(geo.geoAreas.length,112+r91.country_areas_added.length+r92.country_areas_added.length+r93.country_areas_added.length);
assert.equal(sources.sources.length,563+2*r91.published_new.length+2*r92.published_new.length+2*r93.published_new.length+18+p17.published_new.reduce((n,p)=>n+p.source_ids.length,0)+6);
assert.equal(new Set(geo.places.map(x=>x.place_id)).size,geo.places.length);
assert.equal(new Set(sources.sources.map(x=>x.id)).size,sources.sources.length);
assert.equal(geo.directoryPlaceLinks.length,9);
assert.equal(heritage.place_crosswalk.length,geo.places.length);
assert.equal(heritage.counts.places,geo.places.length);
assert.equal(heritage.counts.places_without_direct_claim,heritage.exception_queues.places_without_direct_claim.length);
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrines,sources:sources.sources,places:geo.places}).pass,true);
const byPlace=new Map(geo.places.map(x=>[x.place_id,x]));
const bySource=new Map(sources.sources.map(x=>[x.id,x]));
const oldCountries=new Set(geo.places.filter(x=>!x.source_ids?.some(s=>s.startsWith("AO-R91-"))).map(x=>x.address.country_code));
const oldFeatures=new Set(geo.places.filter(x=>!x.source_ids?.some(s=>s.startsWith("AO-R91-"))).map(x=>x.geo?.source_ref));
const keys=new Set(),mapRefs=new Set();
for(const r of r91.published_new){
 assert.ok(!keys.has(r.place_id),"Duplicate R91 Place "+r.place_id);keys.add(r.place_id);
 assert.ok(!mapRefs.has(r.geo_source_ref),"Repeated source geometry "+r.geo_source_ref);mapRefs.add(r.geo_source_ref);
 assert.ok(!oldCountries.has(r.country),"R91 jurisdiction already represented "+r.country);
 assert.ok(!oldFeatures.has(r.geo_source_ref),"Previously mapped building re-used "+r.geo_source_ref);
 assert.ok(r91.country_areas_added.includes("geo:country:"+r.country));
 const p=byPlace.get(r.place_id);assert.ok(p,"Unpublished R91 Place "+r.place_id);
 assert.equal(p.name.official,r.name);assert.equal(p.place_type,r.place_type);
 assert.deepEqual(p.geo_area_ids,["geo:country:"+r.country]);
 assert.equal(p.address.country_code,r.country);
 assert.equal(p.geo.matched_country_code,r.country);
 assert.equal(p.geo.lat,r.lat);assert.equal(p.geo.lng,r.lng);
 assert.equal(p.geo.source_ref,r.geo_source_ref);
 assert.equal(p.geo.source_url,r.geo_source_url);
 assert.equal(p.geo.verified_at,r91.date);
 assert.ok(p.geo.attribution.includes("OpenStreetMap"));
 assert.ok(isMapPublishablePlaceGeo(p.geo,r.country));
 assert.deepEqual(p.source_ids,r.source_ids);
 assert.equal(r.source_ids.length,2);
 assert.equal(bySource.get(r.source_ids[0])?.url,r.identity_source_url);
 assert.equal(bySource.get(r.source_ids[1])?.url,r.geo_source_url);
 assert.equal(bySource.get(r.source_ids[0])?.directness,r.identity_source_directness);
 assert.equal(r.geo_source_url,"https://www.openstreetmap.org/"+r.geo_source_ref.replace(/^osm:/,"").replace(":","/"));
 assert.equal(geo.directoryPlaceLinks.some(x=>x.place_id===r.place_id),false,"No inferred 1962-TLM location");
 assert.equal(r.tlm_status,"NO_1962_MISSAL_ASSERTION");
 assert.equal(r.access_status,"CURRENT_VISITOR_HOURS_NOT_ASSERTED");
 assert.ok(heritage.exception_queues.places_without_direct_claim.includes(r.place_id));
 const crosswalk=heritage.place_crosswalk.find(x=>x.place_id===r.place_id);
 assert.ok(crosswalk&&Object.keys(crosswalk.record_ids).length===0,"No inferred shrine or relic linkage");
}
assert.equal(keys.size,12);
assert.equal(r91.tlm_venue_links_added,0);
assert.equal(r91.related_shrine_records_added,0);
for(const cc of ["AO","SZ","MW","BS","DM"])assert.ok(r91.held.some(x=>x.country===cc),"Unresolved false-pin case not tracked: "+cc);
assert.equal(r91.result.places,330,"Frozen R91 Place publication");
assert.equal(r91.result.sources,587,"Frozen R91 source publication");
console.log("PASS R91: 12 distinct Catholic buildings; 12 new jurisdictions; 318→330 Places, 563→587 sources; 0 unsupported rite and heritage joins.");
