import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const registry=read("data/geography/approved-place-media.v1.json");
const gal=read("data/geography/approved-place-gallery.v1.json");
const report=read("data/geography/research/photo-finder-20261030/releases/b7-verification-report.json");
const editorial=read("data/geography/research/photo-finder-20261030/decisions.json");
const manifest=read("data/geography/research/photo-finder-20261030/releases/b7-nine-preserved-covers-release-20261101.v1.json");
const seed=read("data/geography/seed-registry.v1.json");
assert.equal(manifest.schema,"AO_PHOTO_FINDER_B7_EXISTING_BLOBS_20261101_V1");
assert.deepEqual(manifest.baseline,{approved_covers:143,approved_gallery_entries:35,canonical_places:530});
assert.equal(seed.places.length,530);
assert.equal(report.verified,10);
assert.equal(report.exceptions.length,10);
assert.equal(manifest.newly_released.length,9);
assert.equal(manifest.newly_released.length+1,report.verified);
assert.ok(registry.items.length>=152,"B7 historical approvals must survive later approved releases");
assert.equal(new Set(registry.items.map(x=>x.place_id)).size,registry.items.length,"No duplicate Place covers");
assert.equal(gal.items.length,manifest.proposed.approved_gallery_entries);
const byId=new Map(registry.items.map(x=>[x.place_id,x]));
const fromReport=new Map(report.media_records.map(x=>[x.item.place_id,x.item]));
for(const expected of manifest.newly_released){
 const entry=byId.get(expected.place_id),frozen=fromReport.get(expected.place_id);
 assert.ok(entry&&frozen,"Missing frozen approval "+expected.place_id);
 assert.deepEqual(entry,frozen,"Do not modify author, source, licence, alt, exact file or editorial state");
 const fileChoice=decodeURIComponent(entry.source_url.split("/wiki/").at(-1)).replaceAll("_"," ");
 assert.equal(editorial.decisions[entry.place_id].files[0],fileChoice,"Chosen first photo must remain authoritative");
 assert.deepEqual([entry.rights_verified,entry.subject_verified,entry.crop_reviewed],[true,true,true]);
 assert.equal(entry.asset_path,expected.asset_path);
 assert.equal(entry.derivative_sha256,expected.derivative_sha256);
 const bytes=readFileSync(new URL("../"+entry.asset_path,import.meta.url));
 assert.equal(createHash("sha256").update(bytes).digest("hex"),expected.derivative_sha256,"Original staged WebP digest mismatch: "+entry.place_id);
 assert.equal(bytes.length,expected.bytes,"Original staged WebP size mismatch");
}
const preserve=manifest.previously_published_other_photo;
assert.deepEqual(byId.get(preserve.place_id)&&{asset_path:byId.get(preserve.place_id).asset_path,source_sha1:byId.get(preserve.place_id).source_sha1},{asset_path:preserve.asset_path,source_sha1:preserve.source_sha1},"Do not override earlier Spanish monastery cover");
assert.equal(report.media_records.filter(x=>x.item.place_id===preserve.place_id).length,1);
assert.equal(manifest.policy.no_new_downloads,true);
assert.equal(manifest.policy.no_new_editorial_choices,true);
console.log("B7 PASS: 9 frozen Photo Finder covers, 9 SHA256-matching reused WebPs, previous 143 and Spanish cover preserved; no re-download.");
