import assert from "node:assert/strict";
import fs from "node:fs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(fs.readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const main=load("data/geography/seed-registry.v1.json");
const sources=load("data/shrines/source-registry.v1.json");
const heritage=load("data/explore/heritage-place-reconciliation.review.v1.json");
const r88=load("data/geography/research/sacred-geography-r88-country-category-coverage.v1.json");
const r89=load("data/geography/research/sacred-geography-r89-first-coverage-release.v1.json");
const r90=load("data/geography/research/sacred-geography-r90-coverage-first-release.v1.json");
const r91=load("data/geography/research/sacred-geography-r91-coverage-first-release.v1.json");
const r92=load("data/geography/research/sacred-geography-r92-verified-site-cohort.v1.json");
const r93=load("data/geography/research/sacred-geography-r93-first-presence-release.v1.json");
const p17=load("data/geography/research/sacred-places-p17-separated-bergamo-asuncion.v1.json");
const shrines=load("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(r89.schema,"AO_SACRED_GEOGRAPHY_R89_FIRST_COVERAGE_RELEASE_V1");
assert.equal(r88.summary.published_places,294,"R88 is an immutable baseline, not recomputed");
assert.equal(r89.published_new.length,12);
assert.equal(r89.country_areas_added.length,11);
assert.equal(main.places.length,294+r89.published_new.length+r90.published_new.length+r91.published_new.length+r92.published_new.length+r93.published_new.length+6+p17.published_new.length);
assert.equal(main.geoAreas.length,89+r89.country_areas_added.length+r90.country_areas_added.length+r91.country_areas_added.length+r92.country_areas_added.length+r93.country_areas_added.length);
assert.equal(sources.sources.length,515+2*r89.published_new.length+2*r90.published_new.length+2*r91.published_new.length+2*r92.published_new.length+2*r93.published_new.length+18+p17.published_new.reduce((n,p)=>n+p.source_ids.length,0));
assert.equal(main.directoryPlaceLinks.length,9);
assert.equal(heritage.place_crosswalk.length,main.places.length);
assert.equal(heritage.counts.places,main.places.length);
assert.equal(heritage.counts.places_without_direct_claim,heritage.exception_queues.places_without_direct_claim.length);
assert.deepEqual(new Set(heritage.place_crosswalk.map(x=>x.place_id)),new Set(main.places.map(x=>x.place_id)));
assert.equal(new Set(main.places.map(x=>x.place_id)).size,main.places.length);
assert.equal(new Set(sources.sources.map(x=>x.id)).size,sources.sources.length);
assert.equal(assertExploreGeographyRegistry(main).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrines,sources:sources.sources,places:main.places}).pass,true);
for(const areaId of r89.country_areas_added){
  const cc=areaId.split(":").at(-1);
  const country=r88.countries.find(x=>x.iso_code===cc);
  assert.ok(country&&country.published_places===0,"R89 must target a previously empty jurisdiction: "+cc);
  const scope=main.geoAreas.find(x=>x.geo_area_id===areaId);
  assert.ok(scope&&scope.area_type==="country");
  assert.deepEqual(scope.parent_geo_area_ids,["geo:world"]);
}
const ids=new Set(r89.published_new.map(x=>x.place_id));
const sourceById=new Map(sources.sources.map(x=>[x.id,x]));
for(const row of r89.published_new){
 const p=main.places.find(x=>x.place_id===row.place_id);
 assert.ok(p,row.place_id);
 assert.equal(p.address.country_code,row.country);
 assert.equal(p.geo.matched_country_code,row.country);
 assert.equal(p.geo_area_ids[0],"geo:country:"+row.country);
 assert.equal(p.geo.precision,"site");
 assert.equal(p.geo.source_url,row.geo_source_url);
 assert.equal(p.geo.source_ref,row.geo_source_ref);
 assert.equal(p.geo.verified_at,r89.date);
 assert.ok(isMapPublishablePlaceGeo(p.geo,row.country));
 assert.deepEqual(p.source_ids,row.source_ids);
 assert.equal(row.geo_source_url,"https://www.openstreetmap.org/"+p.geo.source_ref.replace("osm:","").replace(":","/"));
 assert.ok(p.geo.attribution.includes("OpenStreetMap"));
 assert.equal(sourceById.get(row.source_ids[0]).url,row.identity_source_url);
 assert.equal(sourceById.get(row.source_ids[1]).url,row.geo_source_url);
 assert.equal(main.directoryPlaceLinks.some(link=>link.place_id===row.place_id),false,"Unsupported exact 1962-TLM Place link");
 assert.equal(row.tlm_status,"NO_1962_MISSAL_ASSERTION");
}
assert.equal(ids.size,r89.published_new.length);
assert.equal(r89.tlm_venue_links_added,0);
assert.equal(r89.related_shrine_records_added,0);
console.log("PASS R89: 12 new named physical Catholic Places in 11 previously empty jurisdictions; 294→306; source-proven, nonduplicate, no TLM assertions.");
