#!/usr/bin/env node
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {Script} from "node:vm";
const base="data/geography/";
const read=x=>JSON.parse(readFileSync(base+x,"utf8"));
const src=read("research/sacred-atlas-round20-freetown-atalaya-lowres-source-review-20261104.v1.json");
const wikidata=read("research/sacred-atlas-round20-wikidata-p18-28-source-reconciliation-20261104.v1.json");
const approved=read("approved-place-media.v1.json");
const prev=read("research/sacred-atlas-round19-altoetting15-originals-verified-20261104.v1.json");
const queue=readFileSync(base+"research/sacred-atlas-undecided66-bulk-photo-review-20261104.html","utf8");
const m=queue.match(/const places=(.*?); const auditStatuses=/s);
assert.ok(m,"Review queue missing");
const places=JSON.parse(m[1]);
assert.equal(places.length,66);
assert.equal(approved.items.length,379);
assert.equal(prev.rows.length,15);
assert.equal(wikidata.counts.frozen_places_checked,28);
assert.equal(wikidata.provenance.wikidata_requests,47);
assert.equal(wikidata.counts.no_wikidata_label_match,25);
assert.equal(wikidata.counts.p18_file_links,2);
assert.equal(wikidata.counts.new_correct_cover_leads,0);
assert.equal(wikidata.counts.wrong_site_p18_files,1);
assert.equal(wikidata.counts.known_low_res_p18_duplicates,1);
assert.equal(wikidata.missing_entity_match_place_ids.length,25);
assert.equal(wikidata.matched_entities.length,3);
assert.ok(wikidata.matched_entities.every(x=>x.publication_authorized===false));
assert.equal(src.rows.length,2);
assert.equal(src.counts.new_file_leads,5);
assert.equal(src.counts.cover_eligible,0);
assert.ok(src.rows.every(r=>r.photo_leads.every(x=>x.publication_authorized===false)));
assert.equal(places.filter(p=>p.candidates.length).length,39);
assert.equal(places.reduce((n,p)=>n+p.candidates.length,0),124);
assert.equal(places.filter(p=>!p.candidates.length&&!p.legalHold).length,26);
const hold=(id)=>places.find(p=>p.id===id);
assert.equal(hold("place:SL:sacred-heart-cathedral-freetown").candidates.length,3);
assert.equal(src.rows.find(x=>x.place_id==="place:SL:sacred-heart-cathedral-freetown").historical_original_review.historical_dimensions[0],2048);
assert.ok(hold("place:SL:sacred-heart-cathedral-freetown").round20HistoricalHold.includes("watermark"));
assert.ok(src.rows.find(x=>x.place_id==="place:SL:sacred-heart-cathedral-freetown").historical_original_review.visual_status.startsWith("EXCLUDE_"));
assert.equal(hold("place:PA:basilica-menor-jesus-nazareno-atalaya").candidates.length,2);
assert.ok(src.rows.every(r=>hold(r.place_id).candidates.every(c=>c.visualDecision==="HOLD_ORIGINAL_TOO_SMALL")));
const alt=hold("place:DE:friedhofskirche-st-michael-altoetting");
assert.equal(alt.candidates.length,15);
assert.equal(alt.candidates[0].title,"File:Friedhofskirche Altötting 16.jpg");
assert.equal(alt.round20FirstLook,alt.candidates[0].title);
assert.ok(alt.candidates.find(c=>c.title==="File:Friedhofskirche Altötting 1.jpg").visualDecision.startsWith("SECONDARY_GALLERY_"));
assert.ok(alt.candidates.every(c=>c.originalVerified===true));
assert.equal(places.reduce((n,p)=>n+p.candidates.filter(c=>c.originalVerified).length,0),25);
assert.ok(queue.includes("Wikidata P18"));
assert.ok(queue.includes('if(filter==="round20"&&!p.candidates.some(c=>c.round20))return false;'));
const scripts=[...queue.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);
new Script(scripts[0][1],{filename:"66-place-review.js"});
console.log(JSON.stringify({status:"PASS",source_places:39,files:124,new_held_files:5,verified_originals:25,altotting_first_look:"16",published_approved:379}));
