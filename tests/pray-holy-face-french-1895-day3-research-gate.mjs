import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_HOLY_FACE_1887_B25,HOLY_FACE_SOURCE_GATES_B25} from "../src/pray/holy-face-janvier-1887-b25.js";
const research=(filename)=>JSON.parse(readFileSync(new URL("../data/pray/research/"+filename,import.meta.url),"utf8"));
const day=research("pray-holy-face-1895-fr-day03-transcribed-first-pass.v1.json");
const day1=research("pray-holy-face-1895-fr-day01-transcribed-proofread.v1.json");
const map=research("pray-holy-face-original-french-1895-printed-9day-page-map.v1.json");
assert.equal(day.schema,"ao.pray.holy-face.french-1895-day-transcription.v1");
assert.equal(day.canonicalId,NOVENA_HOLY_FACE_1887_B25.id);
assert.equal(day.day,3);
assert.equal(day.dayHeading,"La sainte Face au Thabor");
assert.deepEqual(day.printedPages,[120,121,122,123]);
assert.deepEqual(day.pdfZeroBasedPages,[126,127,128,129]);
assert.equal(map.dayMap[2].printedPages.from,120);
assert.equal(map.dayMap[2].printedPages.to,123);
assert.deepEqual(day.dayComponents.map(x=>x.key),["opening_reference","narrative","point1","point2","point3","act","virtue","bouquet","conclusion_reference"]);
assert.equal(day.dayComponents.length,9);
const transcribed=day.dayComponents.filter(x=>typeof x.text==="string");
const shared=day.dayComponents.filter(x=>x.text===null);
assert.equal(transcribed.length,7);
assert.equal(shared.length,2);
assert.ok(transcribed.reduce((n,s)=>n+s.text.length,0)>4000);
assert.ok(transcribed.every(x=>x.pages.every(p=>p>=120&&p<=123)));
assert.deepEqual(shared.map(x=>x.refDay),[1,1]);
assert.equal(shared[0].refSection,"opening");
assert.deepEqual(shared[1].refSections,["prayers","collect"]);
for(const name of ["opening","prayers","collect"]){
  assert.ok(day1.dayComponents.some(x=>x.key===name&&x.text?.length>90));
}
assert.match(day.dayComponents[1].text,/Montez avec Notre-Seigneur sur le Thabor/);
assert.match(day.dayComponents[2].text,/Notre-Seigneur est la source/);
assert.match(day.dayComponents[3].text,/Le Thabor et le Calvaire se rapprochent et s’unissent/);
assert.match(day.dayComponents[4].text,/Jésus est, en effet, la splendeur de la gloire de son Père/);
assert.match(day.dayComponents[5].text,/mon Rédempteur est vivant/);
assert.match(day.dayComponents[7].text,/l’immortel et glorieux Jésus est, par l’Eucharistie, présent/);
assert.equal(day.comparison.variants.length,5);
assert.deepEqual(day.comparison.englishParagraphIndicesByFrenchSection.conclusion_reference,[8,9]);
assert.equal(day.comparison.status,"NINE_SECTION_BILINGUAL_FIRST_PASS_ALIGNED__SECOND_PROOF_AND_PRINT_VARIANTS_PENDING");
assert.equal(day.independentSecondProofComplete,false);
assert.equal(day.release,"RESEARCH_ONLY_NOT_BOUND_TO_PUBLIC_READER");
assert.equal(day.frenchBodyInCanonicalReader,"EMPTY");
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every((x,i)=>x.originalSourceDay===i+1&&x.text.fr===""));
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every(x=>x.text.en.length>3000));
assert.equal(HOLY_FACE_SOURCE_GATES_B25.verifiedFrenchPrayerBody,false);
assert.equal(HOLY_FACE_SOURCE_GATES_B25.originalPrintPhotoCollated,false);
console.log("PASS: Day III 7 original French sections, 2 original print shared-prayer references, 5 variant holds, no premature reader publication");
