import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const prefix='data/learn/research/';
const j=(file)=>JSON.parse(readFileSync(prefix+file,'utf8'));
const a=j('pius-x-conversation-depth12-part-a-20261021.v1.json');
const b=j('pius-x-conversation-depth12-part-b-20261021.v1.json');
const flow=j('pius-x-12chapter-dependent-dialogue-flow-20261021.v1.json');
const past82=j('pius-x-82chapter-dialogue-authoring-index-20261021.v1.json');
const past62=j('pius-x-62chapter-dialogue-graph-20261021.v1.json');
const raw=[...a.chapters,...b.chapters];
const prev82=new Map(past82.newChapters.map(x=>[x.id,x]));
const prev62=new Map(past62.chapters.map(x=>[x.id,x]));
const knownRoots=new Set([...past82.priorChapters,...prev82.keys()]);
assert.equal(knownRoots.size,82);
assert.equal(a.chapters.length,6);
assert.equal(b.chapters.length,6);
assert.equal(raw.length,12);
assert.equal(flow.chapters.length,12);
assert.equal(flow.counts.existingChapterRoots,82);
assert.equal(flow.counts.selectedChaptersWithDeeperPaths,12);
assert.equal(flow.counts.newBilingualTurnNodes,36);
assert.equal(flow.counts.newLocalizedAnswerDrafts,72);
assert.equal(flow.counts.totalPreviouslyAuthoredTurnNodes,291);
assert.equal(flow.counts.totalTurnNodesIncludingDeeperPaths,327);
assert.equal(flow.counts.published,0);
assert.equal(flow.publication.enabled,false);
assert.equal(flow.publication.runtimeIntegrated,false);
const idSet=new Set();
const newTurnIds=new Set();
const parentIds=new Set();
for(const episode of raw){
  assert(!idSet.has(episode.chapterId),'unique chapter');
  idSet.add(episode.chapterId);
  assert.equal(episode.parents.length,3);
  const old=prev82.get(episode.chapterId)||prev62.get(episode.chapterId);
  assert(old,'original chapter exists');
  const old82=prev82.has(episode.chapterId);
  const oldNodes=old82?old.nodes:old.nodeRefs;
  assert.equal(oldNodes.length,4);
  const wired=flow.chapters.find(x=>x.chapterId===episode.chapterId);
  assert(wired,'graph has chapter');
  assert.equal(wired.parents.length,3);
  assert.equal(wired.gate.originalQuestionAnswersUnmodified,true);
  assert.equal(wired.gate.linearAutoPlay,false);
  assert.equal(wired.gate.sourcePanelVisible,true);
  assert.equal(wired.gate.denzingerUnverifiedHidden,true);
  assert.equal(wired.gate.nonCoverage,'DO_NOT_FABRICATE_REPLY');
  for(let k=0;k<3;k++){
    const slot='F'+(k+1);
    const draft=episode.parents[k];
    const branch=wired.parents[k];
    const originalParent=oldNodes[k+1];
    assert.equal(draft.parentChoiceSlot,slot);
    assert.equal(branch.afterTurn,originalParent.id,'must attach to actual selected branch');
    assert(!parentIds.has(originalParent.id),'parent should have just one continuation');
    parentIds.add(originalParent.id);
    assert.equal(branch.newNode.fromParentId,branch.afterTurn);
    assert.equal(branch.newNode.id,draft.followup.id);
    assert.equal(branch.nextTurnId,draft.followup.id);
    assert(!newTurnIds.has(branch.newNode.id),'new ID unique');
    newTurnIds.add(branch.newNode.id);
    assert.deepEqual(branch.newNode.visitor,draft.followup.q);
    assert.deepEqual(branch.newNode.reply,draft.followup.a);
    assert.equal(draft.followup.approved,false);
    for(const locale of ['en','fr']){
      assert(branch.newNode.visitor[locale].length>12,'specific visitor follow-up');
      assert(branch.newNode.reply[locale].length>90,'substantive answer');
    }
    assert.equal(branch.transitionTrigger.kind,'VISITOR_CHOOSES_DEEPEN_FROM_THIS_EXACT_PARENT');
    assert.equal(branch.newNode.sourceClaimStatus,'REQUIRES_INDEPENDENT_ORIGINAL_WITNESS_REVIEW');
    assert.equal(branch.newNode.voiceStatus,'HISTORICAL_VOICE_UNAPPROVED');
    assert.equal(branch.attribution.fromExistingChapter,episode.chapterId);
    assert.equal(branch.attribution.sourceURL,old.researchSource.url);
    assert.equal(branch.attribution.sourceLocus,old.researchSource.locus);
    assert.equal(branch.approved.historical,false);
    assert.equal(branch.approved.theological,false);
    assert.equal(branch.approved.periodVoice,false);
    assert.equal(branch.approved.publication,false);
    assert.equal(branch.newNode.afterAnswer.length,4);
    const outs=new Set(branch.newNode.afterAnswer.map(x=>x.type));
    assert.deepEqual([...outs].sort(),['OFFER_CHANOINE_OPT_IN','OPEN_RELATED_CHAPTER','RETURN_TO_CHAPTER_CHOICES','RETURN_TO_TOPIC_MENU'].sort());
    const next=branch.newNode.afterAnswer.find(x=>x.type==='OPEN_RELATED_CHAPTER');
    assert(knownRoots.has(next.chapterId),'related chapter exists and is authored');
    assert.equal(next.chapterId,draft.suggestedNextTopic);
    assert.equal(branch.newNode.afterAnswer.find(x=>x.type==='OFFER_CHANOINE_OPT_IN').requiresSourceRoutingApproval,true);
  }
}
assert.equal(idSet.size,12);
assert.equal(newTurnIds.size,36);
assert.equal(parentIds.size,36);
const doc=readFileSync('docs/research/PIUS-X-12-DEEP-CONVERSATION-TRANSCRIPTS-20261021.md','utf8');
assert(doc.includes('### 12. '));
assert(doc.includes('Route 3'));
assert(doc.includes('Visitor continues:'));
assert(doc.includes('Réponse approfondie'));
console.log('SPX dialogue continuity PASS: 12 chapters, 36 distinct selected-parent transitions, 72 localized answers, 82 roots, 327 authoring turns, source/approval holds intact.');
