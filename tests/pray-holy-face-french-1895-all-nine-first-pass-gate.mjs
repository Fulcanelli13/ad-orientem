import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { NOVENA_HOLY_FACE_1887_B25, HOLY_FACE_SOURCE_GATES_B25 } from "../src/pray/holy-face-janvier-1887-b25.js";
const read = p => JSON.parse(readFileSync(new URL("../" + p, import.meta.url), "utf8"));
const index = read("data/pray/research/pray-holy-face-1895-fr-all-9day-first-pass-index.v1.json");
const printed = read("data/pray/research/pray-holy-face-original-french-1895-printed-9day-page-map.v1.json");
const days = index.entries.map(x=>read(x.researchPath));
assert.equal(index.schema, "ao.pray.holy-face.french-1895-nine-day-first-pass-index.v1");
assert.equal(index.canonicalId,NOVENA_HOLY_FACE_1887_B25.id);
assert.equal(index.counts.firstPassRecords,9);
assert.equal(index.counts.independentlySecondProofed,0);
assert.equal(index.counts.publicFrenchReaderDays,0);
assert.equal(index.counts.englishReaderDaysPreserved,9);
assert.deepEqual([index.printedCoverage.from,index.printedCoverage.to],[112,142]);
assert.equal(index.entries.length,9);
assert.equal(days.length,9);
const coverage = new Set();
let totalOriginalCharacters=0;
let totalVariants=0;
for(let i=0;i<9;i++){
  const rec=days[i],entry=index.entries[i],map=printed.dayMap[i];
  assert.equal(entry.day,i+1);
  assert.equal(entry.firstPassComplete,true);
  assert.equal(entry.independentSecondProofComplete,false);
  assert.equal(entry.frenchReaderPublished,false);
  assert.equal(entry.editorialAdmission,"HOLD");
  assert.equal(rec.schema,"ao.pray.holy-face.french-1895-day-transcription.v1");
  assert.equal(rec.canonicalId,index.canonicalId);
  assert.equal(rec.day,i+1);
  assert.equal(rec.release,"RESEARCH_ONLY_NOT_BOUND_TO_PUBLIC_READER");
  assert.equal(rec.frenchBodyInCanonicalReader,"EMPTY");
  assert.notEqual(rec.independentSecondProofComplete,true);
  assert.equal(rec.printedPages[0],map.printedPages.from);
  assert.equal(rec.printedPages.at(-1),map.printedPages.to);
  assert.equal(rec.pdfZeroBasedPages[0],map.pdfPageZeroBased.from);
  assert.equal(rec.pdfZeroBasedPages.at(-1),map.pdfPageZeroBased.to);
  assert.equal(rec.dayComponents.length,i<=1||i===8?10:9);
  assert.ok(rec.dayComponents.every(x=>x.pages.length>0 && x.pages.every(p=>rec.printedPages.includes(p))));
  const original=rec.dayComponents.filter(x=>typeof x.text==="string");
  assert.ok(original.length>=7,"Every day must preserve 7+ source sections");
  assert.ok(original.every(x=>x.text.trim().length>65),"Source section should not be empty or a placeholder");
  const chars=original.reduce((n,x)=>n+x.text.length,0);
  assert.ok(chars>3000,"Each day must have substantial full-length source text");
  totalOriginalCharacters+=chars;
  const v=rec.comparison.variants;
  assert.ok(v.length>=2);
  totalVariants+=v.length;
  for(const p of rec.printedPages) coverage.add(p);
}
assert.equal(coverage.size,31);
for(let p=112;p<=142;p++) assert.ok(coverage.has(p));
const first=days[0],last=days[8];
assert.deepEqual(first.dayComponents.map(x=>x.key),["opening","narrative","point1","point2","point3","act","virtue","bouquet","prayers","collect"]);
for(let i=1;i<8;i++){
  assert.equal(days[i].dayComponents[0].key,"opening_reference");
  assert.equal(days[i].dayComponents.at(-1).key,"conclusion_reference");
  assert.equal(days[i].dayComponents[0].refDay,1);
  assert.deepEqual(days[i].dayComponents.at(-1).refSections,["prayers","collect"]);
}
assert.deepEqual(last.dayComponents.map(x=>x.key),["opening_reference","narrative","point1","point2","point3","act","virtue","bouquet","prayers_reprinted","collect_reprinted"]);
assert.equal(last.dayComponents[0].refDay,1);
assert.equal(last.dayComponents.at(-2).text===null,false);
assert.equal(last.dayComponents.at(-1).text===null,false);
assert.equal(last.dayNinePrintedConclusion.fullPrayerPrinted,true);
assert.equal(last.dayNinePrintedConclusion.fullCollectPrinted,true);
assert.equal(last.dayNinePrintedConclusion.openingReferenceOnly,true);
const oneCollect=first.dayComponents.find(x=>x.key==="collect").text;
const lastCollect=last.dayComponents.find(x=>x.key==="collect_reprinted").text;
assert.match(oneCollect,/dans l’éclat de la gloire céleste/);
assert.match(lastCollect,/dans l’éclat de sa gloire céleste/);
assert.notEqual(oneCollect,lastCollect);
assert.equal(last.dayComponents.at(-2).printedHeading,"PRIÈRE");
assert.equal(last.dayComponents.at(-1).printedHeading,"ORAISON");
assert.match(last.dayComponents.find(x=>x.key==="point1").text,/I\. Gloire de Jésus ressuscité/);
assert.match(last.dayComponents.find(x=>x.key==="point1").text,/Ô Sauveur adorable/);
assert.match(last.dayComponents.find(x=>x.key==="point2").text,/II\. Joie qu’Il communique/);
assert.match(last.dayComponents.find(x=>x.key==="point3").text,/III\. Louange dans l’éternité/);
assert.match(last.dayComponents.find(x=>x.key==="point3").text,/nous aimerons cet Homme-Dieu/);
assert.match(last.dayComponents.find(x=>x.key==="act").text,/Quand Le verrai-je face à face/);
assert.match(last.dayComponents.find(x=>x.key==="bouquet").text,/Dernières paroles de M\. Dupont/);
assert.equal(last.comparison.variants.length,10);
assert.deepEqual(last.comparison.englishParagraphIndicesByFrenchSection.prayers_reprinted,[8]);
assert.deepEqual(last.comparison.englishParagraphIndicesByFrenchSection.collect_reprinted,[9]);
assert.equal(NOVENA_HOLY_FACE_1887_B25.days.length,9);
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every((x,i)=>x.originalSourceDay===i+1 && x.text.en.length>3000 && x.text.fr===""));
assert.equal(HOLY_FACE_SOURCE_GATES_B25.verifiedFrenchPrayerBody,false);
assert.equal(HOLY_FACE_SOURCE_GATES_B25.originalPrintPhotoCollated,false);
console.log(`PASS: 9/9 French 1895 first-pass source records; 31 printed pages; ${totalOriginalCharacters} original French characters; ${totalVariants} edition/presentation holds; 0 independent second-proofs; 0 French public bodies; Day IX full print/collect variant preserved`);
