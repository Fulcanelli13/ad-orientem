import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const manifest=JSON.parse(readFileSync(new URL("../data/pray/prayer-corpus-ownership-foundation.v1.json",import.meta.url),"utf8"));
assert.equal(manifest.schema,"ao.prayer.corpus-ownership-foundation.v1");
assert.equal(manifest.records.length,94);
assert.equal(new Set(manifest.records.map(x=>x.key)).size,94);
const group=t=>manifest.records.filter(x=>x.record_type===t);
assert.equal(group("CANONICAL_PRAYER").length,48);
assert.equal(group("NOVENA_PROGRAM").length,18);
assert.equal(group("PERPETUAL_WEEKLY_DEVOTION").length,1);
assert.equal(group("HYMN_TEXT").length+group("HYMN_RECENSION").length,11);
assert.equal(group("PRAYER_ALTERNATE_WITNESS").length,4);
assert.equal(group("RELATED_EXTERNAL_PRAYER_LINK").length,1);
const bank=group("CANONICAL_PRAYER");
assert.deepEqual(Object.fromEntries(["en","fr","la"].map(l=>[l,bank.filter(x=>x.existing_texts[l]).length])),{en:48,fr:47,la:47});
assert.equal(bank.filter(x=>x.source_url).length,46);
assert.equal(manifest.summary.source_editions_fully_print_certified,"NOT_MEASURED_ACROSS_ALL_LANES");
assert.equal(manifest.summary.canonical_source_review_v3_fully_print_certified,0);
assert.ok(manifest.records.every(x=>x.edition_verification_gate==="NOT_ESTABLISHED_BY_OWNERSHIP_INVENTORY"));
assert.match(manifest.source_program_status.raccolta,/NOT_YET_COLLECTED/);
assert.match(manifest.source_program_status.sensus_fidelium,/NOT_YET_COLLECTED/);
assert.match(manifest.source_program_status.divine_office,/NOT_FULL_1962_HOURS_CORPUS/);
assert.ok(manifest.nonconflation.length>=15);
assert.ok(manifest.remaining_gates.length>=7);
console.log("Prayer ownership W01: 94 typed records, 48 canonical/19 novena/11 hymn/16 supplementary; external inventories correctly pending PASS");
