import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const C=JSON.parse(readFileSync(new URL('../data/geography/research/mass-scripture-source-extractions-20261011.v1.json',import.meta.url),'utf8'));
assert.equal(C.schema,'MASS_SCRIPTURE_SOURCE_EXTRACTION_V1');
assert.equal(C.status,'RESEARCH_SOURCED_NOT_1962_TEXT_CERTIFIED');
assert.equal(C.records.length,54);
assert.equal(C.primarySources.length,6);
assert.equal(C.holds.length,13);
assert.equal(new Set(C.records.map(x=>x.id)).size,C.records.length);
assert.ok(C.records.every(x=>x.attributableClaim?.length>=45 && x.liturgicalAnchor?.length>=4));
assert.ok(C.records.every(x=>C.classification.includes(x.relationType)));
assert.ok(C.records.every(x=>x.sources.length>0 && x.sources.every(s=>s.url?.startsWith('https://') && s.locator && s.webLineRange && s.inspection==='DIRECTLY_INSPECTED')));
assert.ok(C.records.every(x=>x.certification.forPublishing===false && x.certification.latin1962Text==='AWAITING_COMPARISON'));
assert.ok(C.records.every(x=>x.certification.historicalOrigin==='NOT_CERTIFIED'));
const types=Object.fromEntries(C.classification.map(k=>[k,C.records.filter(x=>x.relationType===k).length]));
assert.deepEqual(types,{TEXT_QUOTATION:16,LITURGICAL_EXPLICIT_FIGURE:3,SCRIPTURAL_TYPOLOGY_PATRISTIC:4,DEVOTIONAL_ANALOGY:19,HISTORICAL_ATTESTATION:8,MEDIEVAL_ALLEGORY:4});
assert.deepEqual(C.records.filter(x=>x.phase==='CANON_SUPRA_QUAE').map(x=>x.liturgicalAnchor).length,3);
assert.ok(C.records.find(x=>x.id==='MS035').sources.some(s=>s.author.includes('Cyprian')));
assert.ok(C.records.find(x=>x.id==='MS035').sources.some(s=>s.author.includes('Ambrose')));
assert.ok(C.records.find(x=>x.id==='MS036').sources.some(s=>s.author.includes('Aquinas')));
assert.ok(C.records.find(x=>x.id==='MS050').sources.some(s=>s.author.includes('Durand')));
assert.ok(C.holds.find(x=>x.code==='G1885_CANON_UNCHANGED'));
assert.ok(C.holds.find(x=>x.code==='D13_EMMAUS_NOT_ORIGIN'));
assert.ok(C.holds.find(x=>x.code==='D13_MY_FEIDEI'));
const anchorNames=C.records.map(x=>x.liturgicalAnchor.toLowerCase()).join('|');
assert.ok(anchorNames.includes('domine non sum dignus') && anchorNames.includes('supra')===false || C.records.some(x=>x.id==='MS033'&&x.phase==='CANON_SUPRA_QUAE'));
console.log('PASS research Mass–Scripture extraction:',C.records.length,'attributed records,',C.primarySources.length,'identified sources,',C.holds.length,'editorial holds; no publication approvals');
