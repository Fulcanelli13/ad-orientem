import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const D=JSON.parse(readFileSync(new URL("../data/geography/research/mass-proper-chant-bible-witnesses-batch01-20261011.v1.json",import.meta.url),"utf8"));
assert.equal(D.schema,"AO_MASS_VARIABLE_CHANT_SCRIPTURE_WITNESSES_RESEARCH_V1");
assert.equal(D.entries.length,32);
assert.equal(D.inspection.upstreamFilesInspected,8);
assert.equal(D.inspection.chantSectionsInspected,32);
assert.equal(D.inspection.sectionMultipleSourceMarkers,15);
assert.equal(new Set(D.entries.map(e=>e.id)).size,32);
assert.equal(new Set(D.entries.map(e=>e.properSourcePath+"|"+e.slot)).size,32);
for(const slot of ["INTROIT","GRADUAL","OFFERTORY","COMMUNION"])assert.equal(D.entries.filter(e=>e.slot===slot).length,8);
assert.ok(D.entries.every(e=>!e.published&&!e.isDirectBiblicalQuoteClaim&&!e.entireChantBiblicalTextCertified));
assert.ok(D.entries.every(e=>e.allScripturalMarkersInSection.length===e.markerCount&&e.markerCount>=1));
assert.ok(D.entries.every(e=>e.allScripturalMarkersInSection[0].sourceMarker===e.scriptureSourceMarkerOriginal&&e.allScripturalMarkersInSection[0].sourceLine===e.markerSourceLine));
assert.ok(D.entries.every(e=>e.upstreamSourceUrl==="https://github.com/DivinumOfficium/divinum-officium/blob/master/web/www/missa/Latin/"+e.properSourcePath+".txt"));
assert.ok(D.entries.some(e=>e.slot==="GRADUAL"&&e.markerCount>1));
assert.ok(D.entries.some(e=>e.properSourcePath==="Tempora/Pent01-4"&&e.slot==="OFFERTORY"&&e.scriptureSourceMarkerOriginal.includes("Levit")));
assert.ok(D.holds.some(s=>s.includes("Graduale")));
console.log("PASS 32 inspected chant sections, 8 upstream Proper files, 15 multi-marker sections; no promotion to liturgical/Bible certification");
