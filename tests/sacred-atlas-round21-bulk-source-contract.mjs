#!/usr/bin/env node
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';

const root='data/geography/research/';
const parse=x=>JSON.parse(readFileSync(root+x,'utf8'));
const screen=parse('sacred-atlas-round21-all26-commons-search-screen-20261104.v1.json');
const identity=parse('sacred-atlas-round21-akita-hales-subject-and-rights-20261104.v1.json');
const approved=JSON.parse(readFileSync('data/geography/approved-place-media.v1.json','utf8'));
const page=readFileSync(root+'sacred-atlas-undecided66-bulk-photo-review-20261104.html','utf8');
const match=page.match(/const places=(.*?); const auditStatuses=/s);
assert.ok(match,'66-place review embedded data missing');
const places=JSON.parse(match[1]);
assert.equal(places.length,66);
assert.equal(new Set(places.map(x=>x.id)).size,66);
assert.equal(places.filter(x=>x.candidates.length).length,40);
assert.equal(places.filter(x=>!x.candidates.length&&!x.legalHold).length,25);
assert.equal(places.reduce((n,p)=>n+p.candidates.length,0),125);
assert.equal(places.reduce((n,p)=>n+p.candidates.filter(c=>c.originalVerified).length,0),25);
assert.equal(approved.items.length,379,'No production cover may change');
const counts=screen.counts;
assert.equal(counts.target_places,26);
assert.equal(counts.raw_file_search_hits,190);
assert.equal(counts.search_hit_places,17);
assert.equal(counts.places_without_search_hits,9);
assert.equal(counts.unique_raster_images,31);
assert.equal(counts.minimum_format_dimension_pass,29);
assert.equal(counts.photographs_independently_identified_as_correct_target_building,0);
assert.equal(counts.new_covers_eligible_from_automatic_search,0);
assert.equal(counts.editorial_approved,0);
assert.equal(counts.published,0);
assert.equal(screen.site_screens.length,26);
assert.equal(new Set(screen.site_screens.map(r=>r.place_id)).size,26);
assert.equal(screen.site_screens.reduce((n,r)=>n+r.raw_hits,0),190);
assert.equal(screen.site_screens.reduce((n,r)=>n+r.raster_images,0),31);
assert.ok(screen.site_screens.every(r=>r.publication_authorized===false));
assert.equal(identity.rows.length,2);
assert.equal(identity.counts.new_distinct_source_files,1);
const akita=places.find(x=>x.id==='place:JP:our-lady-akita-convent');
assert.equal(akita.candidates.length,1);
assert.equal(akita.candidates[0].title,'File:Virgin Mary of Akita Japan.jpg');
assert.equal(akita.candidates[0].visualDecision,'HOLD_UNDERLYING_SCULPTURE_RIGHTS');
assert.equal(akita.candidates[0].publicationAuthorized,false);
assert.equal(akita.candidates[0].originalVerified,false);
const hales=places.find(x=>x.id==='place:US:sacred-heart-shrine-hales-corners');
assert.equal(hales.candidates.length,0);
assert.ok(hales.round21SubjectNote.includes('fountain'));
assert.ok(page.includes('if(filter==="round21"&&!p.candidates.some(c=>c.round21))return false;'));
assert.ok(page.includes('function coverBlocked(p,f)'));
const inline=[...page.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(inline.length,1);
new Script(inline[0][1],{filename:'66-place-review.js'});
console.log(JSON.stringify({status:'PASS',places:66,photo_leads:125,source_screens:26,wrong_site_rasters_excluded:31,manual_Akita_lead_on_hold:1,approved_covers:379,new_published:0}));
