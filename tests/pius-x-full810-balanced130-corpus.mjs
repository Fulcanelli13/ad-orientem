import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {resolve} from "node:path";
import {fileURLToPath} from "node:url";
const root=resolve(fileURLToPath(new URL("..",import.meta.url)));
const read=async name=>JSON.parse(await readFile(resolve(root,"artifacts/pius-x-complete-corpus/"+name),"utf8"));
const corpus=await read("SPX_810_Source_Owner_Coverage.json");
const release=await read("SPX_Balanced_130_Release_Candidates.json");
assert.equal(corpus.schema,"AO_SPX_COMPLETE_810_CORPUS_COVERAGE_V1");
assert.equal(release.schema,"AO_SPX_BALANCED_130_FIRST_RELEASE_CANDIDATE_SELECTION_V1");
assert.equal(corpus.records.length,810);
assert.equal(corpus.inventory.recordFamilies,810);
assert.equal(corpus.inventory.originalDraftTurns,1630);
assert.equal(corpus.inventory.recordedSourceOwnerFiles,80);
assert.equal(corpus.inventory.batchManifests,17);
assert.equal(Object.values(corpus.sourceFamiliesByBatch).reduce((n,x)=>n+x,0),810);
assert.equal(Object.values(corpus.subjectCoverage).reduce((n,x)=>n+x,0),810);
assert.equal(corpus.inventory.independentlySourceAndTheologyApproved,0);
assert.equal(corpus.inventory.publishedFromThisProgramme,0);
assert.equal(release.target,130);
assert.equal(release.actual,130);
assert.equal(release.candidates.length,130);
assert.equal(release.mandatoryDenzinger,false);
assert.equal(release.noPublishedAnswers,true);
assert.equal(release.noRuntimeChange,true);
assert.equal(new Set(release.candidates.map(x=>x.id)).size,130);
const map=new Map(corpus.records.map(x=>[x.id+"|"+x.ownerFile,x]));
for(const candidate of release.candidates){
 const source=map.get(candidate.id+"|"+candidate.ownerFile);
 assert.ok(source,"Selected candidate absent from original owner: "+candidate.id);
 assert.deepEqual(candidate.topic,source.topic);
 assert.deepEqual(candidate.draftPreview,source.draftPreview);
 assert.deepEqual(candidate.source,source.source);
 assert.ok(candidate.topic.en&&candidate.topic.fr&&candidate.draftPreview.en&&candidate.draftPreview.fr);
 assert.ok(candidate.ownerFile.startsWith("data/learn/research/"));
 assert.equal(candidate.approval.published,false);
 assert.equal(candidate.approval.independentlySourceCertified,false);
 assert.equal(candidate.approval.theologyApproved,false);
 assert.equal(candidate.approval.englishApproved,false);
 assert.equal(candidate.approval.frenchApproved,false);
 assert.equal(candidate.approval.historicalVoiceApproved,false);
 assert.ok(candidate.screeningFlags.includes("EN_FR_TRANSLATION_AND_SOURCE_CLAIMS_UNCERTIFIED"));
 assert.equal(candidate.candidateReason,"EDITORIAL_FIRST_RELEASE_SHORTLIST_NOT_SOURCE_OR_VOICE_APPROVAL");
}
assert.ok(release.selectedByCategory.PERSONAL_HISTORY>=10,"Insufficient actual personal-life coverage");
assert.ok(release.selectedByCategory.PAPAL_TEACHING_AND_PASTORAL>=18,"No substantial authentic papal teaching");
assert.ok(release.selectedByCategory.PRAYER_AND_SPIRITUAL_LIFE>=16);
assert.ok(release.selectedByCategory.FAITH_AND_CREED>=14);
assert.ok(release.selectedByCategory.MORAL_LIFE_AND_VIRTUES>=14);
assert.ok(release.selectedByCategory.SACRAMENTS_AND_MASS>=14);
assert.ok(release.selectedByCategory.FEASTS_AND_LITURGY>=8);
assert.ok(release.selectedByCategory.DEATH_AND_LAST_THINGS>=5);
assert.ok(corpus.records.every(x=>x.approval.published===false));
assert.ok(corpus.inventory.uniqueRecordIds<=810);
assert.ok(corpus.inventory.identicalOpeningEnglishQuestionClusters>=0);
const md=await readFile(resolve(root,"artifacts/pius-x-complete-corpus/SPX_Corpus_Progress_and_Release_Selection.md"),"utf8");
assert.ok(md.includes("zero independently approved answers"));
assert.ok(md.includes("Denzinger is OPTIONAL"));
console.log("PASS SPX full 810-family coverage, 1630 original turns, 130 balanced unpublished source-owner candidates; category breakdown",release.selectedByCategory);
