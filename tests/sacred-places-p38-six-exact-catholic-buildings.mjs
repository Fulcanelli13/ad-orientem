import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {auditShrineSource,assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=read("data/geography/research/sacred-places-p38-six-exact-catholic-buildings.v1.json"),g=read("data/geography/seed-registry.v1.json"),s=read("data/shrines/source-registry.v1.json");
const h=read("data/explore/heritage-place-reconciliation.review.v1.json"),sh=read("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P38_SIX_EXACT_CATHOLIC_BUILDINGS_V1");
assert.deepEqual(Object.values(m.baseline),[457,755,457,198,145,9]);
assert.deepEqual(Object.values(m.proposed),[463,761,463,204,145,9]);
assert.deepEqual([g.places.length,s.sources.length,h.place_crosswalk.length,h.exception_queues.places_without_direct_claim.length,g.geoAreas.length,g.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
assert.equal(LIVE.places,463);assert.equal(LIVE.sources,761);assert.equal(LIVE.areas,145);assert.equal(LIVE.links,9);
assert.equal(h.counts.places,LIVE.places);assert.equal(h.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(m.new_physical_locations,6);assert.equal(m.published_new.length,6);assert.equal(m.photo_assets_approved,0);assert.equal(m.tlm_schedule_links_added,0);
const rel=RELEASES.findIndex(x=>x.id==="P38");assert.ok(rel>0 && RELEASES[rel-1].id==="P37");
assert.equal(new Set(m.published_new.map(x=>x.candidate_id)).size,6);
assert.equal(new Set(m.published_new.map(x=>x.place_id)).size,6);
assert.equal(new Set(m.published_new.map(x=>x.geo_source_ref)).size,6);
const ids=new Set(m.published_new.map(x=>x.place_id)),previous=g.places.filter(x=>!ids.has(x.place_id));
assert.equal(previous.length,457);
const refs=new Set(previous.map(x=>x.geo?.source_ref).filter(Boolean));
const byId=new Map(g.places.map(x=>[x.place_id,x])),bySource=new Map(s.sources.map(x=>[x.id,x]));
assert.equal(byId.size,g.places.length);assert.equal(bySource.size,s.sources.length);
for(const x of m.published_new){
  assert.ok(!refs.has(x.geo_source_ref),"Duplicate OSM church way "+x.geo_source_ref);
  assert.match(x.geo_source_ref,/^osm:way:\\d+$/);
  assert.equal(x.geo_source_url,"https://www.openstreetmap.org/way/"+x.geo_source_ref.split(":")[2]);
  const p=byId.get(x.place_id);assert.ok(p);
  assert.equal(p.name.official,x.name);assert.equal(p.place_type,x.place_type);
  assert.equal(p.address.country_code,x.country);assert.deepEqual(p.geo_area_ids,["geo:country:"+x.country]);
  assert.deepEqual([p.geo.lat,p.geo.lng],[x.lat,x.lng]);assert.equal(p.geo.source_ref,x.geo_source_ref);assert.equal(p.geo.source_url,x.geo_source_url);
  assert.equal(p.geo.geocoding_source,"OSM");assert.equal(p.geo.precision,"site");assert.equal(p.geo.matched_country_code,x.country);
  assert.ok(isMapPublishablePlaceGeo(p.geo,x.country));
  assert.deepEqual(p.source_ids,x.source_ids);
  const src=bySource.get(x.source_ids[0]);assert.ok(src);
  assert.deepEqual(auditShrineSource(src),[]);assert.equal(src.url,x.identity_source_url);assert.equal(src.issuer,x.identity_source_issuer);
  assert.deepEqual(h.place_crosswalk.filter(c=>c.place_id===x.place_id).map(c=>c.record_ids),[{}]);
  assert.ok(h.exception_queues.places_without_direct_claim.includes(x.place_id));
  assert.ok(!g.directoryPlaceLinks.some(c=>c.place_id===x.place_id));assert.ok(!sh.shrines.some(c=>c.place_id===x.place_id));
  for(const f of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(p[f],undefined);
}
assert.equal(assertExploreGeographyRegistry(g).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...sh,sources:s.sources,places:g.places}).pass,true);
console.log("PASS P38: 6 distinct Catholic church buildings with named OSM footprints; "+LIVE.places+" Places, "+LIVE.sources+" sources, 3 protected complex holds");
