import assert from "node:assert/strict";
import fs from "node:fs";
import {fileURLToPath} from "node:url";
import path from "node:path";
const root=path.resolve(fileURLToPath(new URL("..",import.meta.url)));
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const dir="previews/visible-mass-3d/";
const graph=read(dir+"GUIDED_TRAIL_GRAPH_RESEARCH_20261018.v1.json");
const pilot=read(dir+"PHASE1_SANCTUARY_PILOT_QUESTIONS_20261017.v1.json");
const historical=read(dir+"HISTORICAL_SYMBOLIC_ANSWERS_20261017.v1.json");
const functional=read(dir+"HISTORICAL_FUNCTIONAL_ANSWERS_NEXT_20261017.v1.json");
const questionOwners=new Map(pilot.questions.map(q=>[q.id,q]));
const originalObjects=new Map(pilot.objects.map(o=>[o.object_id,o]));
const answers=[...historical.answers,...functional.answers];
const available=new Set(answers.map(a=>a.question_id));
const pool=new Set(graph.questionIds);
const held=new Set(graph.heldQuestionsOnly);
const activeObjects=new Set(graph.visibleHotspotIds);
const selectedCounts=Object.fromEntries(graph.visibleHotspotIds.map(id=>[id,0]));

assert.equal(graph.status,"RESEARCH_NAVIGATION_DESIGN_ONLY_NOT_PUBLICATION_NOT_A_SCRIPT");
assert.equal(pilot.status,"RESEARCH_ONLY_NO_PUBLICATION");
assert.equal(graph.trails.length,4);
assert.equal(pool.size,24);
assert.equal(graph.questionIds.length,24);
assert.equal(graph.crossovers.length,13);
assert.deepEqual(graph.visibleHotspotIds,["AL01","AL06","AL07","AL19","SN02","SN04"]);
assert.equal(graph.exactPhotoBinding,"BROMPTON_ALTAR_2019_B");
for(const id of pool){
 const q=questionOwners.get(id);
 assert.ok(q,"No original sanctuary question: "+id);
 assert.ok(activeObjects.has(q.primary_object_id),"Source question has no exact visible hotspot: "+id);
 const object=originalObjects.get(q.primary_object_id);
 assert.ok(object.scene_audit.scene_assets.includes(graph.exactPhotoBinding),"Lost photographic proof boundary: "+id);
 selectedCounts[q.primary_object_id]++;
}
assert.deepEqual(selectedCounts,{AL01:6,AL06:3,AL07:4,AL19:2,SN02:5,SN04:4});
assert.equal(available.size,97);
assert.equal(new Set(answers.map(x=>x.question_id)).size,97);
assert.equal(held.size,4);
assert.deepEqual([...held].sort(),["VMQ-0004","VMQ-0018","VMQ-0061","VMQ-0064"]);
assert.ok([...held].every(id=>pool.has(id)&&!available.has(id)),"Held questions cannot have a research-draft answer without renewed editorial triage");
assert.equal([...pool].filter(id=>available.has(id)).length,20);
assert.equal([...pool].filter(id=>!available.has(id)).length,4);
const trailIds=new Set(graph.trails.map(t=>t.id));
assert.deepEqual([...trailIds].sort(),["ALTAR_MYSTERY","FIRST_VISIT","FOLLOW_PRIEST","SANCTUARY_SECRETS"]);
const trailMembership=new Map();
for(const t of graph.trails){
 assert.equal(t.entry,t.suggested[0],"trail entry must identify the first suggested original question");
 assert.ok(t.suggested.length>=6&&t.suggested.length<=7);
 assert.equal(new Set(t.suggested).size,t.suggested.length);
 for(const id of t.suggested){
   assert.ok(pool.has(id)&&!held.has(id),"Auto route must not require held question "+id);
   assert.ok(available.has(id),"Every primary route stop must have a source-owned research draft: "+id);
   trailMembership.set(id,(trailMembership.get(id)||0)+1);
 }
}
assert.ok([...trailMembership.values()].filter(x=>x>=2).length>=4,"Tours do not share enough real discoveries");
assert.ok([...trailMembership.values()].filter(x=>x>=3).length>=2,"Tours risk behaving like separate courses");
for(const c of graph.crossovers){
 assert.ok(pool.has(c.from)&&pool.has(c.to)&&c.from!==c.to);
 assert.ok(!held.has(c.to),"Do not suggest a pending exact rubric as an auto crossover");
 assert.equal(c.status,"EDITORIAL_CONTEXTUAL_CANDIDATE_NO_PUBLICATION");
 assert.ok(c.editorialReason.length>=50);
}
assert.deepEqual(graph.optionalInvestigations.map(x=>x.entry),["VMQ-0059"]);
assert.ok(!graph.trails.some(t=>t.suggested.includes("VMQ-0059")),"Side investigation must stay optional");
const x=graph.interactionContract;
for(const key of ["guideIsOptional","enterAtAnyHotspot","skipAnySuggestedQuestion","skipWholeTrail","switchTrailAtAnyTime","jumpToAnyKnownObject","leaveGuidePreservesContext","revisitPolicy"]){
 assert.ok(x[key],key+" unavailable");
}
assert.equal(x.noNewQuestionTexts,true);
assert.equal(x.noNewAnswerTexts,true);
assert.equal(x.noAutomaticFreeTextGenerativeAnswers,true);
assert.equal(graph.publication.heldQuestions,"QUESTION_ONLY_NO_AUTOGENERATED_ANSWER");
assert.equal(graph.publication.publishedGuideLinks,"EXISTING_RUNTIME_ONLY_REQUIRE_SOURCE_SCOPED_REVIEW");

// Illustrative stateless resolver for review: no persistence, runtime owner or new text.
// Visited discoveries are global; skipping a suggestion is trail-local; dismissing
// a trail does not mark its shared questions as read.
function suggestion(trail,visited,trailSkipped){
 return trail.suggested.find(id=>!visited.has(id)&&!trailSkipped.has(id))??null;
}
const first=graph.trails.find(t=>t.id==="FIRST_VISIT");
const mystery=graph.trails.find(t=>t.id==="ALTAR_MYSTERY");
const visited=new Set(["VMQ-0013"]);
const skipped=new Set(["VMQ-0062"]);
assert.equal(suggestion(first,visited,skipped),"VMQ-0056");
assert.equal(suggestion(mystery,visited,new Set()),"VMQ-0014");
assert.ok(visited.has("VMQ-0013"),"switching trails cannot clear visited discoveries");
assert.ok(!visited.has("VMQ-0062"),"skipping is not equivalent to learning a subject");
assert.equal(mystery.suggested[0],"VMQ-0013","previously read entry remains manually revisit-able");

console.log("PASS Visible Mass route design: four non-linear trails, 24 original questions (20 research drafts, four held), six exact photo objects, 13 editorial crossovers, skip/switch/revisit semantics, no duplicated educational text.");
