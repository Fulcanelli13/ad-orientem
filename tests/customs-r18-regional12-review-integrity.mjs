import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const seed=load("data/customs/customs-atlas-seed.v1.json");
const review=load("data/customs/reviews/customs-r18-regional12-review-only.v1.json");
const audit=load("data/customs/reviews/customs-r18-regional12-evidence-identity-preflight.v1.json");
const names=["title","description","history","meaning","practice","caution","occasion","scope"];
const forbidden=new Set(["PENT-001"]);
const excluded=["CUSTOMS-R18-03","CUSTOMS-R18-13","CUSTOMS-R18-14","CUSTOMS-R18-15","CUSTOMS-R18-16"];
const allIds=new Set(seed.customs.map(x=>x.custom_id));
const reserved=new Set(["EPIP-003","CRIB-001"]);
assert.equal(seed.customs.filter(x=>x.publication_state==="PUBLISHED").length,review.baseline.canonical_published);
assert.equal(seed.customs.filter(x=>x.publication_state==="CONTEXT_ONLY").length,review.baseline.canonical_context_only);
assert.equal(review.records.length,12);
assert.equal(audit.rows.length,12);
assert.deepEqual(audit.counts,{candidate_articles:12,existing_research_ids:6,additional_proposed_ids_not_allocated:6,narrow_claims_supported_by_direct_read:7,narrow_claims_supported_by_indexed_text:5,full_articles_certified:0,owner_signoffs:0,publication_authorizations:0});
assert.ok(Object.values(review.policies).every(x=>x===true));
assert.ok(Object.values(audit.policies).every(x=>x===true));
const seenKeys=new Set(),seenIds=new Set(),reviewMap=new Map(review.records.map(x=>[x.review_key,x]));
for(const key of excluded)assert.equal(reviewMap.has(key),false,"Previously published or locality-only draft must be excluded: "+key);
for(const record of audit.rows){
 const row=reviewMap.get(record.review_key);
 assert.ok(row,"Audit must have matching bilingual record: "+record.review_key);
 assert.equal(seenKeys.has(record.review_key),false,"Duplicate research key");
 seenKeys.add(record.review_key);
 const id=record.proposed_id_for_editorial_review_only;
 assert.match(id,/^[A-Z]+-[0-9]{3}$/);
 assert.equal(seenIds.has(id),false,"Duplicated provisional ID");
 seenIds.add(id);
 assert.equal(allIds.has(id),false,"Candidate cannot collide with live canonical ID "+id);
 assert.equal(reserved.has(id),false,"Candidate cannot collide with separate #1642 cohort "+id);
 assert.equal(row.proposed_canonical_id||null,record.proposed_id_is_not_canonical_or_reserved?null:id);
 assert.equal(record.identity_decision,"DISTINCT_CANDIDATE_PENDING_OWNER_REVIEW");
 assert.equal(record.canonical_write_authorized,false);
 assert.equal(row.publication_authorized,false);
 assert.equal(row.calendar_activation_authorized,false);
 assert.ok(Object.values(row.owner_decision).every(x=>x==="PENDING"));
 assert.ok(Object.values(record.publication_decisions).every(x=>x==="PENDING"));
 assert.ok((record.identity_comparison_ids||[]).every(x=>allIds.has(x)));
 assert.ok(["DIRECT_PAGE","INDEXED_SOURCE_TEXT"].includes(record.primary_source_check.method));
 assert.match(record.primary_source_check.url,/^https:\/\//);
 assert.equal(record.primary_source_check.status,"NARROW_FACT_CORROBORATED_NOT_FULL_ARTICLE_CERTIFICATION");
 assert.equal(row.source_assessment.full_article_certified,false,"No full historical copy signoff can be inferred");
 assert.ok(row.source_links.length>=1 && row.source_links.every(s=>/^https:\/\//.test(s.url)));
 for(const f of names)for(const lang of ["en","fr"])
  assert.ok(row.article[f]?.[lang]?.trim().length>=4,record.review_key+" lacks "+f+" "+lang);
}
assert.deepEqual([...seenKeys].sort(),review.records.map(x=>x.review_key).sort());
assert.equal([...seenIds].filter(x=>reserved.has(x)).length,0);
assert.equal(review.records.filter(x=>x.exception).length,5);
assert.equal(audit.rows.filter(x=>x.remaining_exception).length,5);
assert.equal(audit.rows.filter(x=>x.proposed_id_is_not_canonical_or_reserved).length,6);
console.log("PASS Customs R18 regional12 preflight: 12 bilingual articles, 12 collision-free proposed IDs, 7 direct sources, 5 indexed sources; 0 owner approvals, 0 publication");
