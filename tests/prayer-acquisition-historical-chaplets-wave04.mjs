import assert from "node:assert/strict";
import {HISTORICAL_CHAPLET_SOURCE_CANDIDATES_V1,historicalChapletCandidate} from "../src/pray/prayer-acquisition-chaplet-structures.v1.js";
import {PRAY_CANONICAL_DATA_V435930} from "../src/pray/canonical-data.js";
const entries=HISTORICAL_CHAPLET_SOURCE_CANDIDATES_V1;
const ids=new Set(entries.map(x=>x.id));
assert.equal(entries.length,3);
assert.equal(ids.size,3);
assert.ok(entries.every(x=>x.releaseStatus.startsWith("HOLD_") && x.userFacing===false));
assert.ok(entries.every(x=>x.sourceUrls.length>=2 && x.sourceUrls.every(url=>url.startsWith("https://"))));
const wounds=historicalChapletCandidate("raccolta_1857_five_wounds");
assert.equal(wounds.historicalEntry,32);
assert.equal(wounds.groups.length,5);
assert.deepEqual(wounds.groups.map(x=>x.repetitions),[5,5,5,5,5]);
assert.deepEqual(wounds.groups.map(x=>x.concludingRepetitions),[1,1,1,1,1]);
assert.equal(wounds.derivedCounts.glory_be,25);
assert.equal(wounds.derivedCounts.hail_mary,5);
assert.ok(wounds.groups.every(x=>PRAY_CANONICAL_DATA_V435930.prayers[x.repeatedPrayerId]));
assert.ok(wounds.groups.every(x=>PRAY_CANONICAL_DATA_V435930.prayers[x.concludingPrayerId]));
const blood=historicalChapletCandidate("raccolta_1857_precious_blood_full");
assert.equal(blood.historicalEntry,35);
assert.deepEqual(blood.mysteries.map(x=>x.pater),[5,5,5,5,5,5,3]);
assert.equal(blood.mysteries.reduce((n,m)=>n+m.pater,0),33);
assert.equal(blood.mysteries.reduce((n,m)=>n+m.gloria,0),7);
assert.ok(PRAY_CANONICAL_DATA_V435930.prayers[blood.repeatedPrayerIds.pater]);
assert.ok(PRAY_CANONICAL_DATA_V435930.prayers[blood.repeatedPrayerIds.gloria]);
assert.equal(blood.closingPrayer,"MOST_PRECIOUS_BLOOD_PRAYER_HISTORICAL_TEXT_NOT_YET_COLLATED");
const shortened=historicalChapletCandidate("raccolta_1857_precious_blood_short");
assert.equal(shortened.historicalEntry,40);
assert.equal(shortened.claimedTotalPater,33);
assert.equal(shortened.reproducedMysteryCounts.reduce((a,b)=>a+b,0),35);
assert.equal(shortened.reproducedTotalPater,35);
assert.equal(shortened.structureStatus,"CONTRADICTORY_SOURCE_REPETITION_COUNT");
assert.equal(shortened.releaseStatus,"HOLD_SOURCE_CONFLICT");
assert.equal(historicalChapletCandidate("nonexistent"),null);
console.log("Wave04 chaplet sources: Five Wounds 25+5, full Blood 33, short Blood 35-vs-33 HOLD; zero live releases PASS");
