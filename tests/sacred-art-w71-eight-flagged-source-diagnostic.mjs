import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Script } from "node:vm";
const base=new URL("../",import.meta.url);
const load=path=>readFileSync(new URL(path,base),"utf8");
const manifest=JSON.parse(load("data/research/sacred-art-w71-w68-eight-source-flags-review-manifest-20261015.v1.json"));
const html=load("docs/research/review-galleries/ao-sacred-art-w71-eight-source-image-diagnostic-20261015.html");
const data=JSON.parse(html.match(/<script type="application\/json" id="data">([\s\S]*?)<\/script>/)?.[1]??"null");
let count=0;
function check(condition,label){assert.ok(condition,label);count++}
check(manifest.schema==="AO_SACRED_ART_W71_EIGHT_ORIGINAL_SOURCE_FLAG_DIAGNOSTIC_V1","schema");
check(manifest.cards.length===8,"exact eight source flag cards");
check(new Set(manifest.cards.map(x=>x.candidateId)).size===8,"unique IDs");
check(manifest.cards.filter(x=>x.originalRating===4).length===5,"five existing four-star scores");
check(manifest.cards.filter(x=>x.originalRating===3).length===3,"three existing three-star scores");
check(manifest.cards.every(x=>x.originalSourceIssueFlag&&x.currentPublicationApproved===false),"original flags and publication holds");
check(manifest.cards.every(x=>x.reviewedImageSourceURL.startsWith("https://commons.wikimedia.org/wiki/File:")),"exact known photo page");
check(manifest.cards.every(x=>x.reviewedImagePreviewURL.startsWith("https://commons.wikimedia.org/wiki/Special:FilePath/File:")),"original reviewed photo thumbnail not altered");
check(manifest.cards.every(x=>typeof x.knownDepiction==="string"&&typeof x.knownSourceFindings==="string"),"original metadata linked");
check(manifest.cards.every(x=>x.technicalStatus.includes("UNVERIFIED")),"no image/object equivalence asserted");
check(data.batchId===manifest.batchId&&data.cards.length===manifest.cards.length,"frozen embedded manifest");
check(manifest.cards.every((x,i)=>data.cards[i].candidateId===x.candidateId),"exact embedded IDs");
check(html.includes("recordedRatingsAreReadOnly:true"),"export score readonly");
check(html.includes("originalUserFlagAutomaticallyCleared:false"),"no source flag auto clearance");
check(html.includes("loadObservedThisSession"),"image load recorded");
check(html.includes("localStorage.setItem")&&html.includes("Import previous notes"),"browser local persistence and import");
check(html.includes("sourcePage:c.reviewedImageSourceURL"),"export retains exact user-reviewed source");
check(html.includes("wrong_artwork_or_attribution")&&html.includes("frame_or_church_setting"),"useful diagnostic reasons");
check(!/<script\s+src=/i.test(html),"no external script dependencies");
check(!/<input[^>]*type="radio"/i.test(html),"no rerating controls");
const js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
check(!!js,"embedded client-side script");
new Script(js,{filename:"w71-eight-source-flags.js"});count++;
console.log("W71 artwork diagnostic source invariant checks "+count+"/"+count+" passed");
