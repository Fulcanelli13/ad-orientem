assert.equal(idx.get("STG-pray.rosary-13").works.filter(w=>w.decision.status==="ALREADY_USER_APPROVED_FOR_SUBJECT").length,2);
assert.equal(idx.get("STG-pray.rosary-14").works.filter(w=>w.decision.status==="ALREADY_USER_APPROVED_FOR_SUBJECT").length,2);
