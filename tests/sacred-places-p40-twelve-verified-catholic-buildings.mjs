import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {auditShrineSource,assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=read("data/geography/research/sacred-places-p40-twelve-verified-catholic-buildings.v1.json");
const g=read("data/geography/seed-registry.v1.json"),s=read("data/shrines/source-registry.v1.json");
const h=read("data/explore/heritage-place-reconciliation.review.v1.json"),sh=read("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P40_TWELVE_VERIFIED_CATHOLIC_BUILDINGS_V1");
assert.deepEqual(Object.values(m.baseline),[463,761,463,204,145,9]);
assert.deepEqual(Object.values(m.proposed),[475,773,475,216,146,9]);
assert.ok(RELEASES.some(r=>r.id==="P40"));
assert.deepEqual([g.places.length,s.sources.length,h.place_crosswalk.length,h.exception_queues.places_without_direct_claim.length,g.geoAreas.length,g.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
assert.ok(LIVE.places>=475);assert.ok(LIVE.sources>=773);assert.ok(LIVE.areas>=146);assert.equal(LIVE.links,9);
assert.equal(h.counts.places,LIVE.places);assert.equal(h.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(m.published_new.length,12);assert.equal(m.new_physical_locations,12);
assert.equal(m.photo_assets_approved,0);assert.equal(m.tlm_schedule_links_added,0);
const index=RELEASES.findIndex(x=>x.id==="P40");assert.ok(index>0&&RELEASES[index-1].id==="P38");
assert.deepEqual(m.new_geo_areas,["geo:country:PR"]);
const prArea=g.geoAreas.filter(x=>x.geo_area_id==="geo:country:PR");
assert.equal(prArea.length,1);
assert.deepEqual(prArea[0].codes,{iso_alpha2:"PR"});
assert.equal(prArea[0].area_type,"country");
const placesById=new Map(g.places.map(x=>[x.place_id,x])),srcById=new Map(s.sources.map(x=>[x.id,x]));
assert.equal(placesById.size,g.places.length);assert.equal(srcById.size,s.sources.length);
const newIds=new Set(m.published_new.map(x=>x.place_id));
const subsequentIds=new Set(RELEASES.slice(index+1).flatMap(r=>(r.data.published_new||[]).map(x=>x.place_id)));
const prev=g.places.filter(x=>!newIds.has(x.place_id)&&!subsequentIds.has(x.place_id));
assert.equal(newIds.size,12);assert.equal(prev.length,463);
const usedRefs=new Set(prev.map(x=>x.geo?.source_ref).filter(Boolean)),newRefs=new Set(),cand=new Set();
for(const row of m.published_new){
 assert.ok(!cand.has(row.candidate_id));cand.add(row.candidate_id);
 assert.ok(!newRefs.has(row.geo_source_ref)&&!usedRefs.has(row.geo_source_ref),"OSM exact geometry collision: "+row.geo_source_ref);newRefs.add(row.geo_source_ref);
 assert.match(row.geo_source_ref,/^osm:(way|relation):\d+$/);
 assert.equal(row.geo_source_url,"https://www.openstreetmap.org/"+row.geo_source_ref.split(":")[1]+"/"+row.geo_source_ref.split(":")[2]);
 assert.ok(["church","basilica","cathedral","yes"].includes(row.osm_building));
 const place=placesById.get(row.place_id);assert.ok(place);
 assert.equal(place.name.official,row.name);assert.equal(place.place_type,row.place_type);
 assert.equal(place.address.country_code,row.country);assert.deepEqual(place.geo_area_ids,["geo:country:"+row.country]);
 assert.deepEqual([place.geo.lat,place.geo.lng],[row.lat,row.lng]);
 assert.equal(place.geo.source_ref,row.geo_source_ref);assert.equal(place.geo.source_url,row.geo_source_url);
 assert.equal(place.geo.geocoding_source,"OSM");assert.equal(place.geo.precision,"site");
 assert.equal(place.geo.matched_country_code,row.country);assert.ok(isMapPublishablePlaceGeo(place.geo,row.country));
 assert.deepEqual(place.source_ids,row.source_ids);
 const src=srcById.get(row.source_ids[0]);assert.ok(src);
 assert.deepEqual(auditShrineSource(src),[]);
 assert.equal(src.url,row.identity_source_url);assert.equal(src.issuer,row.identity_source_issuer);
 assert.deepEqual(h.place_crosswalk.filter(x=>x.place_id===row.place_id).map(x=>x.record_ids),[{}]);
 assert.ok(h.exception_queues.places_without_direct_claim.includes(row.place_id));
 assert.ok(!g.directoryPlaceLinks.some(x=>x.place_id===row.place_id));
 assert.ok(!sh.shrines.some(x=>x.place_id===row.place_id));
 for(const f of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(place[f],undefined);
}
assert.equal(assertExploreGeographyRegistry(g).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...sh,sources:s.sources,places:g.places}).pass,true);
console.log("PASS P40: 12 Catholic building geometries across ten ISO territories, 475 canonical Places, 773 sources and new Puerto Rico area. No schedules or images added.");
