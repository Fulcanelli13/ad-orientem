import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {auditShrineSource,assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=load("data/geography/research/sacred-places-p28-world-11-exact-map.v1.json");
const geo=load("data/geography/seed-registry.v1.json");
const ss=load("data/shrines/source-registry.v1.json");
const cross=load("data/explore/heritage-place-reconciliation.review.v1.json");
const shrine=load("data/shrines/shrines-pilgrimages-seed.v1.json");
const p16=load("data/geography/research/sacred-places-p16-three-qualified-site-release.v1.json");
const p27=load("data/geography/research/sacred-places-p27-osm-search-seeds.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P28_WORLD_11_EXACT_MAP_V1");
assert.deepEqual([m.baseline.places,m.baseline.sources,m.baseline.crosswalk,m.baseline.unlinked,m.baseline.geo_areas],[387,685,387,128,141]);
assert.deepEqual([m.proposed.places,m.proposed.sources,m.proposed.crosswalk,m.proposed.unlinked,m.proposed.geo_areas],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas]);
assert.deepEqual([geo.places.length,ss.sources.length,cross.place_crosswalk.length,cross.exception_queues.places_without_direct_claim.length,geo.geoAreas.length,geo.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
assert.equal(cross.counts.places,LIVE.places);assert.equal(cross.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(p16.held_exceptions.length,16);
assert.ok(RELEASES.some(x=>x.id==="P28"));
assert.equal(m.published_new.length,11);assert.equal(m.reused_existing.length,2);
assert.equal(new Set(m.published_new.map(x=>x.place_id)).size,11);
assert.equal(new Set(m.published_new.map(x=>x.geo_source_ref)).size,11);
assert.equal(new Set(m.published_new.map(x=>x.country)).size,11);
assert.ok(geo.geoAreas.some(x=>x.geo_area_id==="geo:country:PA"&&x.codes.iso_alpha2==="PA"));
const byPlace=new Map(geo.places.map(x=>[x.place_id,x])),bySource=new Map(ss.sources.map(x=>[x.id,x]));
assert.equal(byPlace.size,geo.places.length);assert.equal(bySource.size,ss.sources.length);
const oldRefs=new Set(geo.places.filter(x=>!m.published_new.some(y=>y.place_id===x.place_id)).map(x=>x.geo?.source_ref).filter(Boolean));
for(const old of m.reused_existing){let p=byPlace.get(old.place_id);assert.ok(p);if(old.geo_source_ref)assert.equal(p.geo.source_ref,old.geo_source_ref);assert.ok(!m.published_new.some(x=>x.candidate_id===old.candidate_id));}
for(const row of m.published_new){
 assert.ok(!oldRefs.has(row.geo_source_ref));assert.match(row.geo_source_ref,/^osm:way:\d+$/);
 assert.match(row.geo_provenance_mapcarta_url,/^https:\/\/mapcarta\.com\//);
 const p=byPlace.get(row.place_id);assert.ok(p);
 assert.equal(p.name.official,row.name);assert.equal(p.place_type,row.place_type);
 assert.equal(p.address.country_code,row.country);assert.equal(p.geo.matched_country_code,row.country);
 assert.equal(p.geo_area_ids[0],"geo:country:"+row.country);
 assert.deepEqual([p.geo.lat,p.geo.lng],[row.lat,row.lng]);
 assert.equal(p.geo.source_ref,row.geo_source_ref);assert.equal(p.geo.source_url,row.geo_source_url);
 assert.equal(p.geo.precision,"site");assert.ok(isMapPublishablePlaceGeo(p.geo,row.country));
 assert.deepEqual(p.source_ids,row.source_ids);assert.equal(p.source_ids.length,1);
 const s=bySource.get(p.source_ids[0]);assert.ok(s);assert.equal(auditShrineSource(s).length,0);
 assert.equal(s.url,row.identity_source_url);
 assert.ok(cross.exception_queues.places_without_direct_claim.includes(row.place_id));
 assert.deepEqual(cross.place_crosswalk.find(x=>x.place_id===row.place_id).record_ids,{});
 assert.ok(!geo.directoryPlaceLinks.some(l=>l.place_id===row.place_id));
 assert.ok(!shrine.shrines.some(x=>x.place_id===row.place_id));
 assert.ok(!p27.candidates.some(x=>x.candidate_id===row.candidate_id&&x.exact_identity_verified));
 for(const field of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(p[field],undefined);
}
assert.equal(byPlace.get("place:DE:kevelaer-gnadenkapelle").geo.source_ref,"osm:way:152838064");
assert.equal(byPlace.get("place:DE:kevelaer-kerzenkapelle").geo.source_ref,"osm:way:152838071");
assert.equal(byPlace.get("place:ES:santa-maria-de-montserrat-abbey").geo.precision,"complex_anchor");
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrine,sources:ss.sources,places:geo.places}).pass,true);
console.log("PASS P28: eleven new exact Catholic sites in eleven countries; two existing IDs reused; immutable heritage holds");
