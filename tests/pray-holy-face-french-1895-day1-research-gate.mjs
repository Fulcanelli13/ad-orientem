import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_HOLY_FACE_1887_B25} from "../src/pray/holy-face-janvier-1887-b25.js";
const r=JSON.parse(readFileSync(new URL("../data/pray/research/pray-holy-face-1895-fr-day01-transcribed-proofread.v1.json",import.meta.url),"utf8"));
assert.equal(r.schema,"ao.pray.holy-face.french-1895-day-transcription.v1");
assert.equal(r.canonicalId,NOVENA_HOLY_FACE_1887_B25.id);
assert.equal(r.day,1);
assert.deepEqual(r.printedPages,[112,113,114,115]);
assert.deepEqual(r.pdfZeroBasedPages,[118,119,120,121]);
assert.equal(r.dayComponents.length,10);
assert.deepEqual(r.dayComponents.map(s=>s.key),["opening","narrative","point1","point2","point3","act","virtue","bouquet","prayers","collect"]);
assert.equal(r.comparison.components.length,10);
assert.ok(r.dayComponents.every(s=>s.text.length>90&&s.pages.length>0));
assert.ok(r.dayComponents.reduce((a,s)=>a+s.text.length,0)>3500);
assert.match(r.dayComponents[0].text,/Seigneur, je veux rechercher votre Face/);
assert.match(r.dayComponents[1].text,/Entrez dans la grotte de Bethléem/);
assert.match(r.dayComponents[5].text,/Rendez-lui amour pour amour/);
assert.match(r.dayComponents[7].text,/vous avez mis la joie dans mon cœur/);
assert.match(r.dayComponents[9].text,/Par le même Jésus-Christ Notre-Seigneur\. Ainsi soit-il\./);
assert.equal(r.release,"RESEARCH_ONLY_NOT_BOUND_TO_PUBLIC_READER");
assert.equal(r.frenchBodyInCanonicalReader,"EMPTY");
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every((d,i)=>d.originalSourceDay===i+1&&d.text.fr===""));
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every(d=>d.text.en.length>3000));
assert.equal(r.comparison.status,"TEN_SECTION_BILINGUAL_FIRST_PASS_ALIGNED__SECOND_PROOF_AND_PRINT_VARIANTS_PENDING");
assert.equal(r.comparison.variants.length,2);
assert.deepEqual(r.comparison.englishParagraphIndicesByFrenchSection.narrative,[1,2]);
console.log("PASS day-1 1895 original-language French 10-section research transcript; canonical 9-day EN preserved and FR still held");
