import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {auditShrineSource,assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=read("data/geography/research/sacred-places-p37-eight-exact-churches.v1.json");
const g=read("data/geography/seed-registry.v1.json"),s=read("data/shrines/source-registry.v1.json");
const h=read("data/explore/heritage-place-reconciliation.review.v1.json"),sh=read("data/shrines/shrines-pilgrimages-seed.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P37_EIGHT_EXACT_CHURCH_BUILDINGS_V1");
assert.deepEqual(Object.values(m.baseline),[449,747,449,190,145,9]);
assert.deepEqual(Object.values(m.proposed),[457,755,457,198,145,9]);
assert.deepEqual([g.places.length,s.sources.length,h.place_crosswalk.length,h.exception_queues.places_without_direct_claim.length,g.geoAreas.length,g.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
assert.equal(h.counts.places,LIVE.places);
assert.equal(h.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(m.new_physical_locations,8);
assert.equal(m.published_new.length,8);
assert.equal(m.photo_assets_approved,0);
assert.equal(m.tlm_schedule_links_added,0);
assert.equal(m.held_scope.length,3);
assert.equal(new Set(m.published_new.map(r=>r.candidate_id)).size,8);
assert.equal(new Set(m.published_new.map(r=>r.place_id)).size,8);
assert.equal(new Set(m.published_new.map(r=>r.geo_source_ref)).size,8);
const index=RELEASES.findIndex(r=>r.id==="P37");
assert.ok(index>0&&RELEASES[index-1].id==="P36");
const p37ids=new Set(m.published_new.map(r=>r.place_id));
const subsequentIds=new Set(RELEASES.slice(index+1).flatMap(r=>(r.data.published_new||[]).map(x=>x.place_id)));
const previous=g.places.filter(x=>!p37ids.has(x.place_id)&&!subsequentIds.has(x.place_id));
assert.equal(previous.length,m.baseline.places);
const previousRefs=new Set(previous.map(x=>x.geo?.source_ref).filter(Boolean));
const sourceById=new Map(s.sources.map(x=>[x.id,x])),placeById=new Map(g.places.map(x=>[x.place_id,x]));
assert.equal(sourceById.size,s.sources.length);
assert.equal(placeById.size,g.places.length);
for(const row of m.published_new){
 assert.ok(!previousRefs.has(row.geo_source_ref),"Duplicate physical OSM way "+row.geo_source_ref);
 assert.match(row.geo_source_ref,/^osm:way:\d+$/);
 assert.equal(row.geo_source_url,"https://www.openstreetmap.org/way/"+row.geo_source_ref.split(":")[2]);
 const p=placeById.get(row.place_id);assert.ok(p);
 assert.equal(p.name.official,row.name);
 assert.equal(p.address.country_code,row.country);
 assert.equal(p.place_type,row.place_type);
 assert.deepEqual(p.geo_area_ids,["geo:country:"+row.country]);
 assert.deepEqual([p.geo.lat,p.geo.lng],[row.lat,row.lng]);
 assert.equal(p.geo.source_ref,row.geo_source_ref);
 assert.equal(p.geo.source_url,row.geo_source_url);
 assert.equal(p.geo.geocoding_source,"OSM");
 assert.equal(p.geo.precision,"site");
 assert.equal(p.geo.matched_country_code,row.country);
 assert.ok(isMapPublishablePlaceGeo(p.geo,row.country));
 assert.deepEqual(p.source_ids,row.source_ids);
 const src=sourceById.get(row.source_ids[0]);assert.ok(src);
 assert.deepEqual(auditShrineSource(src),[]);
 assert.equal(src.url,row.identity_source_url);
 assert.equal(src.issuer,row.identity_source_issuer);
 assert.deepEqual(h.place_crosswalk.filter(x=>x.place_id===row.place_id).map(x=>x.record_ids),[{}]);
 assert.ok(h.exception_queues.places_without_direct_claim.includes(row.place_id));
 assert.ok(!g.directoryPlaceLinks.some(x=>x.place_id===row.place_id));
 assert.ok(!sh.shrines.some(x=>x.place_id===row.place_id));
 for(const fld of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(p[fld],undefined);
}
assert.equal(assertExploreGeographyRegistry(g).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...sh,sources:s.sources,places:g.places}).pass,true);
console.log("PASS P37: 8 independent Catholic church buildings, exact map sources, "+LIVE.places+" Places and "+LIVE.sources+" typed sources; 3 complex-building holds protected");
