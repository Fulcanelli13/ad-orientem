import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {CSE_DEBATE_MAP,CSE_DEBATE_IDS,CSE_DEBATE_FIELDS} from "../src/learn/sexual-ethics-data/debates.js";
import {CSE_SOURCE_MAP} from "../src/learn/sexual-ethics-data/sources.js";
import {CSE_HIGH_STAGE_SOURCE_IDS} from "../src/learn/sexual-ethics-data/stage-evidence-high24.js";
import {CSE_REMAINING_STAGE_SOURCE_IDS} from "../src/learn/sexual-ethics-data/stage-evidence-remaining31.js";
const newer=JSON.parse(readFileSync("data/learn/sexual-ethics-catholic-side-remaining44-20261009.v1.json","utf8"));
const prior=JSON.parse(readFileSync("data/learn/sexual-ethics-catholic-side-original-context-11-20261009.v1.json","utf8"));
const high=JSON.parse(readFileSync("data/learn/sexual-ethics-stage-evidence-high24.v1.json","utf8"));
const lower=JSON.parse(readFileSync("data/learn/sexual-ethics-stage-evidence-remaining31.v1.json","utf8"));
const frozen=JSON.parse(readFileSync("data/learn/sexual-ethics-opponent-attribution-55-20261009.v1.json","utf8"));
const ledger=JSON.parse(readFileSync("data/learn/sexual-ethics-certification-evidence.v2.json","utf8"));
const stage={...CSE_HIGH_STAGE_SOURCE_IDS,...CSE_REMAINING_STAGE_SOURCE_IDS};
const ids=prior.cases.map(x=>x.id).concat(newer.cases.map(x=>x.id));
assert.equal(CSE_DEBATE_IDS.length,55);
assert.equal(CSE_DEBATE_FIELDS.length,8);
assert.equal(prior.cases.length,11);
assert.equal(newer.cases.length,44);
assert.equal(newer.summary.previously_bounded_11,11);
assert.equal(newer.summary.newly_source_scoped_44,44);
assert.equal(newer.summary.whole_eight_stage_debates_certified,0);
assert.equal(newer.summary.independent_theological_approvals,0);
assert.equal(newer.summary.independent_french_approvals,0);
assert.equal(new Set(ids).size,55);
assert.deepEqual([...ids].sort(),[...CSE_DEBATE_IDS].sort());
assert.equal(newer.cases.filter(x=>["CSE055","CSE056","CSE058"].includes(x.id)).length,3);
const allowed=new Set(["ORIGINAL_SOURCE_CONTEXT_VIEWED","ITALIAN_AUTHOR_ORIGINAL_VIEWED","MANUAL_FULL_PASSAGE_NOT_COLLATED","GENERAL_SCRIPTURE_INDEX_ONLY","REGISTERED_LOCATOR_UNCOLLATED"]);
for(const row of newer.cases){
 const src=CSE_SOURCE_MAP[row.principal_catholic_source_id];
 assert.ok(CSE_DEBATE_MAP[row.id],row.id+" absent");
 assert.ok(src&&src.canonical_url===row.source_url,row.id+" incorrect original source URL");
 assert.ok(row.passage_locator.length>=3&&row.bounded_supported_claim.length>30,row.id+" missing claim-level limitation");
 assert.ok(row.claim_scope_limit.length>50,row.id+" missing evidence caveat");
 assert.ok(allowed.has(row.source_context_access),row.id+" unrecognized verification status");
 assert.equal(row.eight_stage_catholic_claims_all_collated,false);
 assert.equal(row.independent_theological_approval,false);
 assert.equal(row.independent_french_approval,false);
 const selected=stage[row.id];
 assert.ok(["concession","breakpoint","catholicCase","response","bottom"].some(k=>selected[k].includes(row.principal_catholic_source_id)),row.id+" source missing from Catholic stages");
 assert.deepEqual(frozen.cases.find(x=>x.id===row.id).stage_source_ids,selected,row.id+" frozen stage drift");
 assert.deepEqual(ledger.cases.find(x=>x.id===row.id).stages.map(s=>s.selected_source_ids),CSE_DEBATE_FIELDS.map(k=>selected[k]),row.id+" certification ledger drift");
}
assert.ok(CSE_HIGH_STAGE_SOURCE_IDS.CSE040.catholicCase.includes("CIC"));
assert.ok(CSE_REMAINING_STAGE_SOURCE_IDS.CSE141.catholicCase.includes("FRANCIS_SPADARO2013"));
assert.deepEqual(CSE_HIGH_STAGE_SOURCE_IDS.CSE040,high.cases.CSE040.stage_source_ids);
assert.deepEqual(CSE_REMAINING_STAGE_SOURCE_IDS.CSE141,lower.cases.CSE141.stage_source_ids);
assert.match(CSE_DEBATE_MAP.CSE050.response[0],/civil legal status/);
assert.match(CSE_DEBATE_MAP.CSE050.response[1],/statut juridique civil/);
console.log("PASS 44 remaining Catholic-side source-scope records + earlier 11 = 55 canonical debates, 2 stage-link repairs, 1 bilingual juridical correction, 3 archived retained, 0 fabricated approvals");
