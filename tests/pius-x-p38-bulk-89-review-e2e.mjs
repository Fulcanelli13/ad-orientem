 assert.equal(await page.locator('#items button').count(),21);
 await page.locator('#lane').selectOption('');
 await page.locator('#flag').selectOption('COMPOSITE_SOURCE_ARGUMENT');
 assert((await page.locator('#items button').count())>=2);
