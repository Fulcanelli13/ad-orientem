assert.equal(decisions.policy.zero_new_top_level_modules,true);
assert.deepEqual(Object.keys(decisions.summary.by_decision).sort(),["ADD","ADD_LATER","ALTERNATIVE","DEFER","EXCLUDE","RETAIN"]);
