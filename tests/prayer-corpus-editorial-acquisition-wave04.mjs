assert.equal(decisions.records.length,97);
assert.equal(new Set(decisions.records.map(x=>x.id)).size,97);
assert.ok(decisions.records.every(x=>x.source_url?.startsWith("https://")));
assert.ok(decisions.records.every(x=>x.approved_by_user===false && x.text_imported===false));
