import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {PRAYER_ACQUISITION_WITNESSES_V1, prayerAcquisitionCandidates} from "../src/pray/prayer-acquisition-historical-witnesses.v1.js";
const decisions=JSON.parse(readFileSync(new URL("../data/pray/prayer-corpus-editorial-acquisition-master.v1.json",import.meta.url),"utf8"));
