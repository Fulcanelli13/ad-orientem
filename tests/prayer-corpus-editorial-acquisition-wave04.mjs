import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {PRAYER_ACQUISITION_WITNESSES_V1, prayerAcquisitionCandidates} from "../src/pray/prayer-acquisition-historical-witnesses.v1.js";
const decisions=JSON.parse(readFileSync(new URL("../data/pray/prayer-corpus-editorial-acquisition-master.v1.json",import.meta.url),"utf8"));
assert.equal(decisions.schema,"ao.prayer.corpus-editorial-acquisition.v1");
assert.equal(decisions.records.length,97);
assert.equal(new Set(decisions.records.map(x=>x.id)).size,97);
assert.ok(decisions.records.every(x=>x.source_url?.startsWith("https://")));
assert.ok(decisions.records.every(x=>x.approved_by_user===false && x.text_imported===false));
assert.equal(decisions.policy.no_fixed_ten_prayer_cap,true);
assert.equal(decisions.policy.zero_new_top_level_modules,true);
assert.deepEqual(Object.keys(decisions.summary.by_decision).sort(),["ADD","ADD_LATER","ALTERNATIVE","DEFER","EXCLUDE","RETAIN"]);
assert.equal(decisions.records.filter(x=>x.decision==="ADD").length,7);
assert.equal(decisions.records.filter(x=>x.decision==="DEFER").length,29);
const heroic=decisions.records.find(x=>x.title.includes("Heroic Act of Charity"));
assert.equal(heroic.decision,"DEFER");
assert.equal(PRAYER_ACQUISITION_WITNESSES_V1.length,6);
assert.equal(new Set(PRAYER_ACQUISITION_WITNESSES_V1.map(x=>x.id)).size,6);
assert.ok(PRAYER_ACQUISITION_WITNESSES_V1.every(x=>x.source?.url==="https://en.wikisource.org/wiki/My_Prayer-Book/Prayers_During_the_Day"));
assert.deepEqual(PRAYER_ACQUISITION_WITNESSES_V1.map(x=>x.source.page),["225","226","227","228","227","228"]);
assert.deepEqual(PRAYER_ACQUISITION_WITNESSES_V1.map(x=>x.source.scanPageUrl.split("/").at(-1)),["240","241","242","243","242","243"]);
assert.ok(PRAYER_ACQUISITION_WITNESSES_V1.every(x=>["en","la"].includes(x.language)&&x.text?.length>50));
const published=PRAYER_ACQUISITION_WITNESSES_V1.filter(x=>x.release.status==="LIVE_CLEARED");
assert.deepEqual(published.map(x=>x.id),["ignatius_suscipe_lasance_1908_en","ignatius_suscipe_lasance_1908_la"]);
assert.ok(published.every(x=>x.release.allowed_in_prayer_hub&&x.release.exact_print_verified));
assert.ok(PRAYER_ACQUISITION_WITNESSES_V1.filter(x=>x.release.status!=="LIVE_CLEARED").every(x=>!x.release.allowed_in_prayer_hub));
assert.ok(PRAYER_ACQUISITION_WITNESSES_V1.every(x=>x.release.translation_status.fr==="NOT_AVAILABLE"));
assert.equal(prayerAcquisitionCandidates("prepare_spiritual_reading").length,0);
assert.equal(prayerAcquisitionCandidates("prepare_spiritual_reading",{research:true}).length,2);
assert.equal(prayerAcquisitionCandidates("prepare_spiritual_reading",{research:true,language:"fr"}).length,0);
assert.equal(prayerAcquisitionCandidates("conclude_spiritual_reading").length,0);
assert.equal(prayerAcquisitionCandidates("conclude_spiritual_reading",{research:true}).length,1);
assert.equal(prayerAcquisitionCandidates("self_offering").length,1);
assert.equal(prayerAcquisitionCandidates("self_offering",{language:"la"}).length,1);
assert.equal(prayerAcquisitionCandidates("self_offering",{language:"fr"}).length,0);
assert.equal(prayerAcquisitionCandidates("self_offering",{research:true}).length,1);
assert.equal(prayerAcquisitionCandidates("unsupported-purpose").length,0);
