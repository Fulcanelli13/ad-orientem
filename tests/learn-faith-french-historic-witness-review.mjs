const corrections=new Map();
let claimCount=0;
for(const overlay of [a,b])for(const l of overlay.lessons)for(const [i,claim] of l.claims.entries()){
 claimCount++;
 const ed=claim.frenchEditorialDesk20261009;
 if(!ed)continue;
 assert.equal(ed.status,"EDITORIAL_CANDIDATE_REVISED_NOT_NATIVE_FRENCH_APPROVED");
 assert.equal(ed.independentFrenchApproval,false);
 assert.equal(ed.independentTheologyApproval,false);
 assert.ok(claim.en.length>35&&claim.fr.length>35);
 const refs=new Set(claim.sources.filter(s=>s.source==="PIUS_X_1912").flatMap(s=>s.refs.map(q=>Number(q.slice(-3)))));
 for(const n of ed.piusXQuestionNumbers)assert.ok(refs.has(n),l.id+" misattributed Q"+n);
 corrections.set(l.id+":"+(i+1),claim);
}
assert.equal(claimCount,178);
assert.equal(corrections.size,10);
assert.equal(a.batchFindings.frenchReadabilityCorrections20261009.count,1);
assert.equal(b.batchFindings.frenchReadabilityCorrections20261009.count,9);
assert.equal(c.metrics.frenchBilingualCandidateReadabilityCorrections20261009,10);
const marriage=corrections.get("LTF-031:1");
assert.ok(marriage.fr.includes("d’élever chrétiennement leurs enfants"));
assert.ok(!marriage.fr.includes("parentalité chrétienne"));
assert.ok(corrections.get("LTF-049:2").fr.includes("mérites de Jésus-Christ"));
assert.ok(corrections.get("LTF-024:2").fr.includes("faire ce que fait l’Église"));
