for(const field of ["fullOriginalPassageHumanVerification","editorialApproval","canonicalReview","frenchOriginalCollation","nativeFrenchEdit","publicRouteAdded"])assert.equal(c.publicationGate[field],false);
const preview=buildCatechismGuidedStudy(c,a,b,en,{preview:true});
assert.equal(preview.lessons.length,55);
assert.equal(preview.lessons.reduce((n,l)=>n+l.claims.length,0),181);
assert.equal(Object.keys(preview.questionToLesson).length,433);
assert.equal(buildCatechismGuidedStudy(c,a,b,en).available,false);
console.log(JSON.stringify({status:"PASS",historicEdition:1913,modernFrenchTextDamages:3,bilingualCopyFixes:corrections.size,publicLessons:0,guideClaims:181}));
