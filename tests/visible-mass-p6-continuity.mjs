import assert from "node:assert/strict";
import {PHOTO_VIEWPOINTS,visibleMassTransition,visibleMassPose,restoreVisibleMassPose} from "../previews/visible-mass-3d/photographic-p6-continuity.mjs";
assert.equal(PHOTO_VIEWPOINTS.length,9);
assert.equal(new Set(PHOTO_VIEWPOINTS.map(s=>s.id)).size,9);
const source=id=>({sceneId:id,sourceUrl:"https://commons.wikimedia.org/wiki/File:example.jpg",creator:"Photographer",licence:"CC BY-SA 4.0"});
const close=visibleMassTransition("BROMPTON_PANO","BROMPTON_ALTAR_2019_B",source("BROMPTON_ALTAR_2019_B"));
assert.equal(close.kind,"SEPARATE_VIEW_SAME_VENUE");
assert.equal(close.simulatedWalking,false);
assert.equal(close.proves1962RitualAction,false);
assert.equal(close.transferredObjectCoordinates,false);
assert.equal(visibleMassTransition("BROMPTON_PANO","NEWMAN_360",source("NEWMAN_360")).kind,"SEPARATE_VENUE");
assert.throws(()=>visibleMassTransition("BROMPTON_PANO","NEWMAN_360",source("BROMPTON_PANO")),/exact photo ID/);
assert.throws(()=>visibleMassTransition("BROMPTON_PANO","NEWMAN_360",{...source("NEWMAN_360"),licence:""}),/attribution/);
const pano=visibleMassPose("BROMPTON_PANO",{yaw:.55,pitch:.16,fov:51});
assert.deepEqual(restoreVisibleMassPose("BROMPTON_PANO",pano),pano);
assert.equal(restoreVisibleMassPose("NEWMAN_360",pano),null);
const still=visibleMassPose("BROMPTON_ALTAR_2019_B",{zoom:1.3,offsetX:16,offsetY:12});
assert.deepEqual(restoreVisibleMassPose("BROMPTON_ALTAR_2019_B",still),still);
assert.equal(restoreVisibleMassPose("BROMPTON_ALTAR_2019_A",still),null);
assert.throws(()=>visibleMassPose("BROMPTON_PANO",{yaw:NaN,pitch:0,fov:60}),/Invalid panorama/);
console.log("PASS Visible Mass P6: nine genuine photographed viewpoints; independent camera memory and image provenance; no virtual walking or ceremonial inference.");
