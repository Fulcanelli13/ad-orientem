assert.equal(m.new_physical_locations,4);
assert.equal(m.new_mapping_rows_resolved,0);
assert.equal(m.new_global_candidate_ids_resolved,4);
assert.equal(m.photo_assets_approved,0);
assert.equal(m.tlm_schedule_links_added,0);
assert.equal(p43.counts.global_canonical_links_if_P43_merged,123);
assert.equal(p43.counts.global_unresolved_if_P43_merged,377);
