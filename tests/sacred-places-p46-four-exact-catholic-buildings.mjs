assert.equal(p44.global_unresolved_after_release,376);
const newCandidateIds=new Set(m.published_new.map(x=>x.candidate_id));
assert.deepEqual([...newCandidateIds].sort(),["SG-INV-0215","SG-INV-0225","SG-INV-0272","SG-INV-0313"]);
assert.equal(m.global_canonical_links_after_release,p44.global_canonical_links_after_release+newCandidateIds.size);
assert.equal(m.global_unresolved_after_release,p44.global_unresolved_after_release-newCandidateIds.size);
