import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE,RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {auditShrineSource,assertShrinesPilgrimagesRegistry} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const m=load("data/geography/research/sacred-places-p35-world-13-consolidated.v1.json");
const geo=load("data/geography/seed-registry.v1.json");
const sources=load("data/shrines/source-registry.v1.json");
const heritage=load("data/explore/heritage-place-reconciliation.review.v1.json");
const shrines=load("data/shrines/shrines-pilgrimages-seed.v1.json");
const p16=load("data/geography/research/sacred-places-p16-three-qualified-site-release.v1.json");
const p34=load("data/geography/research/sacred-places-p34-thirteen-audited-churches.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P35_WORLD_13_CONSOLIDATED_V1");
assert.deepEqual(Object.values(m.baseline),[427,725,427,168,141,9],"P34 is frozen P35 predecessor");
assert.deepEqual(Object.values(m.proposed),[440,738,440,181,145,9]);
assert.ok(RELEASES.some(r=>r.id==="P35"),"P35 must be in the immutable ledger");
assert.deepEqual([geo.places.length,sources.sources.length,heritage.place_crosswalk.length,heritage.exception_queues.places_without_direct_claim.length,geo.geoAreas.length,geo.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked,LIVE.areas,LIVE.links]);
assert.equal(heritage.counts.places,LIVE.places);
assert.equal(heritage.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(m.published_new.length,13);
assert.equal(new Set(m.published_new.map(x=>x.candidate_id)).size,13);
assert.equal(new Set(m.published_new.map(x=>x.place_id)).size,13);
assert.equal(new Set(m.published_new.map(x=>x.geo_source_ref)).size,13);
assert.deepEqual(m.old_branch_overlaps.map(x=>x.id),["SG-INV-0468","SG-INV-0602"],"Santo Cerro and Matara each count once");
assert.equal(p16.held_exceptions.length,16);
assert.equal(m.p16_protected_historical_exceptions,16);
assert.equal(m.photo_assets_approved,0);
assert.equal(m.tlm_schedule_links_added,0);
assert.equal(m.new_country_area_count,4);
const places=new Map(geo.places.map(x=>[x.place_id,x]));
const src=new Map(sources.sources.map(x=>[x.id,x]));
assert.equal(places.size,geo.places.length);
assert.equal(src.size,sources.sources.length);
const p35Ids=new Set(m.published_new.map(x=>x.place_id));
const p35Index=RELEASES.findIndex(x=>x.id==="P35");
const futureIds=new Set(RELEASES.slice(p35Index+1).flatMap(r=>(r.data.published_new||[]).map(x=>x.place_id)));
const previous=geo.places.filter(x=>!p35Ids.has(x.place_id)&&!futureIds.has(x.place_id));
assert.equal(previous.length,m.baseline.places);
const oldRefs=new Set(previous.map(x=>x.geo?.source_ref).filter(Boolean));
const p34Ids=new Set(p34.published_new.map(x=>x.place_id));
assert.equal(p34Ids.size,13);
assert.ok(p34.published_new.every(x=>places.has(x.place_id)));
for(const country of ["RO","PA","TW","UA"]){
 const area=geo.geoAreas.find(x=>x.geo_area_id==="geo:country:"+country);
 assert.ok(area,"missing country area "+country);
 assert.equal(area.codes.iso_alpha2,country);
 assert.equal(area.area_type,"country");
}
for(const row of m.published_new){
 assert.match(row.geo_source_ref,/^osm:way:\d+$/);
 assert.equal(row.geo_source_url,"https://www.openstreetmap.org/way/"+row.geo_source_ref.split(":")[2]);
 assert.ok(!oldRefs.has(row.geo_source_ref),"duplicate physical feature "+row.geo_source_ref);
 const p=places.get(row.place_id);
 assert.ok(p,"missing canonical place "+row.place_id);
 assert.equal(p.name.official,row.name);
 assert.equal(p.place_type,row.place_type);
 assert.equal(p.address.country_code,row.country);
 assert.deepEqual(p.geo_area_ids,["geo:country:"+row.country]);
 assert.deepEqual([p.geo.lat,p.geo.lng],[row.lat,row.lng]);
 assert.equal(p.geo.source_ref,row.geo_source_ref);
 assert.equal(p.geo.source_url,row.geo_source_url);
 assert.equal(p.geo.geocoding_source,"OSM");
 assert.equal(p.geo.precision,"site");
 assert.equal(p.geo.matched_country_code,row.country);
 assert.ok(isMapPublishablePlaceGeo(p.geo,row.country));
 assert.deepEqual(p.source_ids,row.source_ids);
 assert.equal(p.source_ids.length,1);
 const s=src.get(p.source_ids[0]);
 assert.ok(s);
 assert.deepEqual(auditShrineSource(s),[]);
 assert.equal(s.url,row.identity_source_url);
 const x=heritage.place_crosswalk.filter(x=>x.place_id===row.place_id);
 assert.equal(x.length,1);
 assert.deepEqual(x[0].record_ids,{});
 assert.ok(heritage.exception_queues.places_without_direct_claim.includes(row.place_id));
 assert.ok(!geo.directoryPlaceLinks.some(x=>x.place_id===row.place_id));
 assert.ok(!shrines.shrines.some(x=>x.place_id===row.place_id));
 for(const f of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])assert.equal(p[f],undefined);
}
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrines,sources:sources.sources,places:geo.places}).pass,true);
console.log("PASS P35: 13 nonduplicate Catholic locations, 4 new country areas, immutable P34/P31 history, 9 Directory links and 16 protected holds");
