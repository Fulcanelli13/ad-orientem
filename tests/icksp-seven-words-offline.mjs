import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {sevenWordsLocalWitnessText,SEVEN_WORDS_LOCAL_EN_1889_V1 as s} from "../src/pray/seven-words-offline-1889.v1.js";
import {parseSevenWordsHistoricalWitness} from "../src/pray/seven-words-witness.v1.js";
assert.equal(s.words.length,7);
assert.equal(s.words[0].title,"The First Word.");
assert.equal(s.words[6].title,"The Seventh Word.");
assert.equal(s.words[1].utterance,"This day Thou shalt be with Me in Paradise.");
assert.match(s.words[4].meditation,/burn with the desire/);
assert.match(s.editorialCorrection,/critical printed-image collation is still pending/);
const parsed=parseSevenWordsHistoricalWitness(sevenWordsLocalWitnessText());
assert.equal(parsed.sections.length,7);
assert.ok(parsed.sections.every((x,i)=>x.text.length>90&&x.title===s.words[i].title));
assert.match(parsed.sections[0].text,/bosom of Thine infinite mercy/);
assert.match(parsed.sections[6].text,/accomplishment of Thy blessed will/);
assert.doesNotMatch(parsed.sections[6].text,/A Prayer to our Blessed Lady of Sorrows/);
assert.match(parsed.appendix,/A Prayer to our Blessed Lady of Sorrows/);
assert.match(parsed.appendix,/Jesus, Mary, and Joseph/);
assert.doesNotMatch(parsed.appendix,/The Seventh Word/);
const reader=readFileSync(new URL("../src/pray/presentation-runtime.js",import.meta.url),"utf8");
assert.match(reader,/sevenWordsLocalWitnessText\(\)/);
assert.doesNotMatch(reader,/await guidedWsText\('A Manual of Prayers for the Use of the Catholic Laity/);
assert.match(reader,/SEVEN\.scriptureOnly/);
assert.match(reader,/Independent print-page collation remains pending/);
assert.match(reader,/Berthaumier/);
assert.match(reader,/\$\{appendix\}<\/main>/);
console.log("Seven Words local English meditations, seven Gospel anchors and separate optional conclusion: PASS");
