import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {LIVE, RELEASES} from "./helpers/sacred-places-live-baseline.mjs";
import {assertExploreGeographyRegistry,isMapPublishablePlaceGeo} from "../src/find/geography-contracts.js";
import {assertShrinesPilgrimagesRegistry,auditShrineSource} from "../src/find/shrines-contracts.js";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const manifest=load("data/geography/research/sacred-places-p24-world-16-map-first.v1.json");
const geo=load("data/geography/seed-registry.v1.json");
const sources=load("data/shrines/source-registry.v1.json");
const cross=load("data/explore/heritage-place-reconciliation.review.v1.json");
const shrine=load("data/shrines/shrines-pilgrimages-seed.v1.json");
const p21=load("data/geography/research/sacred-places-p21-first200-source-review.v1.json");
const p16=load("data/geography/research/sacred-places-p16-three-qualified-site-release.v1.json");
const p22=load("data/geography/research/sacred-places-p22-map-first-ten-sites.v1.json");
assert.equal(manifest.schema,"AO_SACRED_PLACES_P24_WORLD_16_MAP_FIRST_V1");
assert.deepEqual([manifest.baseline.places,manifest.baseline.sources,manifest.baseline.crosswalk,manifest.baseline.unlinked],[371,669,371,112]);
assert.deepEqual([manifest.proposed.places,manifest.proposed.sources,manifest.proposed.crosswalk,manifest.proposed.unlinked],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked]);
assert.deepEqual([geo.places.length,sources.sources.length,cross.place_crosswalk.length,geo.geoAreas.length,geo.directoryPlaceLinks.length],[LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.areas,LIVE.links]);
assert.equal(cross.counts.places,LIVE.places);
assert.equal(cross.counts.places_without_direct_claim,LIVE.unlinked);
assert.equal(cross.exception_queues.places_without_direct_claim.length,LIVE.unlinked);
assert.equal(p16.held_exceptions.length,16);
assert.equal(manifest.published_new.length,16);
assert.equal(manifest.researched_exact_physical_features,18);
assert.equal(manifest.reused_existing.length,2);
assert.ok(RELEASES.some(x=>x.id==="P24"));
assert.equal(new Set(manifest.published_new.map(x=>x.place_id)).size,16);
assert.equal(new Set(manifest.published_new.map(x=>x.geo_source_ref)).size,16);
assert.equal(new Set(manifest.published_new.map(x=>x.country)).size,14);
const byPlace=new Map(geo.places.map(x=>[x.place_id,x]));
const bySource=new Map(sources.sources.map(x=>[x.id,x]));
const byP21=new Map(p21.reviewed_200.map(x=>[x.candidate_id,x]));
assert.equal(byPlace.size,LIVE.places);
assert.equal(bySource.size,LIVE.sources);
for(const p of p22.published_new)assert.ok(byPlace.has(p.place_id),"P22 canonical ID dropped: "+p.place_id);
for(const item of manifest.reused_existing){
 const p=byPlace.get(item.place_id);
 assert.ok(p);
 assert.equal(p.geo.source_ref,item.ref);
 assert.equal(p.name.official,item.identity);
}
for(const item of manifest.published_new){
 const p=byPlace.get(item.place_id);
 assert.ok(p,"Missing P24 "+item.place_id);
 const prior=byP21.get(item.candidate_id);
 assert.equal(prior.source_status,"SOURCE_SNIPPET_REVIEWED_2026_10_24");
 assert.equal(p.name.official,item.name);
 assert.equal(p.place_type,item.place_type);
 assert.equal(p.address.country_code,item.country);
 assert.equal(p.geo.matched_country_code,item.country);
 assert.equal(p.geo_area_ids[0],"geo:country:"+item.country);
 assert.deepEqual([p.geo.lat,p.geo.lng],[item.lat,item.lng]);
 assert.equal(p.geo.source_ref,item.geo_source_ref);
 assert.equal(p.geo.source_url,item.geo_source_url);
 assert.equal(p.geo.precision,item.precision);
 assert.match(p.geo.attribution,/OpenStreetMap/);
 assert.ok(isMapPublishablePlaceGeo(p.geo,item.country));
 assert.equal(p.source_ids.length,1,"No duplicative required source records");
 assert.deepEqual(p.source_ids,item.source_ids);
 const s=bySource.get(p.source_ids[0]);
 assert.ok(s);
 assert.equal(auditShrineSource(s).length,0);
 assert.equal(s.url,item.identity_source_url);
 assert.ok(!geo.directoryPlaceLinks.some(l=>l.place_id===item.place_id),"No fabricated 1962 Mass link");
 assert.ok(!shrine.shrines.some(x=>x.place_id===item.place_id),"No unsupported shrine-domain editorial owner");
 assert.ok(cross.exception_queues.places_without_direct_claim.includes(item.place_id));
 assert.deepEqual(cross.place_crosswalk.find(x=>x.place_id===item.place_id).record_ids,{});
 for(const optional of ["opening_hours","hero_image","description_en","description_fr","mass_times","pilgrimage_schedule"])
  assert.equal(p[optional],undefined,"Optional enrichment is not a P24 publication gate");
}
assert.equal(byPlace.get("place:IT:santuario-francescano-la-verna").geo.precision,"complex_anchor");
assert.equal(byPlace.get("place:DE:benediktinerabtei-maria-laach").geo.precision,"complex_anchor");
assert.equal(byPlace.get("place:MU:marie-reine-de-la-paix-port-louis").place_type,"pilgrimage_destination");
assert.equal(byPlace.get("place:PS:basilica-agony-gethsemane").address.country_code,"PS");
assert.equal(manifest.original_p16_holds_preserved,16);
assert.equal(assertExploreGeographyRegistry(geo).pass,true);
assert.equal(assertShrinesPilgrimagesRegistry({...shrine,sources:sources.sources,places:geo.places}).pass,true);
console.log("PASS P24: 18 physical features, two canonical Covadonga reuses, 16 new map-first Places across 14 country codes, one typed identity source each, 16 historical holds retained");
