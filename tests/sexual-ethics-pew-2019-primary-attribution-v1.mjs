assert.equal(stage.summary.pew_false_23_percent_attribution_corrected,false);
const en=CSE_DEBATE_MAP.CSE035.opposition[0],fr=CSE_DEBATE_MAP.CSE035.opposition[1];
assert.match(en,/23%.*test their relationship/);
assert.match(en,/38%.*finances and 37% convenience/);
