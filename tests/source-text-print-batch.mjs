import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {validateHistoricalPrintBatch} from "../src/source-text/print-batch-review.js";
const load=name=>JSON.parse(readFileSync(new URL("../"+name,import.meta.url),"utf8"));
const plan=load("data/source-text/fortescue-1908-print-page-plan.v1.json");
const previousPageDraft=load("data/source-text/fortescue-1913-p257-provisional-transcription.v1.json");
const batch=load("data/source-text/fortescue-1913-print-batch-258-260.v1.json");
const result=validateHistoricalPrintBatch({plan,batch,previousPageDraft});
assert.equal(result.scannedPages,3);
assert.equal(result.approvedWholePages,0);
assert.equal(result.independentlyCertifiedParagraphs,0);
assert.equal(result.alreadyAllowedTestExcerptsUnchanged,4);
assert.equal(result.humanEditorialReviewRequired,true);
assert.equal(result.productionIngestAllowed,false);
assert.deepEqual(result.imagePages.map(p=>p.printedPage),[258,259,260]);
assert.deepEqual(result.imagePages.map(p=>p.scanPage),[306,307,308]);
assert.equal(batch.pages[0].beginsMidParagraphFromPrintedPage,257);
assert.equal(batch.pages[1].beginsMidParagraphFromPrintedPage,258);
assert.equal(batch.pages[2].beginsMidParagraphFromPrintedPage,259);
assert.equal(batch.transcribedContinuation.approvedForAutoJoin,false);
assert.equal(batch.transcribedContinuation.contentIsReusedNotDuplicated,true);
assert.ok(previousPageDraft.pageJoinCandidate.continuedTextDraft.startsWith(batch.pages[0].beginsWith));
assert.equal(batch.pages[1].importantOriginalTextWitness.quotationOpening,"Fac nobis hanc oblationem");
assert.equal(batch.pages[1].importantOriginalTextWitness.relatedPage257Quotation,"Fac nos hanc oblationem");
assert.equal(batch.pages[1].importantOriginalTextWitness.textVariantsMustRemainDistinct,true);
assert.equal(batch.pages[2].newSectionOnPage.heading,"From the time of St. Gregory I (590–604)");
assert.equal(batch.pages[2].newSectionOnPage.semanticType,"PRINTED_SUBSECTION_HEADING_NOT_COMPLETE_ARTICLE_BOUNDARY");
assert.ok(!JSON.stringify(result).includes("Drews"));
assert.ok(!JSON.stringify(result).includes(previousPageDraft.pageJoinCandidate.continuedTextDraft.slice(0,35)));
const altered=fn=>{const x=structuredClone(batch);fn(x);return x;};
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.productionIngestAllowed=true),previousPageDraft}),/NOT_REVIEW_ONLY/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.witnessId="WRONG"),previousPageDraft}),/NOT_REVIEW_ONLY/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.pages[1].sourceImage="https://fake.invalid/307"),previousPageDraft}),/PAGE_EVIDENCE_INVALID/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.pages[1].printedPage=260),previousPageDraft}),/PAGE_EVIDENCE_INVALID|PAGE_ORDER_INVALID/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.pages[1].importantOriginalTextWitness.textVariantsMustRemainDistinct=false),previousPageDraft}),/TEXT_WITNESSES_CONFLATED/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.pages[2].newSectionOnPage.semanticType="ARTICLE_BEGINS"),previousPageDraft}),/SUBSECTION_INVALID/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.transcribedContinuation.approvedForAutoJoin=true),previousPageDraft}),/PAGE_HANDOFF_UNSAFE/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.pageBoundaryChain[1].toPrintedPage=260),previousPageDraft}),/CONTINUATION_UNVERIFIED/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.reviewMetrics.pagesWithFullyProofreadEntireText=1),previousPageDraft}),/CLEARANCE_CONTRADICTION/);
assert.throws(()=>validateHistoricalPrintBatch({plan,batch:altered(x=>x.crossModuleRestrictions.mustNotImply1962RubricAuthority=false),previousPageDraft}),/CLEARANCE_CONTRADICTION/);
