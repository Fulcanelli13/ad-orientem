import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {execFileSync} from "node:child_process";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const a=read("data/explore/worldwide-relic-subject-census.research.v1.json");
const w=read("data/explore/worldwide-relic-subject-census.wave5.research.v1.json");
const live=read("data/explore/sacred-phenomena-seed.v1.json");
const stats=JSON.parse(execFileSync(process.execPath,["tools/atlas/report-world-relic-census.mjs"],{encoding:"utf8"}));
assert.equal(w.schema,"SACRED_ATLAS_WORLD_RELIC_CENSUS_WAVE5_V1");
assert.equal(w.status,"RESEARCH_ONLY_NOT_ALL_RELICS_WORLDWIDE");
assert.equal(w.new_cases.length,25);
assert.equal(w.reviewed_subject_ids.length,22);
assert.equal(w.pending_subject_ids_before.length,45);
assert.equal(w.pending_subject_ids_after.length,23);
assert.equal(new Set(w.reviewed_subject_ids).size,22);
assert.equal(new Set(w.pending_subject_ids_after).size,23);
assert.deepEqual(new Set([...w.reviewed_subject_ids,...w.pending_subject_ids_after]),new Set(w.pending_subject_ids_before));
assert.ok(w.reviewed_subject_ids.every(x=>!w.pending_subject_ids_after.includes(x)));
const subjects=new Set(a.subjects.map(x=>x.subject_id)),ids=new Set(),sources=new Set();
for(const c of w.new_cases){
 assert.ok(subjects.has(c.subject_id),"Unknown subject "+c.subject_id);
 assert.ok(!ids.has(c.case_id),"duplicate case "+c.case_id);ids.add(c.case_id);
 assert.match(c.source_url,/^https:\/\//,"Missing source "+c.case_id);
 assert.ok(c.source_role&&c.material_kind&&c.custody_status&&c.source_interpretation);
 assert.equal(c.ecclesiastical_authentication,"NOT_ASSIGNED");
 assert.equal(c.new_map_pin,false);
 assert.equal(c.publishable_as_authenticated_relic,false);
 assert.ok(c.source_review_scope.startsWith("CUSTODIAN_OR_HISTORICAL_DESCRIPTION"));
 assert.ok(!c.relic_class.startsWith("CERTIFIED_"));
 if(/MARTYRDOM_PLACE|MARTYRDOM_ONLY|DEVOTIONAL_MEMORIAL|HISTORIC_TOMB_SITE/.test(c.material_kind))assert.ok(!c.relic_class.startsWith("FIRST_CLASS"),c.case_id);
 sources.add(c.source_url);
}
assert.ok(sources.size>=17,"Expected independent primary/heritage source base");
const more=w.new_cases.filter(x=>x.subject_id==="subject:saint-brigid-of-kildare");
assert.equal(more.length,2);
assert.notEqual(more[0].claimed_custodian,more[1].claimed_custodian);
const rome=w.new_cases.filter(x=>["subject:saint-adalbert-of-prague","subject:saint-bartholomew-the-apostle"].includes(x.subject_id));
assert.ok(rome.some(x=>x.claimed_custodian.includes("San Bartolomeo")));
assert.ok(w.new_cases.some(x=>x.subject_id==="subject:saint-bernard-of-clairvaux"&&x.custody_status.includes("DESTROYED")));
assert.ok(w.new_cases.some(x=>x.subject_id==="subject:saint-hedwig-of-silesia"&&x.custody_status.includes("DISPUTED")));
assert.ok(w.new_cases.some(x=>x.subject_id==="subject:saint-maurice-of-agaunum"&&x.country_code==="CH"));
assert.equal(live.relics.length,a.legacy_object_crosswalk.length,"Published relics changed during research-only work");
assert.equal(stats.fifth_wave_cases,25);
assert.equal(stats.first_wave_claims+stats.second_wave_claims+stats.third_wave_claims+stats.fourth_wave_fresh_institutional_cases+stats.fifth_wave_cases,110);
assert.equal(stats.backlog_total,133);
assert.equal(stats.backlog_addressed_after_wave5,110);
assert.equal(stats.backlog_pending_after_wave5,23);
assert.equal(stats.published_place_impact,0);
console.log("PASS fifth global relic census: 25 independently tagged cases, 22 new priority subjects addressed, 23 remaining; 110 total source-screened or historical cases but no new published map records");
