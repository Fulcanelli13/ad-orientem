import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { saintRecognitionAt, supplementarySaintsForDate } from "../src/calendar/living-sanctoral.js";

const registry = JSON.parse(readFileSync(new URL("../data/calendar/living-sanctoral-pilot.v1.json", import.meta.url), "utf8"));
const byId = new Map(registry.persons.map(person => [person.id, person]));
const newman = byId.get("saint.john-henry-newman");
const pio = byId.get("saint.pio-pietrelcina");
const therese = byId.get("saint.therese-lisieux");
const carlo = byId.get("saint.carlo-acutis");
const people = registry.persons;

assert.equal(saintRecognitionAt(newman, "2018-10-09").recognizedAsSaint, false);
assert.equal(saintRecognitionAt(newman, "2024-10-09").recognizedAsSaint, true);
assert.equal(saintRecognitionAt(newman, "2024-10-09").doctorOfChurch, false);
assert.equal(saintRecognitionAt(newman, "2026-10-09").doctorOfChurch, true);
assert.equal(saintRecognitionAt(therese, "1990-10-03").doctorOfChurch, false);
assert.equal(saintRecognitionAt(therese, "2000-10-03").doctorOfChurch, true);
assert.equal(saintRecognitionAt(carlo, "2024-10-12").recognizedAsSaint, false);
assert.equal(saintRecognitionAt(carlo, "2026-10-12").recognizedAsSaint, true);
assert.equal(saintRecognitionAt(pio, "1999-09-23").recognizedAsSaint, false);

const oct2026 = supplementarySaintsForDate("2026-10-09", people, {language:"fr", observedPrincipalId:"sancti:10-09"});
assert.deepEqual(oct2026.map(x => x.personId), ["saint.john-henry-newman"]);
assert.equal(oct2026[0].title, "Saint John Henry Newman");
assert.equal(oct2026[0].doctorOfChurch, true);
assert.equal(oct2026[0].optional1962MassStatus, "NOT_EVALUATED");
assert.equal(oct2026[0].changesPrincipalDay, false);
assert.equal(supplementarySaintsForDate("2025-10-09", people).length, 0, "2026 calendar inscription not retrojected");
const sep2026 = supplementarySaintsForDate("2026-09-23", people);
assert.deepEqual(sep2026.map(x => x.personId), ["saint.pio-pietrelcina"]);
assert.equal(sep2026[0].status, "CONTEXTUAL_SAINT_NOT_MASS_SELECTION");
assert.equal(supplementarySaintsForDate("2026-10-12", people).length, 0, "Carlo lacks a verified universal Roman date");
assert.equal(supplementarySaintsForDate("2026-10-03", people, {observedPrincipalId:"sancti:10-03:3:w", includeOlderCalendarAssociations:true}).length, 0, "do not duplicate principal saint");
const thereseSecondary = supplementarySaintsForDate("2026-10-03", people, {includeOlderCalendarAssociations:true});
assert.deepEqual(thereseSecondary.map(x => x.personId), ["saint.therese-lisieux"]);
assert.equal(supplementarySaintsForDate("2026-10-15", people, {observedPrincipalId:"sancti:10-15:3:w", includeOlderCalendarAssociations:true}).length, 0);
assert.equal(supplementarySaintsForDate("2026-10-03", people).length, 0, "1962 entries are not supplementary by default");
assert.throws(() => saintRecognitionAt(newman,"invalid"), TypeError);
assert.throws(() => supplementarySaintsForDate("not-a-date",people), TypeError);
assert.equal("selectedFormularyId" in oct2026[0], false);
assert.equal("proper" in oct2026[0], false);
assert.equal("colour" in oct2026[0], false);
assert.equal(Object.isFrozen(oct2026), true);
console.log("Living-sanctoral supplemental projection: PASS (historical recognition, modern dates, no Mass changes)");
