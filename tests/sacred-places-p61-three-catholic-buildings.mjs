import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { LIVE, RELEASES } from "./helpers/sacred-places-live-baseline.mjs";
import { isMapPublishablePlaceGeo, assertExploreGeographyRegistry } from "../src/find/geography-contracts.js";
const read = p => JSON.parse(readFileSync(new URL("../"+p,import.meta.url), "utf8"));
const m=read("data/geography/research/sacred-places-p61-three-catholic-buildings.v1.json");
const g=read("data/geography/seed-registry.v1.json");
const s=read("data/shrines/source-registry.v1.json");
const h=read("data/explore/heritage-place-reconciliation.review.v1.json");
assert.equal(m.schema,"AO_SACRED_PLACES_P61_THREE_CATHOLIC_CHURCH_BUILDINGS_V1");
assert.deepEqual(m.baseline,{places:512,sources:810,crosswalk:512,unlinked:253,geo_areas:146,directory_links:9});
assert.deepEqual(m.proposed,{places:515,sources:816,crosswalk:515,unlinked:256,geo_areas:146,directory_links:9});
assert.ok(RELEASES.some(r=>r.id==="P61"));
assert.deepEqual([LIVE.places,LIVE.sources,LIVE.heritage_crosswalk,LIVE.unlinked],[515,816,515,256]);
assert.deepEqual([g.places.length,s.sources.length,h.place_crosswalk.length,h.exception_queues.places_without_direct_claim.length],[515,816,515,256]);
assert.equal(assertExploreGeographyRegistry(g).pass,true);
const pbyid=new Map(g.places.map(p=>[p.place_id,p]));
const sid=new Map(s.sources.map(x=>[x.id,x]));
const osm=new Set(),cand=new Set();
for(const r of m.published_new){
 assert.ok(!cand.has(r.candidate_id));cand.add(r.candidate_id);
 assert.ok(!osm.has(r.geo_source_ref));osm.add(r.geo_source_ref);
 assert.match(r.geo_source_ref,/^osm:way:\d+$/);
 const p=pbyid.get(r.place_id);assert.ok(p,"New canonical Place missing: "+r.place_id);
 assert.equal(p.name.official,r.name);
 assert.equal(p.place_type,r.place_type);
 assert.equal(p.geo.lat,r.lat);assert.equal(p.geo.lng,r.lng);
 assert.equal(p.geo.precision,"site");
 assert.equal(p.geo.source_ref,r.geo_source_ref);
 assert.equal(p.geo.source_url,r.geo_source_url);
 assert.equal(p.geo.geocoding_source,"OSM");
 assert.equal(p.geo.matched_country_code,r.country);
 assert.ok(isMapPublishablePlaceGeo(p.geo,r.country));
 assert.equal(p.address.country_code,r.country);
 assert.deepEqual(p.source_ids,r.source_ids);
 assert.ok(p.source_ids.every(id=>sid.has(id)));
 assert.equal(sid.get(r.source_ids[0]).url,r.identity_source_url);
 assert.equal(sid.get(r.source_ids[0]).directness,"OFFICIAL_CHURCH");
 assert.equal(sid.get(r.source_ids[1]).url,r.geo_source_url);
 assert.equal(sid.get(r.source_ids[1]).directness,"SECONDARY");
 assert.ok(h.exception_queues.places_without_direct_claim.includes(r.place_id));
 assert.deepEqual(h.place_crosswalk.find(x=>x.place_id===r.place_id)?.record_ids,{});
 assert.ok(!g.directoryPlaceLinks.some(x=>x.place_id===r.place_id));
 assert.equal(p.hero_image,undefined);
 assert.equal(p.mass_times,undefined);
 assert.equal(p.opening_hours,undefined);
}
assert.equal(m.published_new.length,3);
assert.equal(m.photo_assets_approved,0);
assert.equal(m.tlm_schedule_links_added,0);
assert.ok(m.held.some(x=>x.candidate_id==="SG-INV-0512"));
assert.ok(m.held.some(x=>x.candidate_id==="SG-INV-0650"));
assert.ok(m.held.some(x=>x.candidate_id==="SG-INV-0049"));
console.log("PASS P61: three unique Catholic churches, source and geometry checks, 512→515 Places; no TLM/photo claims");
