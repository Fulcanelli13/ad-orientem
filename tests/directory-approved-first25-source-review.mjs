import fs from "node:fs";
import assert from "node:assert/strict";
const j=JSON.parse(fs.readFileSync("data/directory/research/approved-mass-original-source-first25-review-20261009.v1.json","utf8"));
const q=JSON.parse(fs.readFileSync("data/directory/research/approved-mass-worldwide-candidates-20261009.v1.json","utf8"));
const sourceIds=new Set(q.records.filter(x=>typeof x.has_mass_evidence==="boolean").map(x=>x.source_id));
assert.equal(j.schema,"AO_APPROVED_FIRST25_SOURCE_REVIEW_V1");
assert.equal(j.records.length,25);
assert.equal(new Set(j.records.map(x=>x.source_id)).size,25);
assert.ok(j.records.every(r=>sourceIds.has(r.source_id)));
assert.equal(j.summary.PUBLISHED_DIOCESAN_OFFICIAL,5);
assert.equal(j.summary.ALREADY_IN_CANONICAL_DIOCESAN,3);
assert.equal(j.summary.VERIFIED_MONASTIC_MASS_OWNERSHIP_REVIEW,2);
assert.equal(j.summary.NO_ORIGINAL_SOURCE_LINK_HOLD,2);
assert.equal(j.records.filter(r=>r.release==="CANONICAL_V19").length,5);
const poor=j.records.find(x=>x.name.includes("Poor Clare"));
assert.ok(poor&&poor.discrepancy.includes("SUN 07:00"));
const carmel=j.records.find(x=>x.name.includes("Infant of Prague Michigan"));
assert.ok(carmel&&carmel.edition==="1962"&&carmel.public_mass===true);
assert.ok(j.records.every(r=>r.decision==="PUBLISHED_DIOCESAN_OFFICIAL"||r.release==="HELD_OR_EXISTING"));
console.log("First 25 primary-source reviews: PASS — 5 published diocesan; 3 existing; 2 monastic holds; 15 further review/source holds");
