import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const j=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const base='data/prayer/artwork-editorial-20261030/';
const current='data/prayer/artwork-editorial-20261031/';
const original=j('data/calendar/prayer-art-reviewed117-user-decisions-20261028.v1.json');
const catalog=j('data/calendar/prayer-module-original-31-review-catalog-20261028.v1.json');
const first=j(base+'decision-ledger-b01-b05.v1.json');
const second=j(base+'approved-unified-b06-b11-from-user-message.v1.json');
const prior=j(base+'prior-explicit-keeps-cross-module-20261031.v1.json');
const assignments=j(current+'provisional-one-choice-per-267-art-position.v1.json');
const authority=j(current+'historical-prayer-artwork-editorial-authority-20261031.v1.json');
const master=j(current+'all-267-source-linked-artwork-candidate-collection.v1.json');
test('full original October 28 user decisions and comments are present, read-only, and counted correctly',()=>{
 assert.equal(original.decisions.length,117);
 assert.equal(catalog.pools.length,31);
 const counts=Object.fromEntries(['keep','reject','elsewhere','better-photo'].map(k=>[k,original.decisions.filter(x=>x.action===k).length]));
 assert.deepEqual(counts,{keep:47,reject:51,elsewhere:6,'better-photo':13});
 assert.equal(original.decisions.filter(x=>x.note||x.destination).length,15);
 const a=original.decisions.find(x=>x.placement_key==='adoration::adoration--primary');
 assert.equal(a.action,'keep');assert.match(a.note,/remove the frame/);
 const b=original.decisions.find(x=>x.placement_key==='benediction::adoration--primary');
 assert.equal(b.action,'keep');assert.match(b.note,/remove the frame/);
 const c=original.decisions.find(x=>x.placement_key==='evening::morning--millet-angelus');
 assert.equal(c.action,'keep');assert.match(c.note,/evening angelus/);
});
test('October 30 exact written instructions and not-presented statuses remain distinct',()=>{
 assert.equal(first.records.length,250);
 assert.equal(first.records.filter(x=>x.verbatim_user_instruction).length,28);
 assert.equal(first.records.filter(x=>x.prayer_editorial_status==='ACCEPTED_FOR_PRAYER_REVIEW').length,114);
 assert.equal(second.decisions.length,107);
 assert.equal(second.nonDisplayedIds.length,191);
 const rubens=first.records.find(x=>x.artwork_id==='CANONICAL::ART-eter-aul-ubens-esurrection-of-hrist');
 assert.match(rubens.verbatim_user_instruction,/regina caoeli only/);
 const mercy=first.records.find(x=>x.artwork_id==='PRAYER::w1-kazimirowski');
 assert.match(mercy.verbatim_user_instruction,/only in divine mercy chapelet/);
 assert.equal(prior.placements.length,7);
});
test('artwork research overlay remains unchanged, no rotation permission and no new approval',()=>{
 assert.equal(assignments.placements.length,267);
 assert.equal(assignments.stats.existingApprovedLinked,244);
 assert.equal(assignments.stats.provisionalOnly,23);
 assert.equal(assignments.publicationEnabled,false);
 assert.equal(authority.safety.releaseEnabled,false);
 assert.equal(authority.safety.noEditorialChanges,true);
 assert.equal(authority.safety.originalVerbatimUserNotesPreserved,true);
 assert.equal(authority.rotationPolicy.categoryDoorRotationEnabled,false);
 assert.equal(authority.rotationPolicy.seasonalHomepage,'ROTATE_ONLY_AMONG_MULTIPLE_USER_APPROVED_WORKS_FOR_SAME_LITURGICAL_OCCASION');
 assert.equal(master.qaState.userSourceDecisionLedgersNowImportedVerbatim,true);
 assert.equal(master.qaState.provisionalAssignmentsAreApprovals,false);
 const therese=assignments.placements.find(x=>x.slot==='COV-novena.st_therese');
 assert.equal(therese.assignment.painting.sourcePage,'https://commons.wikimedia.org/wiki/File:Therese_lisieux_portrait.jpg');
 assert.equal(therese.assignment.productionEnabled,false);
});
