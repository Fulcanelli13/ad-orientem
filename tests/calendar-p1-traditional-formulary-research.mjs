import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const root="data/calendar/";
const law=load(root+"p1-rubrical-permission-matrix.v1.json");
const forms=load(root+"p1-1962-formulary-master.v1.json");
const comm=load(root+"p1-three-oration-commemoration-matrix.v1.json");
const saint=load(root+"p1-saint-formulary-crosswalk.v1.json");
const cases=load(root+"p1-reference-cases.v1.json");
const holds=load(root+"p1-exception-backlog.v1.json");
const old=load(root+"traditional-1962-common-formularies.review.v1.json");
const census=load(root+"post1960-canonizations.official-batch1.v1.json");
const doctors=load(root+"doctors-of-church-roster.review.v1.json");
assert.equal(law.rules.length,35);
assert.equal(new Set(law.rules.map(r=>r.id)).size,35);
assert.ok(law.rules.every(r=>r.sourceCitation&&r.autoMassChange===false));
assert.equal(law.runtimeAutomaticAuthorization,false);
for(const name of ["R07_CLASS_II_EMBER","R12_SUNG_NONCONVENTUAL","R25_OMITTED_FEAST","R26_FORMULARY_ORDER","R27_AD_LIB_COMM","R28_RELIGIOUS_HOUSES","R29_PROTECTED_70","R34_HIGH_MASS_TENSION"])assert.ok(law.rules.find(r=>r.id===name),name);
assert.equal(law.rules.find(r=>r.id==="R34_HIGH_MASS_TENSION").certification,"LEGAL_INTERPRETATION_UNRESOLVED");
assert.deepEqual(law.commemorationCaps.map(c=>c.max),[1,1,1,1,2]);
assert.equal(forms.forms.length,38);
assert.equal(new Set(forms.forms.map(f=>f.id)).size,38);
assert.ok(forms.forms.every(f=>f.primaryEditionCollated===false&&f.approvedForRuntime===false&&f.selected1962FormularyId==null));
const required=["introit","collect","epistle","gradual","alleluia","tract","gospel","offertory","secret","communion","postcommunion"];
assert.deepEqual(forms.components,required);
for(const form of forms.forms){assert.deepEqual(Object.keys(form.sourceComponents),required);for(const c of required)assert.equal(form.sourceComponents[c].latinText,null);}
for(const x of old.candidates){assert.ok(forms.forms.some(f=>f.id===x.id),"Missing pre-existing common ID "+x.id);}
assert.equal(forms.forms.filter(f=>f.canonicalIdStatus==="REUSE_EXISTING_OWNER_ID").length,3);
assert.equal(forms.primaryPrintedEditionCollationCount,0);
assert.deepEqual(comm.orations,["collect","secret","postcommunion"]);
assert.equal(comm.trios.length,2);
for(const t of comm.trios){assert.deepEqual(t.order,comm.orations);assert.deepEqual(Object.keys(t.prayers),comm.orations);assert.ok(t.sourceUrl.startsWith("https://"));assert.ok(!t.entireTrioPrintCertified);for(const p of Object.values(t.prayers)){assert.equal(p.latinText,null);assert.equal(p.primaryPrintCollated,false);}}
assert.equal(comm.combinations.length,4);
assert.ok(comm.combinations.every(c=>c.status.includes("BLOCKED")||c.status.includes("PERMISSION")));
assert.equal(saint.canonizedIndividualCensusCount,census.persons.length);
assert.equal(saint.doctorCensusCount,doctors.doctors.length);
assert.equal(saint.collectiveGroupCount,census.groups.length);
assert.equal(saint.individualCount,saint.persons.length);
assert.equal(new Set(saint.persons.map(x=>x.saintId)).size,saint.persons.length);
assert.equal(new Set(saint.groups.map(x=>x.canonicalGroupId)).size,saint.groups.length);
for(const p of census.persons)assert.ok(saint.persons.some(x=>x.saintId===p.id));
for(const d of doctors.doctors)assert.ok(saint.persons.some(x=>x.saintId===d.canonicalPersonId));
assert.ok(saint.persons.every(x=>x.massAuthorization===false&&x.selected1962FormularyId===null));
assert.ok(saint.groups.every(x=>x.massAuthorization===false&&x.selected1962FormularyId===null));
assert.equal(saint.approvedFormularyCount,0);
const newman=cases.cases.find(x=>x.id==="P1-NEWMAN-2026");
assert.equal(newman.selectedFormularyId,null);
assert.equal(newman.chaplaincyEvidence.actualFormulary,"UNKNOWN");
assert.equal(newman.chaplaincyEvidence.actualLiturgicalOrations,"UNKNOWN");
assert.equal(newman.sungMassRule,"CUM_SANCTISSIMA_4_VERSUS_RG_111A_UNRESOLVED");
assert.ok(newman.otherHistoricCommemorationTrio.includes("denis-rusticus-eleutherius"));
assert.equal(cases.cases.find(x=>x.id==="P1-PIO-2026").optionalFestiveMassStatus,"BLOCKED_ON_THIS_DAY");
for(const x of cases.cases.filter(x=>x.id.includes("DOCTOR")))assert.match(x.effect,/NO_AUTOMATIC_1962_PROPER_REPLACEMENT/);
assert.equal(holds.openCount,holds.items.length);
assert.ok(holds.items.every(x=>x.blocksRuntimeApproval&&x.status==="OPEN"));
console.log("P1 research invariants PASS: "+law.rules.length+" legal rules, "+forms.forms.length+" indexed Commons, "+comm.trios.length+" source-addressed commemoration trios, "+saint.persons.length+" unique persons, "+saint.groups.length+" groups, "+holds.items.length+" explicit blockers; zero liturgical or reader permission inferred.");
