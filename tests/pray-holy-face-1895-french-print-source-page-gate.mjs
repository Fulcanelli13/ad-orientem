assert.equal(d.originalFrenchNovena.printedStart,112);
assert.equal(d.originalFrenchNovena.printedEnd,142);
assert.equal(d.originalFrenchNovena.numberOfDays,9);
assert.equal(d.originalFrenchNovena.commonAspirationsAndCollectPrintedPages.join(","),"115,142");
