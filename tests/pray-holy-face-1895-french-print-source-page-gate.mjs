let end=111;
for(let i=0;i<9;i++){
 const row=d.dayMap[i],app=NOVENA_HOLY_FACE_1887_B25.days[i];
 assert.equal(row.day,i+1);
 assert.equal(row.appEnglishTheme,app.theme.en);
 assert.equal(app.originalSourceDay,i+1);
 assert.ok(app.text.en.length>3000,"English full text must be preserved");
 assert.equal(app.text.fr,"","Do not promote uncollated French body on day "+(i+1));
 assert.equal(row.frenchBodyInReader,"NOT_ADMITTED");
 assert.equal(row.englishMatch,"THEME_AND_CROSS_LANGUAGE_SELECTED_PASSAGES_ONLY");
 assert.ok(row.printedPages.from>=end);
 assert.ok(row.printedPages.to>row.printedPages.from);
 assert.equal(row.pdfPageZeroBased.from,row.printedPages.from+6);
 assert.equal(row.pdfPageOneBased.from,row.printedPages.from+7);
 end=row.printedPages.to;
}
assert.equal(end,142);
