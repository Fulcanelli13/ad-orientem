import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_HOLY_FACE_1887_B25,HOLY_FACE_SOURCE_GATES_B25} from "../src/pray/holy-face-janvier-1887-b25.js";
const d=JSON.parse(readFileSync(new URL("../data/pray/research/pray-holy-face-original-french-1895-printed-9day-page-map.v1.json", import.meta.url),"utf8"));
assert.equal(d.schema,"ao.pray.holy-face.1895-original-french-print-witness.v1");
