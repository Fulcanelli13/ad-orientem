import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {existsSync,readFileSync} from "node:fs";
import {resolveApprovedPlaceMedia} from "../src/find/place-profiles.js";
const read=path=>JSON.parse(readFileSync(path,"utf8"));
const spec=read("data/geography/research/sacred-atlas-maria-luggau-frozen-selected-release-20261104.v1.json");
const geo=read("data/geography/seed-registry.v1.json");
const finder=read("data/geography/research/photo-finder-20261030/decisions.json").decisions;
const covers=read("data/geography/approved-place-media.v1.json");
const gallery=read("data/geography/approved-place-gallery.v1.json");
const proofPath="data/geography/research/sacred-atlas-maria-luggau-selected-cover-binary-evidence-20261104.v1.json";
assert.equal(spec.schema,"AO_SACRED_ATLAS_SELECTED_MARIA_LUGGAU_SAFE_RELEASE_V1");
assert.equal(spec.place_id,"place:AT:wallfahrtsbasilika-maria-schnee-luggau");
assert.equal(spec.pinned_original_sha1,"ca025cb7c0d5815ccb25b5f5570e8a57331103d7");
assert.equal(spec.pinned_original_bytes,11755745);
assert.equal(spec.pinned_source_description_rev_id,1190961558);
assert.equal(spec.photo_license,"CC-BY-SA-3.0-AT");
assert.equal(spec.photo_license_url,"https://creativecommons.org/licenses/by-sa/3.0/at/deed.en");
assert.equal(spec.flags.no_crop,true);
assert.equal(spec.release_authorized_from_metadata_alone,false);
assert.equal(finder[spec.place_id].files[0],spec.selected_file);
assert.equal(geo.places.find(x=>x.place_id===spec.place_id)?.photo_editorial?.cover_commons_file,spec.selected_file);
assert.equal(gallery.items.length,42);
assert.equal(new Set(covers.items.map(x=>x.place_id)).size,covers.items.length);
assert.equal(covers.items.filter(x=>x.place_id===spec.place_id).length,existsSync(proofPath)?1:0);
const previous=covers.items.filter(x=>x.place_id!==spec.place_id);
assert.equal(previous.length,379);
const contains=(x,buf)=>buf.includes(x);
if(!existsSync(proofPath)){
 assert.equal(covers.items.length,379,"No new covers before actual original-byte verification");
 assert.equal(resolveApprovedPlaceMedia(covers.items,spec.place_id),null);
 assert.ok(!process.argv.includes("--staged"),"Expected verified original release proof, not a plan");
 console.log("MARIA LUGGAU SOURCE RELEASE PREFLIGHT: selected original and original rights pinned; no asset or approval yet.");
}else{
 assert.equal(covers.items.length,380);
 const proof=read(proofPath);
 const rec=covers.items.find(x=>x.place_id===spec.place_id);
 assert.equal(proof.schema,"AO_SACRED_ATLAS_MARIA_LUGGAU_FROZEN_COVER_ORIGINAL_VERIFIED_V1");
 assert.equal(proof.place_id,spec.place_id);
 assert.equal(proof.sha1,spec.pinned_original_sha1);
 assert.equal(proof.source_description_revision,spec.pinned_source_description_rev_id);
 assert.equal(proof.source_original_bytes,spec.pinned_original_bytes);
 assert.equal(proof.source_rights_and_original_verified,true);
 assert.equal(proof.source_exact_place_verified,true);
 assert.equal(proof.selected_first_choice_preserved,true);
 assert.equal(proof.full_frame_no_crop_or_recolour,true);
 assert.equal(proof.prior_approved_covers_unchanged,true);
 assert.equal(proof.gallery_unchanged,true);
 assert.equal(proof.production_verified,false,"PR staging is not main publication");
 assert.equal(rec.source_sha1,spec.pinned_original_sha1);
 assert.equal(rec.license,"CC-BY-SA-3.0-AT");
 assert.equal(rec.license_url,spec.photo_license_url);
 assert.equal(rec.credit,"Johann Jaritz");
 assert.equal(rec.source_place_ref,"PHOTO_FINDER_2026-10-30_R1");
 assert.equal(rec.status,"APPROVED");
 assert.ok(rec.rights_verified&&rec.subject_verified&&rec.crop_reviewed);
 assert.ok(rec.alt_en&&rec.alt_fr&&rec.changes_en&&rec.changes_fr);
 assert.match(rec.asset_path,/^assets\/approved\/place-media\/pf-[a-f0-9]{22}\.webp$/);
 assert.equal(rec.asset_path,proof.asset_path);
 assert.equal(rec.derivative_sha256,proof.derivative_sha256);
 const asset=readFileSync(rec.asset_path);
 assert.equal(asset.toString("ascii",0,4),"RIFF");
 assert.equal(asset.toString("ascii",8,12),"WEBP");
 assert.ok(asset.length>3000);
 assert.equal(createHash("sha256").update(asset).digest("hex"),rec.derivative_sha256);
 assert.equal(rec.width,proof.derivative_dimensions[0]);
 assert.equal(rec.height,proof.derivative_dimensions[1]);
 const visible=resolveApprovedPlaceMedia(covers.items,spec.place_id);
 assert.ok(visible,"Only this exact regional-licence original should render as an approved Place photo");
 assert.equal(visible.asset_path,rec.asset_path);
 assert.equal(visible.license_url,spec.photo_license_url);
 const other={...rec,place_id:"place:AT:not-our-maria-luggau"};
 assert.equal(resolveApprovedPlaceMedia([other],other.place_id),null,"Regional exception must not transfer to another Place");
 const changedSource={...rec,source_sha1:"0".repeat(40)};
 assert.equal(resolveApprovedPlaceMedia([changedSource],spec.place_id),null,"Regional exception must be SHA-1 locked");
 const changedLicense={...rec,license_url:"https://creativecommons.org/licenses/by-sa/3.0/de/deed.en"};
 assert.equal(resolveApprovedPlaceMedia([changedLicense],spec.place_id),null,"No generic national-licence acceptance");
 console.log("MARIA LUGGAU ORIGINAL VERIFIED: exact user choice, original bytes, regional 3.0 AT licence, one visible EN/FR Place cover, 379 previous records preserved.");
}
