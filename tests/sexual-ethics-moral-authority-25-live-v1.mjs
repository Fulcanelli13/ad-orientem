import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {CSE_DEBATE_MAP,CSE_DEBATE_FIELDS} from "../src/learn/sexual-ethics-data/debates.js";
import {CSE_QUESTION_MAP,CSE_SOURCE_MAP} from "../src/learn/sexual-ethics-data/index.js";
import {paragraphRefsFor} from "../src/learn/sexual-ethics-data/provenance.js";
const ledger=JSON.parse(readFileSync("data/learn/sexual-ethics-moral-authority-25-bilingual-reader-20261009.v1.json","utf8"));
assert.equal(ledger.summary.debates_touched,10);
assert.equal(ledger.summary.live_stage_pairs_english_and_french_corrected,25);
assert.equal(ledger.summary.original_opponent_position_stage_checks,9);
assert.equal(ledger.summary.independent_french_approvals,0);
assert.equal(ledger.summary.independent_theology_approvals,0);
assert.equal(ledger.summary.full_eight_stage_certifications,0);
assert.equal(ledger.records.length,25);
const target=["CSE007","CSE008","CSE010","CSE012","CSE013","CSE014","CSE016","CSE018","CSE020","CSE021"];
assert.deepEqual([...new Set(ledger.records.map(x=>x.id))].sort(),target);
const seen=new Set(),types={};
for(const row of ledger.records){
 const key=row.id+"."+row.stage;
 assert.ok(!seen.has(key),"Repeated live stage "+key);seen.add(key);
 assert.ok(CSE_DEBATE_FIELDS.includes(row.stage));
 assert.ok(CSE_QUESTION_MAP[row.id]);
 assert.ok(CSE_DEBATE_MAP[row.id]&&CSE_DEBATE_MAP[row.id][row.stage]);
 const [en,fr]=CSE_DEBATE_MAP[row.id][row.stage];
 assert.ok(en.length>75&&fr.length>75,key+" stage pair too brief");
 assert.ok(paragraphRefsFor(CSE_QUESTION_MAP[row.id],"debate",row.stage).some(([id])=>id===row.source_id),key+" no live source");
 assert.equal(row.source_url,CSE_SOURCE_MAP[row.source_id].canonical_url,key+" source registry drift");
 assert.ok(row.original_locator.length>15,key+" imprecise original locator");
 assert.equal(row.bilingual_reader_edit_confirmed,true);
 assert.equal(row.source_claim_scope_checked,true);
 for(const gate of ["full_stage_claim_by_claim_collation_complete","opponent_full_original_book_independently_collated","independent_french_text_certified","independent_theological_approval","final_eight_stage_case_certified"])assert.equal(row[gate],false,key+" false approval");
 types[row.scope_verdict]=(types[row.scope_verdict]||0)+1;
}
assert.deepEqual(types,ledger.summary.source_scope_counts);
assert.match(CSE_DEBATE_MAP.CSE014.opposition[0],/Curran/);
assert.match(CSE_DEBATE_MAP.CSE014.opposition[0],/non-infallible/);
