import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {NOVENA_HOLY_FACE_1887_B25,HOLY_FACE_SOURCE_GATES_B25} from "../src/pray/holy-face-janvier-1887-b25.js";
const research=name=>JSON.parse(readFileSync(new URL("../data/pray/research/"+name,import.meta.url),"utf8"));
const day=research("pray-holy-face-1895-fr-day07-transcribed-first-pass.v1.json");
const day1=research("pray-holy-face-1895-fr-day01-transcribed-proofread.v1.json");
const sourceMap=research("pray-holy-face-original-french-1895-printed-9day-page-map.v1.json");
assert.equal(day.schema,"ao.pray.holy-face.french-1895-day-transcription.v1");
assert.equal(day.canonicalId,NOVENA_HOLY_FACE_1887_B25.id);
assert.equal(day.day,7);
assert.deepEqual(day.printedPages,[133,134,135,136]);
assert.deepEqual(day.pdfZeroBasedPages,[139,140,141,142]);
assert.equal(day.dayHeading,"La sainte Face sur la route du Calvaire");
assert.equal(sourceMap.dayMap[6].printedPages.from,133);
assert.equal(sourceMap.dayMap[6].printedPages.to,136);
assert.deepEqual(day.dayComponents.map(x=>x.key),["opening_reference","narrative","point1","point2","point3","act","virtue","bouquet","conclusion_reference"]);
const originals=day.dayComponents.filter(x=>typeof x.text==="string");
const refs=day.dayComponents.filter(x=>x.text===null);
assert.equal(originals.length,7);
assert.equal(refs.length,2);
assert.ok(originals.every(x=>x.text.length>100&&x.pages.every(p=>p>=133&&p<=136)));
assert.ok(originals.reduce((n,x)=>n+x.text.length,0)>3200);
assert.deepEqual(refs.map(x=>x.refDay),[1,1]);
assert.equal(refs[0].refSection,"opening");
assert.deepEqual(refs[1].refSections,["prayers","collect"]);
for(const key of ["opening","prayers","collect"]) assert.ok(day1.dayComponents.some(x=>x.key===key&&x.text.length>100));
assert.match(day.dayComponents[1].text,/Voyez Jésus gravir la montagne de son sacrifice/);
assert.match(day.dayComponents[2].text,/I\. Réparation offerte/);
assert.match(day.dayComponents[2].text,/elle l’essuie et le soulage/);
assert.match(day.dayComponents[3].text,/II\. Véronique notre modèle/);
assert.match(day.dayComponents[3].text,/Sa Majesté est particulièrement insultée et conspuée/);
assert.match(day.dayComponents[4].text,/III\. Bonne inspiration à suivre/);
assert.match(day.dayComponents[4].text,/J’irai à Vous, ô très doux Sauveur/);
assert.match(day.dayComponents[5].text,/Acte de charité\. — Aimez Jésus/);
assert.match(day.dayComponents[6].text,/Que le zèle de la Réparation vous enflamme/);
assert.match(day.dayComponents[7].text,/Il me faut des Véroniques/);
assert.equal(day.comparison.variants.length,9);
assert.deepEqual(day.comparison.englishParagraphIndicesByFrenchSection.point1,[2]);
assert.deepEqual(day.comparison.englishParagraphIndicesByFrenchSection.conclusion_reference,[8,9]);
const witness=NOVENA_HOLY_FACE_1887_B25.days[6].text.en;
assert.match(witness,/she wipes it and raises it/);
assert.match(witness,/Love the Holy Face and have compassion/);
assert.equal(day.independentSecondProofComplete,false);
assert.equal(day.release,"RESEARCH_ONLY_NOT_BOUND_TO_PUBLIC_READER");
assert.equal(day.frenchBodyInCanonicalReader,"EMPTY");
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every((x,i)=>x.originalSourceDay===i+1&&x.text.fr===""));
assert.ok(NOVENA_HOLY_FACE_1887_B25.days.every(x=>x.text.en.length>3000));
assert.equal(HOLY_FACE_SOURCE_GATES_B25.verifiedFrenchPrayerBody,false);
assert.equal(HOLY_FACE_SOURCE_GATES_B25.originalPrintPhotoCollated,false);
console.log("PASS: Day VII 1895 French Veronica 7 source sections and 2 historical prayer references; nine variant holds; EN 9 intact, FR 9 unpublished");
