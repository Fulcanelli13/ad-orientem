// Generates src/mass/reader-canonical-icon-set.js from the canonical icon set
// JSON, so the browser runtime and the data never drift.
//   node tools/mass/build-canonical-icon-module.mjs          (write)
//   node tools/mass/build-canonical-icon-module.mjs --check  (exit 1 if stale)
import { readFileSync, writeFileSync } from "node:fs";

const SRC = new URL("../../data/presentation/mass-icon-canonical-set-20261021.v1.json", import.meta.url);
const OUT = new URL("../../src/mass/reader-canonical-icon-set.js", import.meta.url);

export function renderCanonicalIconModule(set = JSON.parse(readFileSync(SRC, "utf8"))) {
  const meanings = set.meanings.map(m => ({ meaningId: m.meaningId, lane: m.lane, assetId: m.assetId ?? null, path: m.path ?? null, userName: m.userName ?? null }));
  const runtime = {
    schema: set.schema, date: set.date,
    meanings,
    gaps: set.gaps.map(g => g.meaningId),
    stationMap: set.stationMap,
    actionLabelMap: set.actionLabelMap,
    actionCueOverrides: set.actionCueOverrides,
    lowActionByCue: set.lowActionByCue,
    postureMap: set.postureMap,
    faithfulGestureMap: { byMatrixIconKey: set.faithfulGestureMap.byMatrixIconKey, byType: set.faithfulGestureMap.byType, byCue: set.faithfulGestureMap.byCue },
    voiceMap: Object.fromEntries(Object.entries(set.voiceMap).filter(([k]) => k !== "rules")),
    voiceCueOverrides: set.voiceCueOverrides,
    ultraMasterPriestChantCues: set.ultraMasterPriestChantCues,
    priestIntonationEndCues: set.priestIntonationEndCues,
    voiceOwnerAdjudications: set.voiceOwnerAdjudications,
    scholaOwnedNotPriestChantCues: set.scholaOwnedNotPriestChantCues,
    solemnMinisterReadingCues: set.solemnMinisterReadingCues,
    otherLanes: set.otherLanes,
  };
  const assets = meanings.filter(m => m.path).map(m =>
    `  ${JSON.stringify("canon:" + m.meaningId)}:new URL(${JSON.stringify("../../" + m.path)},import.meta.url).href,`);
  return [
    "// GENERATED by tools/mass/build-canonical-icon-module.mjs from",
    "// data/presentation/mass-icon-canonical-set-20261021.v1.json. Do not edit by hand.",
    "const deepFreeze=o=>{if(o&&typeof o===\"object\"&&!Object.isFrozen(o)){Object.freeze(o);for(const v of Object.values(o))deepFreeze(v);}return o;};",
    `export const CANONICAL_ICON_SET=deepFreeze(${JSON.stringify(runtime)});`,
    "export const CANONICAL_ICON_ASSETS=Object.freeze({",
    ...assets,
    "});",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = renderCanonicalIconModule();
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8");
    if (current !== text) { console.error("reader-canonical-icon-set.js is stale: run node tools/mass/build-canonical-icon-module.mjs"); process.exit(1); }
    console.log("reader-canonical-icon-set.js is current");
  } else {
    writeFileSync(OUT, text);
    console.log("wrote", OUT.pathname);
  }
}
