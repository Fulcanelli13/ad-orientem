const htmlEscape = value => String(value??"").replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
export function approvedClassIHeroForDate(date, observedPrincipalId) {
  const record = APPROVED_CLASS_I_2026.find(row => row.date === date);
  return record?.principalId && record.principalId === observedPrincipalId ? record : null;
}
export function approvedClassIHeroMarkup(date, observedPrincipalId, french = false) {
  const record = approvedClassIHeroForDate(date, observedPrincipalId);
  if (!record) return "";
  const selected = french ? "Peinture choisie pour cette fête" : "Approved feast-day painting";
  const source = french ? "Source de l'œuvre" : "Artwork source";
  const pending = french ? "Reproduction en attente de validation des droits" : "Image on hold pending reuse clearance";
  const image = record.image ? `<img class="aoClassIImage" src="${htmlEscape(record.image)}" alt="${htmlEscape(record.title + ' — ' + record.artist)}" loading="lazy" decoding="async" referrerpolicy="no-referrer">` : `<div class="aoClassIHeld" role="note">${htmlEscape(pending)}</div>`;
  return `<figure class="aoClassIApprovedHero" data-ao-class-i-date="${htmlEscape(date)}" data-ao-artwork-id="${htmlEscape(record.artworkId)}" data-ao-image-status="${htmlEscape(record.imagePublicationStatus)}">
    ${image}
    <figcaption><small>${htmlEscape(selected)}</small><strong>${htmlEscape(record.title)}</strong><span>${htmlEscape(record.artist)}</span><a target="_blank" rel="noopener noreferrer" href="${htmlEscape(record.source)}">${htmlEscape(source)} ↗</a></figcaption>
  </figure>`;
}
