 throw Error("Psalter source alignment table incomplete");
export function psalterIdentityVerse(reference,from,to){
 if(reference?.book!=="Psalms"||reference?.verseStart!==reference?.verseEnd)return null;
 if(!(["cpdv-2009","dr-challoner"].includes(from)&&["cpdv-2009","dr-challoner"].includes(to)&&from!==to))return null;
 const maximum=PSALTER_IDENTITY_VERSE_COUNTS[reference.chapter];
 if(!Number.isSafeInteger(maximum)||reference.verseStart<1||reference.verseStart>maximum)return null;
 return Object.freeze({book:"Psalms",chapter:reference.chapter,
  verseStart:reference.verseStart,verseEnd:reference.verseStart});
}
