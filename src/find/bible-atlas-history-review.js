const escapeHTML=value=>String(value??"").replace(/[&<>"']/g,char=>({
 "&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"
}[char]));
export function atlasHistoricalNameReview(stop,lang="en"){
 const key=stop?.geo?.key,era=stop?.era;
 if(!key||!era)return "";
 const note=ATLAS_HISTORY_REVIEW_NOTES.find(x=>x.key===key&&x.era===era);
 if(!note)return "";
 const french=lang==="fr",label=french?"Nom historique":"Historical name";
 const text=french?note.fr:note.en;
 // Links open separately and never change the selection or Scripture reader.
 const links=[{label:"Pleiades",url:note.pleiades},...note.sources.map((url,i)=>({
  label:french?(i===0?"Source historique":"Autre source"):(i===0?"Historical source":"Further source"),url
 }))];
 return '<details class="aoBibleAtlasHistoryNote" data-bible-history-note="'+escapeHTML(key)+
  '" data-bible-history-era="'+escapeHTML(era)+'"><summary>'+escapeHTML(label)+
  '</summary><p>'+escapeHTML(text)+'</p><div class="aoBibleAtlasHistorySources">'+
  links.map(l=>'<a href="'+escapeHTML(l.url)+'" target="_blank" rel="noopener noreferrer">'+
  escapeHTML(l.label)+' ↗</a>').join('')+'</div></details>';
}
