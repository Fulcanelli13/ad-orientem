export function angelusGuideSections(form,language="en"){
 const k=form==="regina"?"regina":"angelus",lang=language==="fr"?"fr":"en";
 return ANGELUS_GUIDE_V1[k].map(x=>({heading:x.heading[lang],body:x.body[lang],source:x.source}));
}
export function resolveAngelusPosture({form="angelus",weekday=1,saturdayAfterVespers=false}={}){
 const day=Number(weekday),stand=form==="regina"||day===0||(day===6&&saturdayAfterVespers===true);
 return {stand,posture:stand?"stand":"kneel",traditionalCustom:true};
}
export function splitAngelusVersicleResponse(text){
 const lines=String(text??"").replace(/\r/g,"").split("\n").map(x=>x.trim()).filter(Boolean);
 if(lines.length!==2)return [];
 const re=[/^(?:℣|V)\.?\s*/i,/^(?:℟|R)\.?\s*/i];
 if(!re.every((x,i)=>x.test(lines[i])))return [];
 return lines.map((line,i)=>({role:i===0?"leader":"response",text:line.replace(re[i],"").trim()}));
}
