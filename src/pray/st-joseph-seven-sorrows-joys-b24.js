export const JOSEPH_SEVEN_STEP_COUNT_B24=8;
export function josephSevenStepAt(index,canonicalPrayers=null){
 if(!Number.isInteger(index)||index<0||index>=JOSEPH_SEVEN_STEP_COUNT_B24)return null;
 if(index===7)return Object.freeze({type:"closing",index,closure:JOSEPH_SEVEN_CLOSURE_B24});
 const prayer=JOSEPH_SEVEN_PRAYERS_B24[index];
 const repetitions=prayer.prayerIds.map(id=>{
  const record=canonicalPrayers?.[id];
  return record?.id===id&&record.en&&record.fr&&record.la
   ? Object.freeze({id,titleEn:record.title,titleFr:record.titleFr||record.title,en:record.en,fr:record.fr,la:record.la})
   : null;
 });
 if(repetitions.some(x=>!x))return null;
 return Object.freeze({type:"pair",index,prayer,repetitions:Object.freeze(repetitions)});
}
export function josephSevenReleaseAllowed({sourceLanguage="en",prayerIndex=0,canonicalPrayers=null}={}){
 if(!["en","fr"].includes(sourceLanguage))return false;
 return josephSevenStepAt(prayerIndex,canonicalPrayers)!==null;
}
