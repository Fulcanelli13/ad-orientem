export function finalCurated65IconKeys(state={}){
 const currentCue=String(state.cueId??"");
 const station=token(state.priestPosition?.station??state.priestPosition?.value);
 const facing=token(state.priestPosition?.facing);
 const actionCue=String(state.priestAction?.cueId??currentCue);
 const gestureCue=String(state.gesture?.cueId??currentCue);
 const voiceCue=String(state.priestVoice?.cueId??currentCue);
 const form=token(state.form??state.celebrationForm);
 const inSung=["MISSA_CANTATA_SIMPLE","MISSA_CANTATA_INCENSE","SOLEMN"].includes(form);
 const number=Number(currentCue.match(/^AO\.SM\.C(\d{4})$/)?.[1]??NaN);
 // Solemn Mass: the Epistle is sung by the subdeacon, the Gospel by
 // the deacon; do not display the celebrant chanting merely because the
 // public text advances. Those minister actors have independent cues.
 const sungMinisterReading=form==="SOLEMN" &&
   ((number>=75&&number<=78)||(number>=82&&number<=88));
 // A priest's voice cue is event-scoped: never persist the previous
 // chant into a server reply, a Schola phrase, or a silent priest action.
 const currentOwnedVoice=voiceCue===currentCue && state.priestVoice!=null;
 const candidateVoice=currentOwnedVoice?FINAL_65_CUE_ICON_KEYS.priestVoice[voiceCue]??null:null;
 const sourceConfirmedChant=inSung&&!sungMinisterReading&&ULTRA_PRIEST_CHANT.has(currentCue);
 const priestVoiceKey=SCHOLA_NO_PRIEST_CHANT.has(currentCue)?null:
   sourceConfirmedChant?"final_ao_chant":
   candidateVoice==="final_ao_chant"?(inSung&&!sungMinisterReading?candidateVoice:null):candidateVoice;
 const sourceAction=String(state.priestAction?.label??state.priestAction?.action??"").trim().toUpperCase();
 const rubricAction=EXACT_PRIEST_RUBRIC_ACTION_ICON_KEYS[currentCue];
 const approvedRubricKey=rubricAction&&actionCue===currentCue&&sourceAction===rubricAction.action
   ?rubricAction.key:null;
 const posture=token(state.posture?.value??state.posture?.label);
 const facesPeople=facing==="PEOPLE"||facing==="PEOPLE_DURING_TURN";
 return Object.freeze({
  postureIconKey:POSTURES[posture]??null,
  gestureIconKey:state.gesture?FINAL_65_CUE_ICON_KEYS.faithfulGesture[gestureCue]??null:null,
  responseIconKey:state.response?"final_response":null,
  priestVoiceIconKey:priestVoiceKey,
  scholaIconKey:state.schola?"final_schola":null,
  priestPositionIconKey:station==="FOOT_CENTER"?null:(facesPeople?"final_new_priest_facing":FINAL_65_PRIEST_POSITION_ICON_KEYS[station]??null),
  priestActionIconKey:state.priestAction?(FINAL_65_CUE_ICON_KEYS.priestAction[actionCue]??approvedRubricKey??null):null,
  bellIconKey:state.bell?"bells":null,
 });
}
