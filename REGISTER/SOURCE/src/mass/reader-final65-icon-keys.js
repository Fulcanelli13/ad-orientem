  "AO.SM.C0068":Object.freeze({action:"SIGNS HIMSELF",key:"final_ao_sign_of_cross_vector"}),
  "AO.SM.C0079":Object.freeze({action:"PROFOUND BOW",key:"final_ao_adoration"}),
